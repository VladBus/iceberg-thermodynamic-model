! ==============================================================================
! Модуль: main (Главная программа)
! Назначение: Главный оркестратор гидродинамической и термодинамической модели.
! Физика: Реализует метод расщепления (splitting method) по временным масштабам:
!   - Бароклинные (медленные) процессы: шаг dt = 3600 с (1 час).
!   - Баротропные (быстрые) процессы: шаг dt1 = 120 с (2 мин), mm3=30 микрошагов.
!   - Термодинамика: шаг dt = 3600 с (тот же, что и бароклинный).
!   - Динамика льда: mm3=30 подциклов на каждый бароклинный шаг.
!
!   Суточный цикл (mm2 = 12 термодинамических шагов по 3600 с = 12 часов):
!     1. Временная интерполяция метеоданных (линейная: tx→tx1, dpx→dpx1).
!     2. Термодинамика heat() + перераспределение категорий redis().
!     3. Динамика льда (barotropic подциклы, mm3=30 шагов по dt1=120 с):
!        a. Внутренние напряжения льда (stress).
!        b. Кориолис + ветер + давление + трение + напряжения → U/V.
!     4. Адвекция сплошности и массы льда (adv2d по категориям).
!     5. Вертикальная скорость W (уравнение неразрывности).
!     6. Адвекция T/S в океане (advs/advt).
!     7. Конвективная коррекция (conv_adj).
!     8. 3D-импульс (block 200: Coriolis + baroclinic + DPX + Laplacian).
!     9. Вертикальная вязкость (block 210: Thomas algorithm).
!    10. Баротропный расчёт (shal: shallow water).
!    11. Возврат баротропной компоненты (block 280: обнуление вертикального среднего).
!
! Ответственность: Инициализация полей, контроль временных шагов, вызов
!                  вспомогательных модулей в строгой физической последовательности,
!                  управление процессами ввода (ERA5) и вывода (NetCDF) данных.
! ==============================================================================

program main
    use param
    use advection_2d
    use thermodynamics
    use wind_forcing
    use ice_stress
    use grid_masks
    use ice_deform
    use ice_redis
    use smooth_filter
    use advection_3d_s
    use advection_3d_t
    use tide_forcing
    use shallow_water, only: shal, jjq, euu
    use grid_coupling
    use netcdf_output
    use initial_conditions
    use netcdf_input
    use equation_of_state
    use convective_adjustment
    use run_config

    implicit none

    ! --- Локальные переменные ---
    ! Временные переменные (модельное время)
    real :: god, mes, den, hour          ! Год, месяц, день, час (текущие в модели)
    ! Флаги управления
    integer :: kl1, nom                  ! kl1=1 включает термодинамику (требует patm>0)
    ! Параметры временной сетки
    integer :: mm1, mm2, mm3, mm4, mm5, kkb
    real :: dt1, dt, dx                  ! Временные шаги [с] и пространственный шаг [см]
    ! Физические константы
    real :: ah, aht, ahs, g, roc, cp     ! Коэффициенты диффузии, g, rho0, Cp
    ! Производные константы (вычисляются один раз для скорости)
    real :: c1, c2, c3, c4, c5, c8, c9, c10, c11, c12, c15, c16, c17
    ! Рабочие переменные для вычислений в циклах
    real :: sas, a, b, a1, b1, a2, b2, a3, b3, a4, b4, cc_val
    real :: hht, uij, vij, fix, fiy, aa, au, av, sl, du, ff, ff1
    real :: dzz, dzzz, dzz1, dz1z, bb, sum, sum1, asa1, asa, ymm, hh1, hh2
    real :: tt0, ss0, tt1, ss1, tt2, ss2, tt3, ss3, tt4, ss4, yyy, uu, vv
    real :: ri2j, rij, ri2j2, rij2, slapu, slapv, auu, avv
    real :: ck1, ck2, ww1, ww2, ww

    ! Счетчики циклов
    integer :: mmmm, lll, kkk, iii, jjj  ! Год, месяц, день, шаг в сутках, баротропный шаг
    integer :: i, j, k, i1, i2, j1, j2, k1, k2, ki, kk, ki1, ki2
    integer :: ix1, ix2, iy1, iy2
    integer :: nday, nday1, ikkk, ios    ! Счетчики дней и I/O статус

    ! --- ERA5 snowfall diagnostics: monthly domain-mean sfal (Stage 7.1) ---
    ! Доменная средняя для диагностики/валидации. НЕ используется для форсинга.
    real :: sfal_accum(12)               ! Накопленная сумма дневных средних [м/с]
    integer :: sfal_count(12)            ! Число дней в накоплении для каждого месяца

    ! Энергетические диагностики
    real :: ecc = 0.0, ess = 0.0         ! Предыдущая и текущая кинетическая энергия
    character(len=20) :: nam_file        ! Имя файла начального льда (1_1.ice ... 1_5.ice)
    character(len=256) :: day_file       ! Имя суточного NetCDF файл
    character(len=64) :: run_id_arg      ! Аргумент командной строки: run_id
    character(len=256) :: era5_arg       ! Аргумент командной строки: путь ERA5 файла
    real(8) :: start_sec                 ! Время первого ERA5-среза в секундах с эпохи
    integer :: nperday                   ! Число ERA5-срезов в сутки
    integer :: narg, arglen              ! Количество и длина аргументов командной строки

    print *, "================================================="
    print *, "   AARI Iceberg Thermodynamic & Dynamics Model   "
    print *, "================================================="

    ! --- Конфигурация прогона (Stage 6.2) ---
    ! Аргументы командной строки (fpm run -- <run_id> [era5_file]):
    !   arg1: run_id (обязателен в новом workflow; по умолчанию исторический).
    !   arg2: путь ERA5 input (необязателен; по умолчанию из param).
    run_id_arg = trim(run_id)
    era5_arg = ''
    narg = command_argument_count()
    if (narg .ge. 1) then
        call get_command_argument(1, run_id_arg, arglen)
    end if
    if (narg .ge. 2) then
        call get_command_argument(2, era5_arg, arglen)
    end if
    call setup_run_dirs(trim(run_id_arg), trim(era5_arg))

    ! --- Инициализация времени и параметров ---
    god = 1998.0        ! Начальный год моделирования (Гринвич)
    mes = 4.0           ! Начальный месяц моделирования (апрель)
    den = 16.0          ! Начальный день месяца
    hour = 0.0          ! Начальный час суток

    nat(1) = int(god)
    nat(2) = int(mes)
    nat(3) = int(den)
    nat(4) = int(hour)

    kl1 = 1             ! Флаг использования термодинамики (1 - да, требует patm>0)
    nom = 1             ! Идентификатор чтения начальных данных
    ! Временный переключатель для отладки ERA5 input (этап 2/3).
    forcing_mode = forcing_mode_era5

    ! ========================================================================
    !   ВРЕМЕННЫЕ И ПРОСТРАНСТВЕННЫЕ ПАРАМЕТРЫ СЕТКИ
    ! ========================================================================
    dt1 = 120.0         ! [с] Шаг баротропной моды (2 минуты).
    !   CFL для баротропных гравитационных волн: dt1 < dx/√(g·H).
    !   При dx=13.89 км, H=500 м: √(gH)≈700 м/с, dx/√(gH)≈20 с.
    !   dt1=120 с превышает CFL для глубоководных ячеек —
    !   компенсируется диффузией и ограничением шагов.
    dt = 3600.0         ! [с] Шаг бароклинной моды и термодинамики (1 час).
    !   CFL для бароклинных волн: dt < dx/c_bc, c_bc~1-2 м/с.
    !   dx=13890 м, c_bc=1.5 м/с → CFL≈9260 с > 3600 с — безопасно.
    mm1 = 91            ! Число модельных дней (Q1 2020: 91 день = 31+28+31).
    mm2 = 12            ! Число термодинамических шагов в сутках (12 × 3600 с = 12 ч).
    mm3 = 30            ! Число баротропных микрошагов на бароклинный (30 × 120 с = 1 ч).
    mm4 = 1             ! Число расчётных месяцев (1 для Q1 2020).
    mm5 = 1             ! Число расчётных лет.
    dx = 1389000.0      ! [см] Пространственный шаг сетки = 13.89 км.
    !   В WGS 84 / IBCAO Polar Stereographic проекции (EPSG:3996) dx ~ dy ~ 13.89 км.
    kkb = 1             ! Начальный индекс метеoданных
    ikkk = 0            ! Счётчик диагностических записей
    nday = 0            ! Счётчик дней внутри месяца
    nday1 = 0           ! Общий счётчик дней модельного времени

    ! ========================================================================
    !   ФИЗИЧЕСКИЕ КОНСТАНТЫ МОДЕЛИ
    ! ========================================================================
    ! Единицы: всё в CGS для гидродинамики.
    ah = 7.5e6          ! [см²/с] Коэффициент горизонтальной турбулентной диффузии импульса.
    !   Граница Рейнольдса: Re = U·dx/Ah ~ 10·1.4e6/7.5e6 ~ 19.
    !   Значение характерно для региональных моделей.
    aht = 7.5e6         ! [см²/с] Коэффициент горизонтальной диффузии тепла (= Ah).
    ahs = 7.5e6         ! [см²/с] Коэффициент горизонтальной диффузии солености (= Ah).
    g = 981.0           ! [см/с²] Ускорение силы тяжести (CGS).
    roc = 1.0           ! [г/см³] Базовая плотность воды для расчёта аномалий.
    !   Используется как ρ₀ в C1 = g/ρ₀.
    cp = 0.958          ! [безразм.] Эмпирический коэффициент теплоёмкости (legacy).

    ! ========================================================================
    !   ВЫЧИСЛЕННЫЕ ВСПОМОГАТЕЛЬНЫЕ КОНСТАНТЫ (однократный расчёт)
    ! ========================================================================
    c1 = g/roc                      ! [см/с² / (г/см³)] = г·см⁻²·с⁻² — "g/ρ₀"
    !   Используется в block 200: Coriolis и baroclinic.
    !   c1 = 981/1 = 981.
    c2 = dt/dx                      ! [с/см] Число Куранта для бароклинного шага.
    !   c2 = 3600/1389000 ≈ 2.59e-3.
    c3 = ah/(dx*dx)                 ! [см²·с⁻¹/см²] = [1/с] Коэффициент Laplacian-вязкости.
    !   c3 = 7.5e6/(1.389e6)² ≈ 3.89e-6 1/с.
    c4 = aht/(dx*dx)*dt             ! [безразм.] Коэффициент диффузии тепла.
    c5 = ahs/(dx*dx)*dt             ! [безразм.] Коэффициент диффузии соли.
    c8 = 0.25/dx                    ! [1/см] Фактор 1/(4·dx) для баротропно-бароклинного
    !   интеграла плотности в block 200.
    !   c8 = 0.25/1389000 ≈ 1.80e-7 1/см.
    c9 = 0.5/dx                     ! [1/см] Фактор 1/(2·dx) для градиентов W-блока.
    c10 = dt1/dx                    ! [с/см] Число Куранта для баротропного шага.
    !   c10 = 120/1389000 ≈ 8.64e-5.
    c11 = g/dx*0.005                ! [см/с²/см] = [1/с²] Градиент давления с масштабированием.
    !   0.005 = эмпирический коэффициент.
    !   c11 = 981/1389000 × 0.005 ≈ 3.53e-6.
    c12 = 1.0/dx                    ! [1/см] Обратный шаг сетки.
    c15 = cos(15.0/57.3)            ! [безразм.] cos(15°) ≈ 0.966 — поворот напряжений
    !   (Кориолис + 15° поправка к оси).
    c16 = sin(15.0/57.3)            ! [безразм.] sin(15°) ≈ 0.259.
    c17 = 0.0055*1000.0/910.0       ! [безразм.] Коэффициент трения вода-лёд.
    !   0.0055 — drag coefficient, 1000/910 = ρ_water/ρ_ice.
    !   c17 ≈ 0.00604.

    ! ========================================================================
    !   ЧТЕНИЕ ПРИЛИВНЫХ ГАРМОНИК
    ! ========================================================================
    ! Файл GRM2 содержит амплитуды и фазы приливных гармоник на гидросетке.
    ! Формат: 3 блока по 133/105/133 чисел (amp1, faz1, amp2, faz2, amp3, faz3).
    ! При отсутствии файла используется нулевая инициализация (все амплитуды = 0).
    amp1 = 0.0
    amp2 = 0.0
    amp3 = 0.0
    faz1 = 0.0
    faz2 = 0.0
    faz3 = 0.0
    open (3, file='GRM2', status='old', iostat=ios)
    if (ios .eq. 0) then
        read (3, *) (amp1(i, 1), i=1, 133)
        read (3, *) (faz1(i, 1), i=1, 133)
        read (3, *) (amp2(i, 1), i=1, 105)
        read (3, *) (faz2(i, 1), i=1, 105)
        read (3, *) (amp3(i, 1), i=1, 133)
        read (3, *) (faz3(i, 1), i=1, 133)
        close (3)
    else
        print *, "WARNING: GRM2 missing, using defaults"
    end if

    ! ========================================================================
    !   ЧАСТОТЫ ПРИЛИВНЫХ ГАРМОНИК
    ! ========================================================================
    ! 4 основные гармоники (M2, S2, K1, O1) [°/ч]:
    qq(1) = 28.9841042   ! M2 — главная полусуточная лунная (период ≈ 12.42 ч)
    qq(2) = 30.0         ! S2 — главная полусуточная солнечная (период = 12.00 ч)
    qq(3) = 15.041069    ! K1 — лунно-солнечная суточная (период ≈ 23.93 ч)
    qq(4) = 13.943036    ! O1 — основная суточная лунная (период ≈ 25.82 ч)

    call datte()

    ! Перевод угловых частот из °/ч в радианы на баротропный шаг dt1:
    !   q[k] = qq[k] × (dt1/3600) × (π/180) = qq[k] × dt1 / 3600 / 57.2958
    q(1:4) = qq(1:4)*dt1/3600.0/57.2958

    ! --- Вызов модулей инициализации сетки и геометрии ---
    print *, "Calling grid_coupling..."
    call coup1()

    print *, "Calling grid_masks (IKUV)..."
    call ikuv()

    ! --- Чтение метеоданных и стартовых полей льда ---
    p = 0.0
    open (1, file='DAV4_5.98', status='old', iostat=ios)
    if (ios .eq. 0) then
        read (1, *) mm1
        do j = 1, mm1 + 1
            read (1, *)
            do i = 1, 1420
                read (1, *) a, a, a, p(i, j)
            end do
        end do
        close (1)
    end if

    ! Чтение начальных толщин категорий льда
    an1 = 0.0
    wice1 = 0.0
    hsnow = 0.0
    u = 0.0
    v = 0.0
    u0 = 0.0
    v0 = 0.0
    exx = 0.0
    eyy = 0.0
    exy = 0.0
    epr = 0.0
    sxx = 0.0
    syy = 0.0
    sxy = 0.0
    do k = 2, 6
        write (nam_file, '(A,I1,A)') '1_', k - 1, '.ice'
        open (1, file=trim(nam_file), status='old', iostat=ios)
        if (ios .eq. 0) then
            do i = 1, is1
                read (1, *) (an1(i, j, k), j=1, js1)
            end do
            close (1)
        end if
    end do

    ! Первичная очистка и нормировка ледовых массивов
    do j = 1, js1
        do i = 1, is1
            sas = 0.0
            do k = 2, ngr1
                if (abs(an1(i, j, k) - 9.99) .lt. 1e-8) an1(i, j, k) = 0.0
                if (an1(i, j, k) .ge. 1.0) an1(i, j, k) = 1.0
                sas = sas + an1(i, j, k)
            end do
            ! Безопасное сравнение вещественного числа с нулем устраняет предупреждение -Wcompare-reals
            if (abs(sas) .lt. 1e-8) an1(i, j, 1) = 1.0

            ! Инициализация толщин категорий льда на основе характерных толщин HST
            wice1(i, j, 1) = 0.20*an1(i, j, 2)   ! Категория 1: 0.20 м
            wice1(i, j, 2) = 0.40*an1(i, j, 3)   ! Категория 2: 0.40 м
            wice1(i, j, 3) = 0.95*an1(i, j, 4)   ! Категория 3: 0.95 м
            wice1(i, j, 4) = 1.60*an1(i, j, 5)   ! Категория 4: 1.60 м
            wice1(i, j, 5) = 2.50*an1(i, j, 6)   ! Категория 5: 2.50 м
        end do
    end do

    call redis()

    ! --- Инициализация синтетических полей ---
    call init_ocean()

    ! Диагностика уравнения состояния (этап 3.1): расчет RO из T2/S2
    ! в диагностическом режиме. Пока НЕ используется в уравнениях движения.
    call eos_diag()

    ! Записываем состояние океана ДО начала расчета (День 0)
    call write_nc(trim(run_nc_dir)//'/results_day_00.nc')

! ====================================================================
!              ЧТЕНИЕ АТМОСФЕРНОГО ФОРСИНГА ERA5 (NetCDF)
! ====================================================================
! Этап 2/3: чтение и диагностика. Открываем файл полного месяца (январь
! 2020). Пока это только проверка канала ввода; подключение к физике
! (wind/tx/ty/dpx/dpy/tatm/patm) выполняется на следующих этапах.
! При ошибке чтения модель продолжает работу в legacy-режиме (без ERA5).
    if (forcing_mode .eq. forcing_mode_era5) then
        call era5_open(trim(era5_input_file), ios)
        if (ios .eq. 0) then
            call era5_diag()

            ! Временной интерфейс: модельные сутки привязываются к первому
            ! ERA5-срезу (nearest-time, документированное допущение первого
            ! этапа). start_sec = время первого среза в секундах с эпохи.
            start_sec = era5_time(1)

            ! Ограничиваем прогон числом суток, покрытых ERA5-данными,
            ! чтобы модель не выходила за пределы входных данных.
            nperday = nint(86400.0_8/max(era5_time(2) - era5_time(1), 1.0_8))
            mm1 = min(mm1, (era5_ntime - 1)/max(nperday, 1))
            print *, "ERA5: run limited to ", mm1, " days (", era5_ntime, &
                " time steps, ", nperday, " steps/day)"
        else
            print *, "WARNING: ERA5 input failed, falling back to legacy forcing."
            forcing_mode = forcing_mode_legacy
        end if
    end if

! ====================================================================
!                    ГЛАВНЫЙ ЦИКЛ ПО ВРЕМЕНИ
! ====================================================================
    print *, "Starting Main Integration Loop..."

! Начальное состояние ветра/давления для первого дня
    pp(:) = p(:, kkb)
    if (forcing_mode .eq. forcing_mode_era5) then
        call era5_wind(start_sec)
    else
        call wind1()
    end if

! --- Initialize ERA5 snowfall accumulation for monthly sfal climatology (Stage 6.6) ---
    sfal_accum = 0.0
    sfal_count = 0

! --- ЦИКЛ ПО ГОДАМ (MMMM = 1..MM5) ---
    do mmmm = 1, mm5
        nday = 0
        ! --- ЦИКЛ ПО МЕСЯЦАМ (LLL = 1..MM4) ---
        do lll = 1, mm4
            ! Reset monthly snowfall accumulator at start of each month
            sfal_accum(lll) = 0.0
            sfal_count(lll) = 0
            ! --- ЦИКЛ ПО ДНЯМ (KKK = KKB..MM1) ---
            do kkk = kkb, mm1
                nday = nday + 1
                nday1 = nday1 + 1

                if (nday1 .eq. 91) exit

                ess = euu - ecc
                print *, "Day:", kkk, " Month:", lll, " Kin.Energy(EUU)=", euu
                ecc = euu
                euu = 0.0

                ! Сброс суточных счётчиков convective adjustment (этап 4.2).
                call ca_reset()

                ! Сохранение полей предыдущего дня для временной интерполяции
                dpx(:, :) = dpx1(:, :)
                dpy(:, :) = dpy1(:, :)
                windx(:, :) = windx1(:, :)
                windy(:, :) = windy1(:, :)
                tx(:, :) = tx1(:, :)
                ty(:, :) = ty1(:, :)

                ! Переход к следующим метеоданным (день KKK+1)
                pp(:) = p(:, kkk + 1)
                if (forcing_mode .eq. forcing_mode_era5) then
                    call era5_wind(start_sec + real(kkk, 8)*86400.0_8)
                    ! Diagnostic: update monthly domain-mean sfal for validation (not used for forcing)
                    sfal_accum(lll) = sfal_accum(lll) &
                                      + compute_snowfall_mean(era5_snowfall_rate)
                    sfal_count(lll) = sfal_count(lll) + 1
                    sfal(lll) = sfal_accum(lll)/real(sfal_count(lll))
                else
                    call wind1()
                end if

                ! --- ЦИКЛ ПО СУТКАМ (III = 1..MM2) ---
                ! MM2 = 12 означает 12 шагов термодинамики за сутки (dt = 3600 с)
                do iii = 1, mm2
                    ! 1. Временная интерполяция ветровых напряжений
                    ! Линейная интерполяция между текущим и следующим днем
                    if (iii .ne. 1) then
                        b = real(mm2 - iii + 2)
                        tx = tx + (tx1 - tx)/b
                        ty = ty + (ty1 - ty)/b
                        dpx = dpx + (dpx1 - dpx)/b
                        dpy = dpy + (dpy1 - dpy)/b
                        windx = windx + (windx1 - windx)/b
                        windy = windy + (windy1 - windy)/b
                    end if

                    ! windx/windy хранят см/с, а heat использует модуль скорости в м/с.
                    wind = sqrt(windx*windx + windy*windy)*1.0e-2

                    ! Сохранение текущего шага как "предыдущего" для следующего шага
                    t1 = t2
                    s1 = s2
                    v1 = v2
                    u1 = u2

                    ! Термодинамика должна идти с тем же шагом, что и океан.
                    ! Без ERA5-полей (kl1=0) вызов дал бы деление на patm=0.
                    if (kl1 .eq. 1) then
                        call heat(dt, nday, lll)
                        ! heat меняет категории; динамике льда нужны новые A и h.
                        call redis()
                    end if

                    ! ====================================================================
                    !   3. ДИНАМИКА ЛЬДА (баротропные подциклы, mm3=30)
                    ! ====================================================================
                    ! Ледовый тензор движется быстрее, чем океан (dt1=120 с).
                    ! На каждом микрошаге jjj=1..mm3:
                    !   1. Сохраняем u0/v0 (скорость льда на начало микрошага).
                    !   2. txic/tyic = 0 (инициализация).
                    !   3. stress() — внутренние напряжения льда (Sxx, Syy, Sxy).
                    !   4. Для каждой ячейки:
                    !      a. hht = средняя толщина льда [м] (по 4 T-точкам).
                    !         Если hht < 0.01 м → u=v=0 (guard от сингулярности).
                    !      b. txic = c17·|V_water - V_ice|·(V_water - V_ice)/hht [м/с²].
                    !         Трение вода-лёд: положительная обратная связь при малом hht.
                    !      c. f_u = ∂(Sxx)/∂x + ∂(Sxy)/∂y — горизонтальные напряжения.
                    !      d. Уравнение движения льда (simplified):
                    !         du/dt = τ_wind/ρ_ice·h + τ_water·A_ice + f·v - ∇p + f_u/ρ_ice
                    !         c15/c16 = cos/sin(15°) — поправка на ориентацию напряжений.
                    !   5. Граничные условия: u(:,1)=u(:,2), u(:,js1)=u(:,js), и т.д.
                    do jjj = 1, mm3
                        u0 = u       ! [м/с] Сохранение скорости на начало микрошага
                        v0 = v
                        txic = 0.0   ! [м/с²] Обнуление перед расчётом
                        tyic = 0.0

                        call stress()  ! Внутренние напряжения льда (Sxx, Syy, Sxy)

                        do j = 2, js
                            j1 = j + 1
                            j2 = j - 1
                            do i = 2, is
                                i1 = i + 1
                                i2 = i - 1
                                if (kt1(i, j) .eq. 0) cycle  ! Суша — пропуск

                                ! hht [м] — средняя толщина льда по 4 T-точкам
                              hht = 0.25*(hices(i, j) + hices(i, j2) + hices(i2, j) + hices(i2, j2))
                                if (hht .lt. 0.01) then
                                    ! Guard: при hht < 1 см трение вода-лёд сингулярно.
                                    u(i, j) = 0.0
                                    v(i, j) = 0.0
                                    cycle
                                end if

                                uij = u0(i, j)  ! [м/с] U-скорость льда на начало микрошага
                                vij = v0(i, j)  ! [м/с] V-скорость льда
                                ! a1/b1 — скорость воды на поверхности [м/с]
                                !   (u2/v2 в CGS → перевод в SI: /100)
                                a1 = u2(i, j, 1)/100.0
                                b1 = v2(i, j, 1)/100.0
                                a = a1 - uij  ! [м/с] Относительная скорость (вода-лёд) U
                                b = b1 - vij  ! [м/с] Относительная скорость (вода-лёд) V
                                ! a [1/с] — коэффициент трения: c17·|V_rel|/hht
                                a = c17*sqrt(b*b + a*a)/hht

                                ! txic/tyic [м/с²] — напряжение трения вода-лёд.
                                !   c15/c16 = cos(15°)/sin(15°) — поворот на угол 15°.
                                txic(i, j) = a*(a1*c15 - b1*c16)
                                tyic(i, j) = a*(b1*c15 + a1*c16)

                                ! a3 — средняя сплошность льда (по 4 T-точкам)
                                a3 = 0.25*(ans(i, j) + ans(i, j2) + ans(i2, j) + ans(i2, j2))
                                if (a3 .gt. 2.0) cycle  ! Защита от некорректных данных

                                ! fix/fiy [Н/м] — горизонтальные градиенты напряжений льда.
                                !   ∂Sxx/∂x + ∂(Sxy)/∂y → fix
                                !   ∂(Syy)/∂y + ∂(Sxy)/∂x → fiy
                                !   c12 = 1/dx [1/см] — обратный шаг сетки.
                                a4 = sxy(i2, j) - sxy(i, j2)
                                b4 = sxy(i, j) - sxy(i2, j2)
                             fix = (sxx(i2, j) + sxx(i, j) - sxx(i2, j2) - sxx(i, j2) + a4 - b4)*c12
                             fiy = (syy(i2, j2) + syy(i2, j) - syy(i, j2) - syy(i, j) + a4 + b4)*c12

                                ! --- Уравнение движения льда ---
                                !   b3 [кг/м²] = hht × ρ_ice = hht × 910 кг/м³.
                                b3 = hht*9100.0
                                ! a2/b2 — скорости льда после.force-impulse (предварительная оценка):
                                !   u_new = u_old + dt1 × [τ_wind/b3 + τ_water·A + f·v - c11·∇η + fix/b3]
                                !   fku(i,j) — параметр Кориолиса [1/с].
                                !   c11×∇η — градиент уровня моря (barotropic pressure).
                                a2 = uij + dt1*(tx(i, j)/b3 + txic(i, j)*a3 + fku(i, j)*vij - &
                                c11*(ym2(i2, j) - ym2(i2, j2) + ym2(i, j) - ym2(i, j2)) + fix/910.0)
                                b2 = vij + dt1*(ty(i, j)/b3 + tyic(i, j)*a3 - fku(i, j)*uij - &
                                c11*(ym2(i2, j2) - ym2(i, j2) + ym2(i2, j) - ym2(i, j)) + fiy/910.0)

                                ! --- Учёт нелинейного трения (c15/c16) ---
                                ! b1/a1 — безразмерные коэффициенты трения (matrix inverse).
                                !   aa = a1² + b1² — норма матрицы.
                                !   u = (a1·a2 + b1·b2)/aa — решение 2×2 системы.
                                b1 = dt1*a*c16
                                a1 = 1.0 + dt1*a*c15
                                aa = a1*a1 + b1*b1
                                u(i, j) = (a1*a2 + b1*b2)/aa
                                v(i, j) = (a1*b2 - b1*a2)/aa

                                ! На последнем микрошаге: txic/tyic сохраняются для block 210
                                if (jjj .eq. mm3) then
                                    b3 = hht*9100.0
                                    txic(i, j) = -(txic(i, j) - a*(u(i, j)*c15 - v(i, j)*c16))*b3
                                    tyic(i, j) = -(tyic(i, j) - a*(v(i, j)*c15 + u(i, j)*c16))*b3
                                end if

                            end do
                        end do

                        ! Граничные условия ледового блока
                        u(:, 1) = u(:, 2)
                        v(:, 1) = v(:, 2)
                        u(:, js1) = u(:, js)
                        v(:, js1) = v(:, js)
                        u(1, :) = u(2, :)
                        v(1, :) = v(2, :)
                    end do

                    ! 4. Адвекция сплошности и массы льда
                    ! Цикл по категориям толщины (NGR = 5 категорий)
                    do k = 1, ngr
                        k1 = k + 1
                        an3(:, :) = an1(:, :, k1)
                        call adv2d(dt, dx, c2)
                        an3(:, js) = an1(:, js, k1)
                        an3(1, :) = an1(1, :, k1)
                        an1(:, :, k1) = an3(:, :)

                        an3(:, :) = wice1(:, :, k)
                        call adv2d(dt, dx, c2)
                        an3(:, js) = wice1(:, js, k)
                        an3(1, :) = wice1(1, :, k)
                        wice1(:, :, k) = an3(:, :)
                    end do
                    call redis()

                    ! ====================================================================
                    !   5. РАСЧЁТ ВЕРТИКАЛЬНОЙ СКОРОСТИ TЕЧЕНИЙ (W)
                    ! ====================================================================
                    ! Уравнение неразрывности (continuous):
                    !   ∂W/∂z = -∂U/∂x - ∂V/∂y
                    ! Дискретная реализация:
                    !   W(i,j,1) = -∂η/∂t - C8·(HH1·A_U + HH2·A_V)
                    !   W(i,j,k) = W(i,j,k-1) - C9·DZ1(k-1)·(TT(k-1) + SS(k-1))
                    ! где:
                    !   C8 = 1/dx [1/см] — обратный шаг сетки.
                    !   C9 = 1/dx [1/см] — обратный шаг сетки (вертикальная часть).
                    !   A_U = Σ(U1·cosφ) — интеграл U-скорости по границе ячейки по X.
                    !   A_V = Σ(V1) — интеграл V-скорости по границе ячейки по Y.
                    !   HH1 [см] — расстояние между соседними T-точками по X (южная граница).
                    !   HH2 [см] — расстояние между соседними T-точками по Y (восточная граница).
                    !   TT(k) = U1(i,j1,k) + U1(i1,j1,k) - U1(i,j,k) - U1(i1,j,k) — ∂U/∂x.
                    !   SS(k) = V1(i,j,k) + V1(i,j1,k) - V1(i1,j,k) - V1(i1,j1,k) — ∂V/∂y.
                    !   DZ1(k) [см] — толщина полуслоя (unused→используется dz1).
                    !   ym2 [см] — уровень моря (eta) на текущем шаге.
                    !   ym1 [см] — уровень моря на предыдущем шаге (для ∂η/∂t).
                    ! ====================================================================
                    do j = 2, js
                        j1 = j + 1
                        j2 = j - 1
                        do i = 2, is
                            i1 = i + 1
                            i2 = i - 1
                            ix1 = idx(i, j)    ! Индекс дна U-ячейки (i,j)
                            ix2 = idx(i, j1)   ! Индекс дна U-ячейки (i,j+1)
                            ki = kt1(i, j)      ! Число мокрых уровней T-точки
                            if (ki .eq. 0) cycle

                            iy1 = idy(i, j)    ! Индекс дна V-ячейки (i,j)
                            iy2 = idy(i1, j)   ! Индекс дна V-ячейки (i+1,j)

                            ! --- Интегралы U и V по границам ячейки ---
                            do k = 1, ki
                                ! U-потенциалы: сумма U1 по 4 U-точкам (2 по X, 2 по Y)
                                a = u1(i, j, k) + u1(i1, j, k)      ! Южная граница
                                aa = u1(i, j1, k) + u1(i1, j1, k)  ! Северная граница
                                if (k .eq. 1) au = a + aa  ! Для нижнего слоя

                                ! Защита от выхода за дно
                                if (ix1 .lt. k .or. ix2 .lt. k) then
                                    tt(k) = 0.0  ! Нет U-потока — дно
                                else
                                    tt(k) = aa - a  ! ∂U/∂x ≈ (U_north - U_south)
                                end if

                                ! V-потенциалы: сумма V1 по 4 V-точкам (2 по X, 2 по Y)
                                b = v1(i, j, k) + v1(i, j1, k)      ! Восточная граница
                                bb = v1(i1, j, k) + v1(i1, j1, k)  ! Западная граница
                                if (k .eq. 1) av = b + bb  ! Для нижнего слоя

                                if (iy1 .lt. k .or. iy2 .lt. k) then
                                    ss(k) = 0.0  ! Нет V-потока — дно
                                else
                                    ss(k) = b - bb  ! ∂V/∂y ≈ (V_east - V_west)
                                end if
                            end do

                            ymm = ym2(i, j)  ! [см] Текущий уровень моря

                            ! --- Расстояние HH1 между T-точками по X ---
                            if (ix1 .eq. 0 .and. ix2 .ne. 0) then
                                hh1 = ymm - ym2(i, j2)  ! Только южный сосед
                            else if (ix1 .ne. 0 .and. ix2 .eq. 0) then
                                hh1 = ym2(i, j1) - ymm  ! Только северный сосед
                            else if (ix1 .ne. 0 .and. ix2 .ne. 0) then
                                hh1 = 0.5*(ym2(i, j1) - ym2(i, j2))  ! Среднее
                            else
                                hh1 = 0.0  ! Нет соседей — контур не определён
                            end if

                            ! --- Расстояние HH2 между T-точками по Y ---
                            if (iy1 .eq. 0 .and. iy2 .ne. 0) then
                                hh2 = ymm - ym2(i1, j)  ! Только восточный сосед
                            else if (iy1 .ne. 0 .and. iy2 .eq. 0) then
                                hh2 = ym2(i2, j) - ymm  ! Только западный сосед
                            else if (iy1 .ne. 0 .and. iy2 .ne. 0) then
                                hh2 = 0.5*(ym2(i2, j) - ym2(i1, j))  ! Среднее
                            else
                                hh2 = 0.0
                            end if

                            ! --- W на поверхности (k=1) ---
                            ! W = -∂η/∂t - C8·(HH1·A_U + HH2·A_V)
                            !   ∂η/∂t = -(ym2 - ym1)/dt — приближение конечных разностей
                            a = -(ymm - ym1(i, j))/dt - (hh1*au + hh2*av)*c8
                            w(i, j, 1) = a
                            ym1(i, j) = ymm  ! Сохранение для следующего шага

                            ! --- W на глубине (k=2..ki) ---
                            ! W(k) = W(k-1) - C9·DZ1(k-1)·(TT(k-1) + SS(k-1))
                            !   TT = ∂U/∂x, SS = ∂V/∂y
                            if (ki .ge. 2) then
                                do k = 2, ki
                                    k2 = k - 1
                                    a = a - (tt(k2) + ss(k2))*dz1(k2)*c9
                                    w(i, j, k) = a
                                end do
                            end if
                        end do
                    end do

                    ! ====================================================================
                    !   6. АДВЕКЦИЯ СОЛЕНОСТИ И ТЕМПЕРАТУРЫ В ОКЕАНЕ
                    ! ====================================================================
                    ! Метод конечных разностей (FCT — Flux Corrected Transport).
                    !   advs(dt, c2) — адвекция солености S2 → S1 (3D).
                    !   advt(dt, c2) — адвекция температуры T2 → T1 (3D).
                    ! dt [с] — шаг по времени, c2 [безразм.] — коэффициент стабилизации.
                    ! Используются скорости U2/V2 (из block 210) и вертикальная W.
                    ! Массивы после вызова: S1/T1 содержат адвектированные поля.
                    call advs(dt, c2)
                    call advt(dt, c2)

                    ! Диагностика этапа 4.3 (ТОЛЬКО чтение, не влияет на физику):
                    ! точка A - плотностные инверсии сразу после адвекции T/S,
                    ! т.е. на входе в convective adjustment. Опрашивается в
                    ! нескольких шагах суток, чтобы не засорять консоль.
                    if (iii .eq. 1 .or. iii .eq. 6 .or. iii .eq. mm2) then
                        call ca_probe_inversions('A_after_adv', kkk, iii)
                    end if

                    ! Конвективная коррекция плотностной стратификации (этап 3.2):
                    ! историческая схема перемешивания при RR(K)-RR(K1) > 0.9E-7.
                    ! RO пока НЕ используется в уравнениях движения (этапы 3.1-3.2).
                    call conv_adj(kkk, iii)

                    ! Диагностика этапа 4.3: точка D - остаточные инверсии после
                    ! convective adjustment (должны быть близки к нулю, кроме
                    ! столбцов с guard-срабатыванием).
                    if (iii .eq. 1 .or. iii .eq. 6 .or. iii .eq. mm2) then
                        call ca_probe_inversions('D_after_conv', kkk, iii)
                    end if

                    ! ====================================================================
                    !   6b. 3D-ИМПУЛЬС (BLOCK 200): Coriolis + baroclinic + DPX + Laplacian
                    ! ====================================================================
                    ! Исторический блок 200 (Coupl1.f90:880-940, Nesterov_last:2110-2160).
                    ! Уравнение (для каждого уровня k):
                    !   AUU = U1 + ASA1·V1 + dt·(-C1·SUM - DPX + C3·SLAPU)
                    !   AVV = V1 - ASA1·U1 + dt·(-C1·SUM1 - DPY + C3·SLAPV)
                    !   U2 = (AUU + AVV·ASA1) / ASA
                    !   V2 = (AVV - AUU·ASA1) / ASA
                    ! где:
                    !   ASA1 = FKU·0.5·dt — полу-интервал Кориолиса [безразм.].
                    !   ASA = 1 + ASA1² — нормирующий множитель.
                    !   C1 = g/ρ₀ = 981 — гравитационный масштаб [см/с²].
                    !   C3 = Ah/dx² — горизонтальная вязкость [1/с].
                    !   SUM = Σ[(RO(i2,j,k)+RO(i,j,k)-RO(i2,j2,k)-RO(i,j2,k))
                    !         + (RO(i2,j,k+1)+RO(i,j,k+1)-RO(i2,j2,k+1)-RO(i,j2,k+1))]
                    !         × c8·dz(k) — бароклинный интеграл давления по X.
                    !   SLAPU = ∇²U — дискретный Лапласиан [см/с].
                    !   DPX/DPY [hPa/см] — градиент атмосферного давления.
                    ! Единицы: U1/U2 [см/с], RO [г/см³], DPX/DPY [hPa/см].
                    ! Специальная обработка: если hht = z(k) (уровень совпадает с дном),
                    !   U2 = V2 = 0 (нет движения на дне).
                    do j = 2, js
                        do i = 2, is
                            ki = kk1(i, j)       ! Число мокрых уровней U/V-ячейки
                            if (ki .eq. 0) cycle  ! Суша — пропуск
                            i1 = i + 1
                            i2 = i - 1
                            j1 = j + 1
                            j2 = j - 1
                            hht = map1(i, j)  ! [см] Средняя глубина ячейки
                            if (abs(hht - 8888.0) .lt. 1e-8) cycle  ! Land mask

                            sum = 0.0   ! Бароклинный интеграл по X
                            sum1 = 0.0  ! Бароклинный интеграл по Y
                            asa1 = fku(i, j)*0.5*dt  ! [безразм.] ASA1 = f·dt/2
                            asa = 1.0 + asa1*asa1     ! [безразм.] ASA = 1 + (f·dt/2)²

                            ! Начальные RO-значения для предыдущего уровня (уровень 0)
                            ri2j = ro(i2, j, 1)
                            rij = ro(i, j, 1)
                            ri2j2 = ro(i2, j2, 1)
                            rij2 = ro(i, j2, 1)
                            a = ri2j + rij - ri2j2 - rij2   ! ΔRO по X (уровень 0)
                            b = ri2j2 + ri2j - rij2 - rij   ! ΔRO по Y (уровень 0)
                            dzz = dz(1)  ! [см] Толщина первого слоя

                            do k = 1, ki
                                ! Если уровень совпадает с дном — скорость = 0
                                if (abs(hht - z(k)) .lt. 1e-6) then
                                    u2(i, j, k) = 0.0
                                    v2(i, j, k) = 0.0
                                    cycle
                                end if
                                k1 = k + 1
                                dzz1 = dz(k1)  ! [см] Толщина следующего слоя
                                uij = u1(i, j, k)  ! [см/с] U на предыдущем шаге
                                vij = v1(i, j, k)  ! [см/с] V на предыдущем шаге

                                ! RO на текущем уровне (4 соседние C-точки)
                                ri2j = ro(i2, j, k)
                                rij2 = ro(i, j2, k)
                                rij = ro(i, j, k)
                                ri2j2 = ro(i2, j2, k)
                                a1 = ri2j + rij - ri2j2 - rij2  ! ΔRO по X (уровень k)
                                b1 = ri2j2 + ri2j - rij2 - rij  ! ΔRO по Y (уровень k)

                                ! Накопление бароклинного интеграла
                                !   cc_val = c8·dz [см·см⁻¹] = [безразм.]
                                cc_val = c8*dzz
                                sum = sum + (a + a1)*cc_val   ! ∫(∂ρ/∂x)dz
                                sum1 = sum1 + (b + b1)*cc_val  ! ∫(∂ρ/∂y)dz

                                ! Лапласиан: ∇²U = U(i,j-1)+U(i,j+1)+U(i-1,j)+U(i+1,j) - 4·U(i,j)
                         slapu = u1(i, j2, k) + u1(i, j1, k) + u1(i2, j, k) + u1(i1, j, k) - 4.0*uij
                         slapv = v1(i1, j, k) + v1(i2, j, k) + v1(i, j1, k) + v1(i, j2, k) - 4.0*vij

                                ! Уравнение 3D-импульса (с隐式 Кориолис):
                                !   AUU = U1 + (f·dt/2)·V1 + dt·[-(g/ρ₀)·SUM - DPX + Ah/dx²·∇²U]
                                !   AVV = V1 - (f·dt/2)·U1 + dt·[-(g/ρ₀)·SUM1 - DPY + Ah/dx²·∇²V]
                                auu = uij + asa1*vij + dt*(-c1*sum - dpx(i, j) + c3*slapu)
                                avv = vij - asa1*uij + dt*(-c1*sum1 - dpy(i, j) + c3*slapv)
                                ! Решение 2×2 системы (явный Кориолис):
                                u2(i, j, k) = (auu + avv*asa1)/asa
                                v2(i, j, k) = (avv - auu*asa1)/asa

                                a = a1  ! Сохранение для следующего уровня
                                b = b1
                                dzz = dzz1
                            end do
                        end do
                    end do

                    ! ====================================================================
                    !   6c. ВЕРТИКАЛЬНАЯ ВЯЗКОСТЬ (BLOCK 210): Thomas algorithm
                    ! ====================================================================
                    ! Исторический блок 210 (Coupl1.f90:942-1020).
                    !
                    ! Коэффициент вертикальной вязкости (модификация Ричардсона):
                    !   NU(k) = L² · |∂U/∂z|
                    ! где L — длина смешения (mixing length):
                    !   L = κ · z · (1 - z/H) · f(FF, FF1) / (1 + 4·FF1/5000)
                    !   κ = 0.4 — константа Кармана.
                    !   z — расстояние от дна, H — глубина.
                    !   FF = H - z(k) + 2 — расстояние до поверхности [см].
                    !   FF1 = z(k) - yyy - 2 — расстояние до дна [см].
                    !   yyy = 0.25·ΣYM2 — средний уровень моря.
                    !   sl — длина смешения (variable sl в коде).
                    !   NU = sl² · |∂U/∂z| [см²/с].
                    !   rr(k) = NU(k) — хранится в рабочем массиве.
                    !   skz(i,j) = rr(1) — для термодинамики (турбулентный обмен).
                    !
                    ! Трёхдиагональная система (алгоритм Томаса):
                    !   a_k · U(k-1) + b_k · U(k) + c_k · U(k+1) = d_k
                    ! Прямой ход: вычисление uca/unu (коэффициенты).
                    ! Граничное условие на поверхности:
                    !   τ_surface = (1-A)·τ_wind + A·τ_water_ice
                    !   где A = средняя сплошность льда.
                    ! Обратный ход: U2(k) = uca(k)·U2(k+1) + unu(k).
                    ! ====================================================================
                    do j = 2, js
                        do i = 2, is
                            ki = kk1(i, j)      ! Число мокрых уровней
                            if (ki .eq. 0) cycle
                            i2 = i - 1
                            j2 = j - 1
                            hht = map1(i, j)  ! [см] Средняя глубина
                            if (abs(hht - 8888.0) .lt. 1e-8) cycle
                            ki1 = ki + 1
                            ki2 = ki - 1
                            ! yyy [см] — средний уровень моря по 4 T-точкам
                            yyy = 0.25*(ym2(i2, j2) + ym2(i, j2) + ym2(i2, j) + ym2(i, j))

                            ! --- Расчёт коэффициентов вертикальной вязкости NU(k) ---
                            uij = u2(i, j, 1)  ! [см/с] U на поверхности
                            vij = v2(i, j, 1)
                            aa = sqrt(uij*uij + vij*vij)  ! |U| на текущем уровне
                            do k = 1, ki
                                k1 = min(k + 1, ks)
                                uij = u2(i, j, k1)  ! [см/с] U на следующем уровне
                                vij = v2(i, j, k1)
                                bb = sqrt(uij*uij + vij*vij)  ! |U(k+1)|
                                ! FF [см] — расстояние от уровня k до поверхности
                                ff = hht - z(k) + 2.0
                                ! FF1 [см] — расстояние от уровня k до дна
                                ff1 = z(k) - yyy - 2.0
                                ! sl — длина смешения [см] (формула Кармана с поправками)
                                !   0.4 = κ (константа Кармана).
                                !   (1 - 1.2·FF·FF1/H²) — обнуление на границах.
                                !   (4·FF1/5000 + 1) — дренаж у дна.
                               sl = 0.4/hht*ff*ff1*(1.0 - 1.2*ff*ff1/hht/hht)/(4.0*ff1/5000.0 + 1.0)
                                ! rr(k) = NU(k) [см²/с] = sl² · |∂U/∂z|
                                if (k .ne. ki) then
                                    rr(k) = sl*sl*abs(bb - aa)/dz(k1)  ! |∂U/∂z| ≈ ΔU/Δz
                                else
                                    ! Для нижнего слоя:特殊ная формула с 50 см поправкой
                                    rr(k) = sl*sl*abs(bb - aa)/(hht - z(ki) + 50.0)
                                end if
                                aa = bb  ! Следующий уровень
                            end do
                            ! skz [см²/с] — турбулентный обмен для термодинамики (верхний слой)
                            skz(i, j) = rr(1)

                            ! --- Начальные условия для алгоритма Томаса ---
                            if (ki .ne. 1) then
                                dzz = dz1(1)     ! [см] Толщина полуслоя 1
                                dzzz = dz(2)     ! [см] Толщина слоя 2
                            else
                                dzz = hht        ! Один уровень — вся глубина
                                dzzz = hht - z(1) + 50.0
                            end if
                            ! Прямой ход: первый уровень (поверхностное ГУ)
                            !   b = dt/(dzz·dzzz)·rr(1) — безразмерный коэффициент
                            b = dt/dzz/dzzz*rr(1)
                            a = 1.0 + b
                            uca(1) = b/a  ! Коэффициент Томаса (безразм.)
                            ! a1 — средняя сплошность льда (4 T-точки)
                            a1 = 0.25*(ans(i, j) + ans(i, j2) + ans(i2, j) + ans(i2, j2))
                            ! Граничное условие: τ = (1-A)·τ_wind + A·τ_water_ice
                            !   tau [дин/см²] → перевод в [см/с²]: /dz [см] × dt [с].
                            unu(1) = (u2(i, j, 1) + dt/dzz*((1.0 - a1)*tx(i, j) + a1*txic(i, j)))/a
                            vca(1) = uca(1)
                            vnu(1) = (v2(i, j, 1) + dt/dzz*((1.0 - a1)*ty(i, j) + a1*tyic(i, j)))/a
                            if (ki .eq. 1) then
                                ! Один уровень: прямой и обратный ход одновременно
                                u2(i, j, ki) = uca(ki)*u2(i, j, ki1) + unu(ki)
                                v2(i, j, ki) = vca(ki)*v2(i, j, ki1) + vnu(ki)
                            else if (ki .ge. 2) then
                                ! --- Прямой ход Томаса (k=2..ki-1) ---
                                ! Рекуррентные формулы для uca/unu/vca/vnu:
                                !   a[k] = -NU(k-1)/(dz1·dz[k])
                                !   b[k] = -NU(k)/(dz1·dz[k+1])
                                !   a1[k] = -1 + a[k] + b[k]
                                !   uca[k] = b[k] / (a1[k] - uca[k-1]·a[k])
                                !   unu[k] = (a[k]·unu[k-1] - U2[k]) / (a1[k] - uca[k-1]·a[k])
                                if (ki .ge. 3) then
                                    do k = 2, ki2
                                        k2 = k - 1
                                        aa = dt/dz1(k)  ! [с] / [см] → нужен комментарий
                                        a = -aa/dz(k)*rr(k2)    ! -dt/(dz1·dz)·NU(k-1)
                                        b = -aa/dz(k + 1)*rr(k)  ! -dt/(dz1·dz)·NU(k)
                                        a1 = -1.0 + a + b         ! Диагональный элемент
                                        ! uca — безразмерный коэффициент ( forward sweep)
                                        aa = a1 - uca(k2)*a
                                        uca(k) = b/aa
                                        unu(k) = (a*unu(k2) - u2(i, j, k))/aa  ! [см/с]
                                        aa = a1 - vca(k2)*a
                                        vca(k) = b/aa
                                        vnu(k) = (a*vnu(k2) - v2(i, j, k))/aa
                                    end do
                                end if
                                ! --- Граничное условие на дне + обратный ход ---
                                ! dzz [см] — полуслой нижнего уровня
                                dzz = hht - 0.5*(z(ki) + z(ki2))
                                ! dzzz [см] — расстояние от нижнего уровня до дна
                                dzzz = hht - z(ki) + 50.0
                                b = dt/dzz/dz(ki)*rr(ki2)
                                a = 1.0 + b + dt/dzz/dzzz*rr(ki)
                                bb = b/a
                                ! Нижний уровень: обратный ход
                                u2(i, j, ki) = (u2(i, j, ki)/a + bb*unu(ki2))/(1.0 - bb*uca(ki2))
                                v2(i, j, ki) = (v2(i, j, ki)/a + bb*vnu(ki2))/(1.0 - bb*vca(ki2))
                                ! Обратный ход от нижнего уровня к поверхности
                                do k = 1, ki2
                                    kk = ki - k
                                    k1 = kk + 1
                                    u2(i, j, kk) = uca(kk)*u2(i, j, k1) + unu(kk)
                                    v2(i, j, kk) = vca(kk)*v2(i, j, k1) + vnu(kk)
                                end do
                            end if
                        end do
                    end do

                    ! ====================================================================
                    !   7. БАРОТРОПНЫЙ РАСЧЁТ МЕЛКОЙ ВОДЫ И УРОВНЯ МОРЯ
                    ! ====================================================================
                    ! shallow_water.f90:sh() — решает уравнения мелкой воды:
                    !   ∂η/∂t + ∇·(H·U_bar) = 0  (неразрывность)
                    !   ∂U_bar/∂t + f×U_bar + g·∇η = τ/ρ·H  (импульс)
                    ! Где U_bar = (UP2, VP2) — интегральные потоки [см²/с].
                    call shal()

                    ! ====================================================================
                    !   8. ВОЗВРАТ БАРОТРОПНОЙ КОМПОНЕНТЫ (BLOCK 280)
                    ! ====================================================================
                    ! Исторический блок 280 (Coupl1.f90:1031-1058).
                    !
                    ! Проблема: после block 210 скорость U2 содержит бароклинную
                    !   компоненту, вертикальное среднее которой не обязательно равно
                    !   баротропному потоку UP2/HHT.
                    ! Решение: добавляем поправку SUM ко всем уровням:
                    !   SUM = [-Σ(U2(k)·DZ1(k)) + 0.5·(UP2(I,J)+UP2(I2,J))] / HHT
                    !   U2(I,J,K) = U2(I,J,K) + SUM  (для всех K)
                    ! Это обнуляет вертикальное среднее: <U2> = UP2/HHT.
                    ! Аналогично для V2 с VP2.
                    ! DZ1(k) — толщина полуслоя; для нижнего уровня: HHT - 0.5·(z(ki)+z(ki-1)).
                    ! ====================================================================
                    do j = 2, js
                        do i = 2, is
                            ki = kk1(i, j)      ! Число мокрых уровней
                            if (ki .eq. 0) cycle
                            i2 = i - 1
                            j2 = j - 1
                            hht = map1(i, j)  ! [см] Средняя глубина
                            if (abs(hht - 8888.0) .lt. 1e-8) cycle

                            sum = 0.0   ! ∫U2·DZ1 для U
                            sum1 = 0.0  ! ∫U2·DZ1 для V

                            do k = 1, ki
                                k1 = k + 1
                                if (k .eq. ki) then
                                    ! Нижний уровень:特殊ная формула для толщины
                                    if (ki .ne. 1) then
                                        dzz = hht - 0.5*(z(ki) + z(ki - 1))  ! [см]
                                    else
                                        dzz = hht  ! Один уровень
                                    end if
                                else
                                    dzz = dz1(k)  ! [см] Толщина полуслоя
                                end if
                                ! Накопление вертикального интеграла
                                sum = u2(i, j, k)*dzz + sum    ! [см²/с] · [см] = [см³/с]
                                sum1 = v2(i, j, k)*dzz + sum1
                            end do
                            ! Поправка: SUM = (-∫U2·DZ1 + U_bar·HHT) / HHT
                            !   0.5·(UP2(I,J)+UP2(I2,J)) — баротропный поток в U-точке
                            !   (усреднение по 2 соседним T-точкам).
                            sum = (-sum + 0.5*(up2(i, j) + up2(i2, j)))/hht  ! [см/с]
                            sum1 = (-sum1 + 0.5*(vp2(i, j) + vp2(i, j2)))/hht  ! [см/с]

                            ! Добавление поправки ко всем уровням
                            do k = 1, ki
                                u2(i, j, k) = u2(i, j, k) + sum   ! [см/с]
                                v2(i, j, k) = v2(i, j, k) + sum1
                            end do
                        end do
                    end do

                    ! Диагностика 3D-скоростей (этап 3.3): min/max U2,V2 после всех блоков
                    if (kkk .le. 2) then
                        uu = 0.0
                        vv = 0.0
                        aa = 0.0
                        do j = 2, js
                            do i = 2, is
                                if (kk1(i, j) .eq. 0) cycle
                                do k = 1, kt1(i, j)
                                    if (u2(i, j, k) .ne. u2(i, j, k)) aa = 1.0
                                    if (v2(i, j, k) .ne. v2(i, j, k)) aa = 1.0
                                    uu = max(uu, abs(u2(i, j, k)))
                                    vv = max(vv, abs(v2(i, j, k)))
                                end do
                            end do
                        end do
                        print '(A,I1,A,I3,A,E12.4,A,E12.4,A,E12.4)', &
                            "B3.3 d=", kkk, " III=", iii, " maxU2=", uu, &
                            " maxV2=", vv, " NaNflag=", aa
                    end if

                end do ! Конец суточного цикла III

                ! --- Суточный диагностический вывод (этап 4.2) ---
                ! Пишем NetCDF-срез за сутки kkk и строку CSV со статистиками
                ! (U/V/W/T/S/RO min/max/mean, ветер, напряжения, градиенты,
                !  кинетическая энергия EUU, счётчики convective adjustment).
                write (day_file, '(A,A,I2.2,A)') trim(run_nc_dir), '/results_day_', kkk, '.nc'
                call write_nc(trim(day_file))
                call write_daily_diagnostics(kkk, lll)
            end do ! Конец цикла дней KKK

            ! --- Final monthly ERA5 snowfall rate report (diagnostic domain-mean) ---
            if (forcing_mode .eq. forcing_mode_era5 .and. sfal_count(lll) .gt. 0) then
            print *, "ERA5 Snowfall DIAG: month ", lll, " domain-mean = ", sfal(lll), " m/s (", sfal_count(lll), " days)"
            end if
        end do ! Конец цикла месяцев LLL
    end do ! Конец цикла лет MMMM

    print *, "Integration completed successfully!"

! Диагностика уравнения состояния после 5 дней (этап 3.1)
    call eos_diag()

! Записываем финальное состояние океана после интеграции.
! Суточные срезы записаны внутри цикла как results_day_01.nc...30.nc,
! поэтому финальный файл назван отдельно и не затирает суточный срез.
    call write_nc(trim(run_nc_dir)//'/results_day_final.nc')

contains

    ! ==========================================================================
    ! write_daily_diagnostics: суточная диагностика (этап 4.2).
    ! Считает min/max/mean U/V/W/T/S/RO по водным колонкам, max ветра,
    ! min/max напряжений и градиентов давления, кинетическую энергию EUU
    ! и суточные счётчики convective adjustment. Аппендит одну CSV-строку.
    ! Ничего в физике не меняет - только диагностический вывод.
    ! ==========================================================================
    subroutine write_daily_diagnostics(day, month)
        integer, intent(in) :: day, month

        integer, parameter :: diag_unit = 77
        real :: u_min, u_max, u_sum, v_min, v_max, v_sum
        real :: w_min, w_max, w_sum, t_min, t_max, t_sum
        real :: s_min, s_max, s_sum, ro_min, ro_max, ro_sum
        real :: wind_max, tx_min, tx_max, ty_min, ty_max
        real :: dpx_min, dpx_max, dpy_min, dpy_max
        integer :: n, iw, jw, kw, ki_col
        integer :: total_nmix, max_iter, guard_hits, affected_cols
        logical :: first, is_open

        u_min = huge(1.0); u_max = -huge(1.0); u_sum = 0.0
        v_min = huge(1.0); v_max = -huge(1.0); v_sum = 0.0
        w_min = huge(1.0); w_max = -huge(1.0); w_sum = 0.0
        t_min = huge(1.0); t_max = -huge(1.0); t_sum = 0.0
        s_min = huge(1.0); s_max = -huge(1.0); s_sum = 0.0
        ro_min = huge(1.0); ro_max = -huge(1.0); ro_sum = 0.0
        wind_max = 0.0
        tx_min = huge(1.0); tx_max = -huge(1.0)
        ty_min = huge(1.0); ty_max = -huge(1.0)
        dpx_min = huge(1.0); dpx_max = -huge(1.0)
        dpy_min = huge(1.0); dpy_max = -huge(1.0)
        n = 0

        do jw = 2, js
            do iw = 2, is
                ki_col = kt1(iw, jw)
                if (ki_col .eq. 0) cycle
                wind_max = max(wind_max, wind(iw, jw))
                tx_min = min(tx_min, tx(iw, jw)); tx_max = max(tx_max, tx(iw, jw))
                ty_min = min(ty_min, ty(iw, jw)); ty_max = max(ty_max, ty(iw, jw))
                dpx_min = min(dpx_min, dpx(iw, jw)); dpx_max = max(dpx_max, dpx(iw, jw))
                dpy_min = min(dpy_min, dpy(iw, jw)); dpy_max = max(dpy_max, dpy(iw, jw))
                do kw = 1, ki_col
                    n = n + 1
                    u_min = min(u_min, u2(iw, jw, kw)); u_max = max(u_max, u2(iw, jw, kw)); u_sum = u_sum + u2(iw, jw, kw)
                    v_min = min(v_min, v2(iw, jw, kw)); v_max = max(v_max, v2(iw, jw, kw)); v_sum = v_sum + v2(iw, jw, kw)
                    w_min = min(w_min, w(iw, jw, kw)); w_max = max(w_max, w(iw, jw, kw)); w_sum = w_sum + w(iw, jw, kw)
                    t_min = min(t_min, t2(iw, jw, kw)); t_max = max(t_max, t2(iw, jw, kw)); t_sum = t_sum + t2(iw, jw, kw)
                    s_min = min(s_min, s2(iw, jw, kw)); s_max = max(s_max, s2(iw, jw, kw)); s_sum = s_sum + s2(iw, jw, kw)
                    ro_min = min(ro_min, ro(iw, jw, kw)); ro_max = max(ro_max, ro(iw, jw, kw)); ro_sum = ro_sum + ro(iw, jw, kw)
                end do
            end do
        end do

        call ca_stats(total_nmix, max_iter, guard_hits, affected_cols)

        ! Заголовок CSV - только если файл создаётся заново.
        inquire (file=trim(run_csv_dir)//'/daily_diagnostics.csv', exist=first)
        first = .not. first
        open (diag_unit, file=trim(run_csv_dir)//'/daily_diagnostics.csv', position='append')
        if (first) then
            write (diag_unit, '(A)') &
                "day,month,u_min,u_max,u_mean,v_min,v_max,v_mean,w_min,w_max,w_mean,"// &
                "t_min,t_max,t_mean,s_min,s_max,s_mean,ro_min,ro_max,ro_mean,"// &
                "wind_max,tx_min,tx_max,ty_min,ty_max,dpx_min,dpx_max,dpy_min,dpy_max,"// &
                "euu,ca_nmix,ca_max_iter,ca_guard_hits,ca_affected_cols"
        end if
        write (diag_unit, '(I3,A1,I3,34(A1,ES16.5E2))') &
            day, ',', month, ',', &
            u_min, ',', u_max, ',', u_sum/max(n, 1), ',', &
            v_min, ',', v_max, ',', v_sum/max(n, 1), ',', &
            w_min, ',', w_max, ',', w_sum/max(n, 1), ',', &
            t_min, ',', t_max, ',', t_sum/max(n, 1), ',', &
            s_min, ',', s_max, ',', s_sum/max(n, 1), ',', &
            ro_min, ',', ro_max, ',', ro_sum/max(n, 1), ',', &
            wind_max, ',', tx_min, ',', tx_max, ',', ty_min, ',', ty_max, ',', &
            dpx_min, ',', dpx_max, ',', dpy_min, ',', dpy_max, ',', &
            euu, ',', real(total_nmix), ',', real(max_iter), ',', &
            real(guard_hits), ',', real(affected_cols)
        close (diag_unit)
        print '(A,I3,A,ES12.4,A,I8,A,I5,A,I3,A,I8)', &
            "  daily diag day=", day, " EUU=", euu, &
            " nmix=", total_nmix, " maxiter=", max_iter, &
            " guard=", guard_hits, " cols=", affected_cols
    end subroutine write_daily_diagnostics

    ! ==========================================================================
    ! compute_snowfall_mean: Compute spatial mean of ERA5 snowfall rate
    ! avoiding conflict with variable named 'sum'.
    ! ==========================================================================
    real function compute_snowfall_mean(arr)
        real, intent(in) :: arr(:, :)
        integer :: si, sj
        real :: total

        total = 0.0
        do sj = 1, js1
            do si = 1, is1
                total = total + arr(si, sj)
            end do
        end do
        compute_snowfall_mean = total/real(is1*js1)
    end function compute_snowfall_mean

