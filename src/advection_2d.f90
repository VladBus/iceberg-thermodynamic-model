! ==============================================================================
! Модуль: advection_2d (adv2d.f90)
! Назначение: Двумерная адвекция скалярных субстанций — сплошности льда (AN3)
!             и объёма льда (WICE1) в горизонтальной плоскости.
! Физика: Решает уравнение конвекции для 2D-поля:
!           ∂C/∂t + ∂(u·C)/∂x + ∂(v·C)/∂y = 0
!         где C — концентрация (сплошность A [безразм.] или объём льда [м³/м²]),
!         u,v — скорость льда [м/с].
!
!         Используется монотонная схема Flux-Corrected Transport (FCT)
!         Бориса-Бука (Boris & Book, 1973) с лимитером Залесака (Zalesak, 1979).
!         Алгоритм (4 этапа):
!           1. ПРЕДИКТОР: прямая конечная разность с направленными разностями (upwind).
!              CD2 = C - (dt/dx)·(F_x + F_y)
!              F_x = u·(C_j - C_j-1) при u>0, u·(C_j+1 - C_j) при u<0
!              + дивергентный член: + C·(u_j+1/2 - u_j-1/2)·0.5
!           2. АНТИДИФФУЗИОННЫЕ ПОТОКИ: квартичная (4-го порядка) коррекция.
!              APX2 = [u·(7·(C+C_j) - (C_j-1+C_j+2))/12 - F_upwind] · c2
!           3. FCT-ЛИМИТЕР ЗАЛЕСАКА: ограничение потоков для монотонности.
!              APX = sign(APX)·max(0, min(|APX|, P+, P-))
!           4. КОРРЕКЦИЯ: C_new = CD2 - ∇·(APX, APY)
!           5. СГЛАЖИВАНИЕ В ИЗЛОМАХ БЕРЕГОВОЙ ЛИНИИ (IT-индексы):
!              Замена угловых значений средним соседей (legacy, не консервативно).
!
!         Схема guarantees:
!           - Положительность: C ≥ 0 (нет отрицательных концентраций)
!           - Ограниченность: C ≤ max(C_neighbors) (нет новых экстремумов)
!           - Консервативность (с точностью до берегового сглаживания)
!
! Единицы (CGS):
!   AN3       — сплошность льда [безразм., 0..1]
!   U, V      — скорость льда [м/с] → перевод в [см/с] через ×50
!               (50 = 100/2, где 100 — перевод м/с→см/с, а /2 — усреднение
!               двух соседних скоростей на грани)
!   dt        — бароклинный шаг по времени [с] (= 3600 с)
!   dx        — пространственный шаг сетки [см] (= 1 389 000 см ≈ 13.89 км)
!   c2 = dt/dx — число Куранта [безразм.]
!   APX2, APY2 — антидиффузионные потоки FCT [безразм.]
!   CD2        — предиктор (промежуточное поле) [безразм.]
!
! Маски:
!   KT1(i,j)  — число мокрых уровней (0 = суша)
!   IT(i,j)   — идентификатор береговой конфигурации (0 = не берег)
!   IDX(i,j)  — вертикальная маска X-грани (0 = дно)
!   IDY(i,j)  — вертикальная маска Y-грани (0 = дно)
!
! Сетка: T-точки (центры ячеек). X ↔ j, Y ↔ i.
!         Скорости U/V определены на гранях (B-grid), интерполяция на центры
!         через усреднение двух соседних значений.
!
! Зависимости: param (массивы AN3, CD2, APX2, APY2, U, V, KT1, IT, IDX, IDY)
! ==============================================================================

module advection_2d
    use param
    implicit none

contains

    subroutine adv2d(dt, dx, c2)
        real, intent(in) :: dt     ! Бароклинный шаг по времени [с] (= 3600)
        real, intent(in) :: dx     ! Пространственный шаг сетки [см]
        real, intent(in) :: c2     ! Число Куранта = dt/dx [безразм.]

        integer :: i, j, i1, j1, i2, j2, i3, j3
        integer :: ix1, ix2, iy1, iy2, ki
        real :: up, um, uu, vp, vm, vv
        real :: cc, ci1, ci2, ci3, cj1, cj2, cj3
        real :: cdx, cdy, flxp, flyp, a1, b1, a, b

        ! Обнуление массивов антидиффузионных потоков FCT
        apx2(:, :) = 0.0
        apy2(:, :) = 0.0

        ! ================================================================
        ! ЦИКЛ 11: ПРЕДИКТОР (upwind + конвективный поток)
        ! ================================================================
        ! Вычисляет предварительное поле CD2 с учётом конвекции
        ! по направленным разностям (upwind-схема 1-го порядка).
        ! Для каждой ячейки (i,j):
        !   CD2(i,j) = C(i,j) - (dt/dx)·[F_x(i+1/2) - F_x(i-1/2) + F_y(j+1/2) - F_y(j-1/2)]
        ! где F_x = u·C (upwind), F_y = v·C (upwind).
        do j = 1, js
            do i = 1, is
                ! Пропуск суши и береговых ячеек (IT != 0)
                if (kt1(i, j) .eq. 0 .or. it(i, j) .ne. 0) cycle

                ! Индексы соседних ячеек с защитой от выхода за границы
                i1 = min(is1, i + 1)     ! Сосед по +Y (i+1/2)
                j1 = min(js1, j + 1)     ! Сосед по +X (j+1/2)
                i2 = max(1, i - 1)       ! Сосед по -Y (i-1/2)
                j2 = max(1, j - 1)       ! Сосед по -X (j-1/2)

                ! --- ИНТЕРПОЛЯЦИЯ СКОРОСТЕЙ НА ГРАНИ ЯЧЕЙКИ ---
                ! Скорости U/V определены на гранях B-сетки.
                ! Перевод из [м/с] в [см/с]: ×100, затем усреднение двух значений на грани → ×0.5
                ! Итого: ×50.0 (м/с → см/с на середине грани).
                up = 50.0*(u(i, j1) + u(i1, j1))   ! U на границе j+1/2 [см/с]
                um = 50.0*(u(i, j) + u(i1, j))     ! U на границе j-1/2 [см/с]
                uu = 0.5*(up + um)                   ! U в центре ячейки [см/с]
                vp = 50.0*(v(i1, j) + v(i1, j1))   ! V на границе i+1/2 [см/с]
                vm = 50.0*(v(i, j) + v(i, j1))     ! V на границе i-1/2 [см/с]
                vv = 0.5*(vp + vm)                   ! V в центре ячейки [см/с]
                iy1 = idy(i1, j)                     ! Маска Y-грани i+1/2
                ix1 = idx(i, j1)                     ! Маска X-грани j+1/2

                cc = an3(i, j)                        ! Текущее значение сплошности

                ! --- СОСЕДНИЕ ЗНАЧЕНИЯ ДЛЯ СХЕМЫ ПРОТИВ ПОТОКА ---
                ! Если маска = 0 (дно), значение = 0 (нет переноса).
                if (iy1 .eq. 0) then
                    ci1 = 0.0           ! Сосед по +Y не существует (дно)
                    i3 = i1
                else
                    ci1 = an3(i1, j)    ! Сосед по +Y [безразм.]
                    i3 = min(is1, i + 2)
                end if

                if (idy(i, j) .eq. 0) then
                    ci2 = 0.0           ! Сосед по -Y не существует
                else
                    ci2 = an3(i2, j)
                end if

                if (ix1 .eq. 0) then
                    cj1 = 0.0           ! Сосед по +X не существует
                    j3 = j1
                else
                    cj1 = an3(i, j1)
                    j3 = min(js1, j + 2)
                end if

                if (idx(i, j) .eq. 0) then
                    cj2 = 0.0           ! Сосед по -X не существует
                else
                    cj2 = an3(i, j2)
                end if

                ! --- ПОТОК ПО X (upwind-схема) ---
                ! F_x = u·(C_upstream - C_downstream)
                ! Если u > 0: поток идёт с запада, upwind = C(j-1), down = C(j)
                ! Если u < 0: поток идёт с востока, upwind = C(j+1), down = C(j)
                cdx = 0.0
                if (uu .gt. 0.0) then
                    cdx = (cc - cj2)*uu      ! u>0: с запада на восток
                else
                    cdx = (cj1 - cc)*uu      ! u<0: с востока на запад
                end if

                ! Запасная ветвь при нулевом потоку (uv��)
                if (abs(cdx) .lt. 1e-8) then
                    if (um .gt. 0.0) cdx = (cc - cj2)*um
                    if (up .lt. 0.0) cdx = (cj1 - cc)*up
                end if

                ! --- ДИВЕРГЕНТНЫЙ ЧЛЕН ---
                ! +C·(u_j+1/2 - u_j-1/2)/2 — компенсирует расходимость потока
                ! (без этого члена схема была бы не консервативна).
                cdx = cdx + cc*(up - um)*0.5

                ! --- ПОТОК ПО Y (upwind-схема) ---
                cdy = 0.0
                if (vv .gt. 0.0) then
                    cdy = (cc - ci1)*vv      ! v>0: с юга на север
                else
                    cdy = (ci2 - cc)*vv      ! v<0: с севера на юг
                end if

                if (abs(cdy) .lt. 1e-8) then
                    if (vp .gt. 0.0) cdy = (cc - ci1)*vp
                    if (vm .lt. 0.0) cdy = (ci2 - cc)*vm
                end if

                ! Дивергентный член по Y
                cdy = cdy + cc*(vm - vp)*0.5

                ! --- ПРЕДИКТОР ---
                ! CD2 = C - (dt/dx)·(F_x + F_y) [безразм.]
                cd2(i, j) = cc - dt*(cdx + cdy)/dx

                ! --- АНТИДИФФУЗИОННЫЕ ПОТОКИ ВЫСОКОГО ПОРЯДКА ---
                ! Квартичная (4-го порядка) коррекция:
                ! APX2 = [u·(7·(C+C_j) - (C_j-1+C_j+2))/12 - F_upwind] · c2
                ! Это разность между схемой 4-го порядка и 1-го порядка (upwind).
                ! c2 = dt/dx — число Куранта (для нормализации потока).

                ! Поток по X (j+1/2)
                if (ix1 .ne. 0) then
                    if (up .lt. 0.0) then
                        flxp = cj1*up           ! Upwind flux при u<0
                    else
                        flxp = cc*up            ! Upwind flux при u>0
                    end if

                    ! Значение C(j+2) для 4-го порядка (или 0 на границе)
                    cj3 = 0.0
                    if (j .ne. js) then
                        j3 = min(js1, j + 2)
                        if (idx(i, j3) .ne. 0) cj3 = an3(i, j3)
                    end if
                    ! Антидиффузионный поток [безразм.]
                    apx2(i, j1) = (up*(7.0*(cc + cj1) - (cj2 + cj3))/12.0 - flxp)*c2
                end if

                ! Поток по Y (i+1/2)
                if (iy1 .ne. 0) then
                    if (vp .lt. 0.0) then
                        flyp = cc*vp
                    else
                        flyp = ci1*vp
                    end if

                    ci3 = 0.0
                    if (i .ne. is) then
                        i3 = min(is1, i + 2)
                        if (idy(i3, j) .ne. 0) ci3 = an3(i3, j)
                    end if
                    apy2(i1, j) = (vp*(7.0*(cc + ci1) - (ci2 + ci3))/12.0 - flyp)*c2
                end if
            end do
        end do

        ! ================================================================
        ! ЦИКЛ 91: ОГРАНИЧИТЕЛЬ ПОТОКОВ FCT ПО X (лимитер Залесака)
        ! ================================================================
        ! Формула: APX = sign(APX) · max(0, min(|APX|, P+, P-))
        ! где P+ = CD2(j+1) - CD2(j), P- = CD2(j-1) - CD2(j-2)
        ! P+ и P- — разности предиктора вдоль направления потока.
        ! Если APX превышает допустимые градиенты, он обрезается до них.
        do j = 1, js
            do i = 1, is
                if (idx(i, j) .eq. 0) cycle

                j1 = min(js1, j + 1)
                j2 = max(1, j - 1)
                ix1 = idx(i, j1)
                ix2 = idx(i, j2)

                if (ix1 .eq. 0) then
                    a1 = 0.0
                else
                    a1 = cd2(i, j1) - cd2(i, j)         ! P+ (впереди по потоку)
                end if

                if (ix2 .eq. 0) then
                    b1 = 0.0
                else
                    b1 = cd2(i, j2) - cd2(i, max(1, j - 2))  ! P- (позади)
                end if

                a = apx2(i, j)
                b = sign(1.0, a)                         ! Знак потока
                apx2(i, j) = b*max(0.0, min(abs(a), b*a1, b*b1))
            end do
        end do

        ! --- ЦИКЛ 191: ОБНОВЛЕНИЕ ЗНАЧЕНИЙ ПО X ---
        ! CD2_new = CD2 - (APX2(j+1) - APX2(j))
        do j = 1, js
            do i = 1, is
                if (kt1(i, j) .eq. 0 .or. it(i, j) .ne. 0) cycle
                j1 = min(js1, j + 1)
                cd2(i, j) = cd2(i, j) - (apx2(i, j1) - apx2(i, j))
            end do
        end do

        ! ================================================================
        ! ЦИКЛ 391: ОГРАНИЧИТЕЛЬ ПОТОКОВ FCT ПО Y
        ! ================================================================
        do j = 1, js
            do i = 1, is
                if (idy(i, j) .eq. 0) cycle

                i1 = min(is1, i + 1)
                i2 = max(1, i - 1)
                iy1 = idy(i1, j)
                iy2 = idy(i2, j)

                if (iy1 .eq. 0) then
                    a1 = 0.0
                else
                    a1 = cd2(i, j) - cd2(i1, j)
                end if

                if (iy2 .eq. 0) then
                    b1 = 0.0
                else
                    b1 = cd2(max(1, i - 2), j) - cd2(i2, j)
                end if

                a = apy2(i, j)
                b = sign(1.0, a)
                apy2(i, j) = b*max(0.0, min(abs(a), b*a1, b*b1))
            end do
        end do

        ! --- ЦИКЛ 392: ОБНОВЛЕНИЕ ЗНАЧЕНИЙ ПО Y ---
        ! AN3_new = CD2 - (APY2(i+1) - APY2(i))
        do j = 1, js
            do i = 1, is
                if (kt1(i, j) .eq. 0 .or. it(i, j) .ne. 0) cycle
                i1 = min(is1, i + 1)
                an3(i, j) = cd2(i, j) - (apy2(i, j) - apy2(i1, j))
            end do
        end do

        ! ================================================================
        ! ЦИКЛ 400: СГЛАЖИВАНИЕ В ИЗЛОМАХ БЕРЕГОВОЙ ЛИНИИ (ИНДЕКС IT)
        ! ================================================================
        ! Legacy-процедура: в углах береговой линии (где IT=1..4)
        ! значение AN3 заменяется средним двух соседних водных ячеек.
        ! Это НЕ консервативно (масса льда не сохраняется), но предотвращает
        ! численные осцилляции вблизи неявных границ.
        ! IT=9 — ячейка внутри водного массива (не обрабатывается).
        do j = 1, js
            do i = 1, is
                ki = it(i, j)
                if (ki .eq. 0 .or. ki .eq. 9) cycle

                i1 = min(is1, i + 1)
                j1 = min(js1, j + 1)
                i2 = max(1, i - 1)
                j2 = max(1, j - 1)

                ! Угловые конфигурации берега (IT=1..4):
                ! 1: (+X, +Y) — сглаживание по j+1 и i+1
                ! 2: (+X, -Y) — сглаживание по j+1 и i-1
                ! 3: (-X, -Y) — сглаживание по j-1 и i-1
                ! 4: (-X, +Y) — сглаживание по j-1 и i+1
                if (ki .eq. 1) an3(i, j) = 0.5*(an3(i, j1) + an3(i1, j))
                if (ki .eq. 2) an3(i, j) = 0.5*(an3(i, j2) + an3(i1, j))
                if (ki .eq. 3) an3(i, j) = 0.5*(an3(i, j2) + an3(i2, j))
                if (ki .eq. 4) an3(i, j) = 0.5*(an3(i, j1) + an3(i2, j))
            end do
        end do

    end subroutine adv2d

end module advection_2d
