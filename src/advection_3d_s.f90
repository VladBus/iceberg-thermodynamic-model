! ==============================================================================
! Модуль: advection_3d_s
! Назначение: Трёхмерная адвекция солености (S) в океане.
! Физика: Решает уравнение конвекции для 3D-поля солености:
!           ∂S/∂t + u·∂S/∂x + v·∂S/∂y + w·∂S/∂z = 0
!         где:
!           S — соленость [массовая доля, безразм., ~0.033-0.035]
!           u,v [см/с] — горизонтальные компоненты скорости (U2, V2)
!           w [см/с] — вертикальная скорость
!
!         Алгоритм ИДЕНТИЧЕН advection_3d_t (только переменная — S вместо T):
!           1. Горизонтальный предиктор (X,Y) — upwind-схема 1-го порядка
!           2. Вертикальный перенос (Z) — неявная схема Томаса
!           3. Антидиффузионные потоки высокого порядка (X,Y,Z)
!           4. FCT-лимитер Залесака для X, Y, Z
!           5. Коррекция: S2 = CD
!
!         Схема FCT гарантирует:
!           - S ≥ 0 (нет отрицательных концентраций соли)
!           - S ≤ max(S_neighbors) (нет новых экстремумов)
!           - Консервативность массы соли
!
! Единицы (CGS для гидродинамики):
!   S1, S2  — соленость на шагах dt и dt1 [массовая доля, безразм.]
!   U2, V2  — компоненты скорости течения [см/с]
!   W       — вертикальная скорость [см/с]
!   dx      — горизонтальный шаг сетки [см] (= 1 389 000)
!   dz(k)   — толщина полного слоя [см]
!   dz1(k)  — толщина полуслоя [см] (расстояние между центрами уровней)
!   dt      — бароклинный шаг по времени [с] (= 3600)
!   c2 = dt/dx — число Куранта [безразм.]
!   adx, ady — вертикальные маски адвекции (1=вода, 0=дно)
!   apx, apy, apz — антидиффузионные потоки FCT
!   cd      — промежуточное поле предиктора
!   tt(k)   — временный массив горизонтального предиктора (переиспользуется)
!
! ВАЖНО: Массив tt(k) используется совместно с модулем advection_3d_t,
!   т.к. вызовы advs() и advt() не пересекаются во времени.
!   tt хранит горизонтальный предиктор для текущего столбца (i,j).
!
! Сетка: B-сетка Аракавы. Аналогична advection_3d_t.
! ==============================================================================

module advection_3d_s
    use param
    implicit none

contains

    subroutine advs(dt, c2)
        real, intent(in) :: dt        ! Бароклинный шаг по времени [с] (= 3600)
        real, intent(in) :: c2        ! Число Куранта = dt/dx [безразм.]

        ! Локальные переменные
        integer :: i, j, k, i1, i2, j1, j2, ki, k1
        real :: cc, ci1, ci2, cj1, cj2, up, uu, vp, vv, a, b
        real :: cdx, cdy, flxp, flyp, a1, b1
        real :: ck1, ck2, ww1, ww2, ww

        ! Обнуление массивов антидиффузионных потоков FCT
        apz(:, :, :) = 0.0    ! Потоки по вертикали Z
        apx(:, :, :) = 0.0    ! Потоки по горизонтали X
        apy(:, :, :) = 0.0    ! Потоки по горизонтали Y

        ! ================================================================
        ! ОСНОВНОЙ ЦИКЛ: ПРЕДИКТОР + ВЕРТИКАЛЬНЫЙ ПЕРЕНОС
        ! ================================================================
        ! Аналогично advection_3d_t, но для солености S2/S1.

        do j = 1, js
            j1 = j + 1
            j2 = max(1, j - 1)
            do i = 1, is
                ki = kt1(i, j)        ! Число мокрых уровней в столбце
                if (ki .eq. 0) cycle  ! Пропуск суши

                i1 = i + 1
                i2 = max(1, i - 1)

                ! --- ГОРИЗОНТАЛЬНЫЙ ПЕРЕНОС (upwind-схема 1-го порядка) ---
                do k = 1, ki
                    cc = s2(i, j, k)              ! S в текущей ячейке [массовая доля]
                    ci1 = s2(i1, j, k)            ! S в соседе по +Y (i+1)
                    ci2 = s2(i2, j, k)            ! S в соседе по -Y (i-1)
                    cj1 = s2(i, j1, k)            ! S в соседе по +X (j+1)
                    cj2 = s2(i, j2, k)            ! S в соседе по -X (j-1)

                    ! Скорости на гранях ячейки [см/с]
                    up = u2(i, j1, k)             ! U на X-грани (j+1/2)
                    uu = 0.5*(up + u2(i, j, k))   ! U в центре ячейки
                    vp = v2(i1, j, k)             ! V на Y-грани (i+1/2)
                    vv = 0.5*(vp + v2(i, j, k))   ! V в центре ячейки

                    ! --- Конвективный поток по X (upwind) ---
                    ! Аналогично T, но для S: F_x = u·S (upwind)
                    a = abs(uu)
                    cdx = 0.5*(uu + a)*adx(i, j, k)*(cc - cj2) &
                          + 0.5*(uu - a)*adx(i, j1, k)*(cj1 - cc)

                    ! --- Конвективный поток по Y ---
                    a = abs(vv)
                    cdy = 0.5*(vv + a)*ady(i1, j, k)*(cc - ci1) &
                          + 0.5*(vv - a)*ady(i, j, k)*(ci2 - cc)

                    ! --- Горизонтальный предиктор ---
                    ! TT(k) = S1 - c2·(CDX + CDY) [массовая доля]
                    tt(k) = s1(i, j, k) - c2*(cdx + cdy)

                    ! --- Антидиффузионные потоки FCT по X ---
                    ! APX = adx·(u·0.5·(S+Sj) - F_upwind) · c2
                    a = abs(up)
                    flxp = 0.5*(up + a)*cc + 0.5*(up - a)*cj1
                    apx(i, j1, k) = adx(i, j1, k)*(up*0.5*(cc + cj1) - flxp)*c2

                    ! Антидиффузионные потоки FCT по Y
                    a = abs(vp)
                    flyp = 0.5*(vp + a)*cc + 0.5*(vp - a)*ci1
                    apy(i1, j, k) = ady(i1, j, k)*(vp*0.5*(cc + ci1) - flyp)*c2
                end do

                ! --- ВЕРТИКАЛЬНЫЙ ПЕРЕНОС (неявная схема Томаса) ---
                ! Уравнение: ∂S/∂t + w·∂S/∂z = 0
                ! Дискретизация: CD(k) = TT(k) - dt·[w(k+1/2)·(S(k+1)-S(k))/dz(k+1)]
                ck2 = s2(i, j, 1)
                cc = ck2
                ww1 = w(i, j, 1)

                do k = 1, ki - 1
                    k1 = k + 1
                    ww2 = w(i, j, k1)
                    ww = 0.5*(ww1 + ww2)       ! W на границе k+1/2 [см/с]
                    a = abs(ww)
                    ck1 = s2(i, j, k1)
                    cd(i, j, k) = tt(k) - dt* &
                                  (0.5*(ww + a)*(cc - ck2)/dz(k) + 0.5*(ww - a)*(ck1 - cc)/dz(k1))
                    ck2 = cc
                    cc = ck1
                    ww1 = ww2
                end do

                cd(i, j, ki) = tt(ki)          ! Нижняя граница
                cc = s2(i, j, 1)

                ! --- Антидиффузионные потоки FCT по Z ---
                ! APZ = 0.5·w·(S(k-1)+S(k)) - 0.5·(|w|+w)·S(k-1) - 0.5·(|w|-w)·S(k)
                do k = 2, ki
                    ck1 = s2(i, j, k)
                    ww = w(i, j, k)
                    a = abs(ww)
                    apz(i, j, k) = 0.5*ww*(cc + ck1) - 0.5*(ww + a)*cc + 0.5*(ww - a)*ck1
                    cc = ck1
                end do
            end do
        end do

        ! ================================================================
        ! КОРРЕКЦИЯ ПОТОКОВ FCT ПО X (лимитер Залесака)
        ! ================================================================
        do j = 1, js
            do i = 1, is
                ki = idx(i, j)
                if (ki .eq. 0) cycle
                j1 = j + 1
                j2 = max(1, j - 1)

                do k = 1, ki
                    a1 = adx(i, j, k)*(cd(i, j, k) - cd(i, j2, k))
                    b1 = adx(i, j2, k)*(cd(i, j2, k) - cd(i, max(1, j - 2), k))
                    a = apx(i, j, k)
                    b = sign(1.0, a)
                    apx(i, j, k) = b*max(0.0, min(abs(a), b*a1, b*b1))
                end do
            end do
        end do

        do j = 1, js
            j1 = j + 1
            do i = 1, is
                ki = kt1(i, j)
                if (ki .eq. 0) cycle
                do k = 1, ki
                    cd(i, j, k) = cd(i, j, k) - (apx(i, j1, k) - apx(i, j, k))
                end do
            end do
        end do

        ! ================================================================
        ! КОРРЕКЦИЯ ПОТОКОВ FCT ПО Y (лимитер Залесака)
        ! ================================================================
        do j = 1, js
            do i = 1, is
                i1 = i + 1
                i2 = max(1, i - 1)
                ki = idy(i, j)
                if (ki .eq. 0) cycle

                do k = 1, ki
                    a1 = ady(i, j, k)*(cd(i, j, k) - cd(i2, j, k))
                    b1 = ady(i2, j, k)*(cd(i2, j, k) - cd(max(1, i - 2), j, k))
                    a = apy(i, j, k)
                    b = sign(1.0, a)
                    apy(i, j, k) = b*max(0.0, min(abs(a), b*a1, b*b1))
                end do
            end do
        end do

        do j = 1, js
            do i = 1, is
                i1 = i + 1
                ki = kt1(i, j)
                if (ki .eq. 0) cycle
                do k = 1, ki
                    cd(i, j, k) = cd(i, j, k) - (apy(i, j, k) - apy(i1, j, k))
                end do
            end do
        end do

        ! ================================================================
        ! КОРРЕКЦИЯ ПОТОКОВ FCT ПО Z (лимитер Залесака)
        ! ================================================================
        do j = 1, js
            do i = 1, is
                ki = kt1(i, j)
                if (ki .eq. 0) cycle

                if (ki .ge. 3) then
                    a1 = (cd(i, j, 2) - cd(i, j, 1))*dz1(2)/dt
                    a = apz(i, j, 2)
                    b = sign(1.0, a)
                    apz(i, j, 2) = b*max(0.0, min(abs(a), b*a1))

                    do k = 3, ki - 1
                        a1 = (cd(i, j, k) - cd(i, j, k - 1))*dz1(k)/dt
                        b1 = (cd(i, j, k - 1) - cd(i, j, k - 2))*dz1(k - 1)/dt
                        a = apz(i, j, k)
                        b = sign(1.0, a)
                        apz(i, j, k) = b*max(0.0, min(abs(a), b*a1, b*b1))
                    end do
                end if

                if (ki .ge. 2) then
                    a1 = (cd(i, j, ki) - cd(i, j, ki - 1))*dz1(ki)/dt
                    b1 = (cd(i, j, ki - 1) - cd(i, j, max(1, ki - 2)))*dz1(ki - 1)/dt
                    a = apz(i, j, ki)
                    b = sign(1.0, a)
                    apz(i, j, ki) = b*max(0.0, min(abs(a), b*a1, b*b1))
                end if
            end do
        end do

        ! Обновление CD после коррекции по Z
        do j = 1, js
            do i = 1, is
                ki = kt1(i, j)
                if (ki .eq. 0) cycle
                do k = 2, ki - 1
                    cd(i, j, k) = cd(i, j, k) - (apz(i, j, k + 1) - apz(i, j, k))*dt/dz1(k)
                end do
            end do
        end do

        ! Финальное обновление: S2 = CD [массовая доля]
        s2(:, :, :) = cd(:, :, :)

    end subroutine advs

end module advection_3d_s
