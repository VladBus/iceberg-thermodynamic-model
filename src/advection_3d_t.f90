! ==============================================================================
! Модуль: advection_3d_t
! Назначение: Трёхмерная адвекция температуры (T) в океане.
! Физика: Решает уравнение конвекции для 3D-поля температуры:
!           ∂T/∂t + u·∂T/∂x + v·∂T/∂y + w·∂T/∂z = 0
!         где:
!           T — температура [°C]
!           u,v [см/с] — горизонтальные компоненты скорости (U2, V2)
!           w [см/с] — вертикальная скорость
!
!         Алгоритм: Flux-Corrected Transport (FCT) Бориса-Бука
!         с лимитером Залесака (Zalesak, 1979) в трёх измерениях:
!
!           ЭТАП 1: Горизонтальный предиктор (X, Y)
!             TT(k) = T1(i,j,k) - c2·(F_x + F_y)
!             F_x = 0.5·(u+|u|)·adx·(T-TWest) + 0.5·(u-|u|)·adx·(TEast-T)
!             (upwind-схема, комбинация двух направлений)
!             Антидиффузионные потоки: APX = adx·(u·0.5·(T+Tj) - F_upwind)·c2
!
!           ЭТАП 2: Вертикальный предиктор (Z) — неявная схема Томаса
!             CD(k) = TT(k) - dt·[0.5·(w+|w|)·(T(k)-T(k-1))/dz(k)
!                              + 0.5·(w-|w|)·(T(k+1)-T(k))/dz(k+1)]
!             Вертикальная часть неявная → без ограничения по CFL для w.
!
!           ЭТАП 3: FCT-лимитер Залесака для X, Y, Z
!             APX = sign(APX)·max(0, min(|APX|, P+, P-))
!             Для Z: P+ = (CD(k)-CD(k-1))·dz1(k)/dt
!
!           ЭТАП 4: Коррекция
!             CD_new = CD - (APX(j+1)-APX(j)) - (APY(i+1)-APY(i)) - (APZ(k+1)-APZ(k))·dt/dz1
!             T2 = CD (финальное обновление)
!
! Единицы (CGS для гидродинамики, °C для температуры):
!   T1, T2  — температура на шагах dt и dt1 [°C]
!   U2, V2  — компоненты скорости течения [см/с]
!   W       — вертикальная скорость [см/с]
!   dx      — горизонтальный шаг сетки [см] (= 1 389 000)
!   dz(k)   — толщина полного слоя [см] (из param: dz(1)=500, ..., dz(18)=10000)
!   dz1(k)  — толщина полуслоя [см] (расстояние между центрами уровней)
!   dt      — бароклинный шаг по времени [с] (= 3600)
!   c2 = dt/dx — число Куранта [безразм.]
!   adx, ady — вертикальные маски адвекции (1=вода, 0=дно) [безразм.]
!   apx, apy, apz — антидиффузионные потоки FCT [°C·см/с]
!   cd      — промежуточное поле предиктора [°C]
!   tt(k)   — временный массив горизонтального предиктора [°C]
!
! Сетка: B-сетка Аракавы. T-точки (центры ячеек).
!   U2(i,j1,k) — скорость U на X-грани (j+1/2)
!   V2(i1,j,k) — скорость V на Y-грани (i+1/2)
!   W(i,j,k)   — вертикальная скорость на Z-грани (k+1/2)
!
! Стабильность:
!   Горизонтальная часть: CFL-условие |u|·dt/dx < 1 → обеспечивается dt=3600, dx=1.389e6
!   Вертикальная часть: неявная → без CFL-ограничения по w.
! ==============================================================================

module advection_3d_t
    use param
    implicit none

contains

    subroutine advt(dt, c2)
        real, intent(in) :: dt        ! Бароклинный шаг по времени [с] (= 3600)
        real, intent(in) :: c2        ! Число Куранта = dt/dx [безразм.]

        ! Локальные переменные
        integer :: i, j, k, i1, i2, j1, j2, ki, k1
        real :: cc, ci1, ci2, cj1, cj2, up, uu, vp, vv, a, b
        real :: cdx, cdy, flxp, flyp, a1, b1
        real :: ck1, ck2, ww1, ww2, ww

        ! Обнуление массивов антидиффузионных потоков FCT
        apz(:, :, :) = 0.0    ! Потоки по вертикали Z [°C·см/с]
        apx(:, :, :) = 0.0    ! Потоки по горизонтали X [°C·см/с]
        apy(:, :, :) = 0.0    ! Потоки по горизонтали Y [°C·см/с]

        ! ================================================================
        ! ОСНОВНОЙ ЦИКЛ: ПРЕДИКТОР + ВЕРТИКАЛЬНЫЙ ПЕРЕНОС
        ! ================================================================
        ! Для каждой ячейки (i,j):
        !   1. Горизонтальный предиктор по X и Y (explicit upwind)
        !   2. Вертикальный перенос (неявная схема Томаса)

        do j = 1, js
            j1 = j + 1
            j2 = max(1, j - 1)
            do i = 1, is
                ki = kt1(i, j)        ! Число мокрых уровней в столбце
                if (ki .eq. 0) cycle  ! Пропуск суши

                i1 = i + 1
                i2 = max(1, i - 1)

                ! --- ГОРИЗОНТАЛЬНЫЙ ПЕРЕНОС (upwind-схема 1-го порядка) ---
                do k = 1, ki
                    cc = t2(i, j, k)              ! T в текущей ячейке [°C]
                    ci1 = t2(i1, j, k)            ! T в соседе по +Y (i+1)
                    ci2 = t2(i2, j, k)            ! T в соседе по -Y (i-1)
                    cj1 = t2(i, j1, k)            ! T в соседе по +X (j+1)
                    cj2 = t2(i, j2, k)            ! T в соседе по -X (j-1)

                    ! Скорости на гранях ячейки [см/с]
                    up = u2(i, j1, k)             ! U на X-грани (j+1/2)
                    uu = 0.5*(up + u2(i, j, k))   ! U в центре ячейки (среднее)
                    vp = v2(i1, j, k)             ! V на Y-грани (i+1/2)
                    vv = 0.5*(vp + v2(i, j, k))   ! V в центре ячейки

                    ! --- Конвективный поток по X ---
                    ! CDX = 0.5·(u+|u|)·adx(i,j)·(T-TWest) + 0.5·(u-|u|)·adx(i,j+1)·(TEast-T)
                    ! При u>0: CDX = u·adx·(T-TWest) (из западной ячейки)
                    ! При u<0: CDX = u·adx·(TEast-T) (из восточной ячейки)
                    a = abs(uu)
                    cdx = 0.5*(uu + a)*adx(i, j, k)*(cc - cj2) &   ! u>0 часть
                          + 0.5*(uu - a)*adx(i, j1, k)*(cj1 - cc)   ! u<0 часть

                    ! --- Конвективный поток по Y ---
                    a = abs(vv)
                    cdy = 0.5*(vv + a)*ady(i1, j, k)*(cc - ci1) &
                          + 0.5*(vv - a)*ady(i, j, k)*(ci2 - cc)

                    ! --- Горизонтальный предиктор ---
                    ! TT(k) = T1 - c2·(CDX + CDY) [°C]
                    tt(k) = t1(i, j, k) - c2*(cdx + cdy)

                    ! --- Антидиффузионные потоки FCT по X ---
                    ! APX = adx·(u·0.5·(T+Tj) - F_upwind) · c2
                    ! где F_upwind = 0.5·(u+|u|)·T + 0.5·(u-|u|)·Tj
                    a = abs(up)
                    flxp = 0.5*(up + a)*cc + 0.5*(up - a)*cj1    ! Upwind flux
                    apx(i, j1, k) = adx(i, j1, k)*(up*0.5*(cc + cj1) - flxp)*c2

                    ! Антидиффузионные потоки FCT по Y
                    a = abs(vp)
                    flyp = 0.5*(vp + a)*cc + 0.5*(vp - a)*ci1
                    apy(i1, j, k) = ady(i1, j, k)*(vp*0.5*(cc + ci1) - flyp)*c2
                end do

                ! --- ВЕРТИКАЛЬНЫЙ ПЕРЕНОС (неявная схема Томаса) ---
                ! Уравнение: ∂T/∂t + w·∂T/∂z = 0
                ! Дискретизация: CD(k) = TT(k) - dt·[w(k+1/2)·(T(k+1)-T(k))/dz(k+1)]
                !   Это трёхдиагональная система (implicit scheme), решаемая
                !   методом Томаса (прямой + обратный ход).
                ! Преимущество: без CFL-ограничения по вертикальной скорости w.

                ck2 = t2(i, j, 1)     ! T на нижней границе (k=0)
                cc = ck2               ! T текущего уровня
                ww1 = w(i, j, 1)      ! W на верхней границе первого слоя

                do k = 1, ki - 1
                    k1 = k + 1
                    ww2 = w(i, j, k1)            ! W на границе k+1/2 [см/с]
                    ww = 0.5*(ww1 + ww2)         ! W в центре слоя [см/с]
                    a = abs(ww)
                    ck1 = t2(i, j, k1)           ! T на уровне k+1

                    ! Трёхдиагональная дискретизация:
                    ! CD(k) = TT(k) - dt·[0.5·(w+|w|)·(T(k)-T(k-1))/dz(k)
                    !                     + 0.5·(w-|w|)·(T(k+1)-T(k))/dz(k+1)]
                    cd(i, j, k) = tt(k) - dt* &
                                  (0.5*(ww + a)*(cc - ck2)/dz(k) + 0.5*(ww - a)*(ck1 - cc)/dz(k1))
                    ck2 = cc
                    cc = ck1
                    ww1 = ww2
                end do

                cd(i, j, ki) = tt(ki)          ! Нижняя граница: CD(ki) = TT(ki)
                cc = t2(i, j, 1)               ! Сброс для расчёта APZ

                ! --- Антидиффузионные потоки FCT по Z ---
                ! APZ(k) = 0.5·w·(T(k-1)+T(k)) - 0.5·(|w|+w)·T(k-1) - 0.5·(|w|-w)·T(k)
                ! При w>0: APZ = w·T(k-1) (из нижнего слоя)
                ! При w<0: APZ = w·T(k)   (из верхнего слоя)
                do k = 2, ki
                    ck1 = t2(i, j, k)
                    ww = w(i, j, k)
                    a = abs(ww)
                    apz(i, j, k) = 0.5*ww*(cc + ck1) - 0.5*(ww + a)*cc + 0.5*(ww - a)*ck1
                    cc = ck1
                end do
            end do
        end do

        ! ================================================================
        ! КОРРЕКЦИЯ ПОТОКОВ FCT ПО X (лимитер Залесака)
        ! ================================================================
        ! APX(i,j) = sign(APX) · max(0, min(|APX|, P+, P-))
        ! где P+ = adx(i,j)·(CD(i,j)-CD(i,j-1))
        !      P- = adx(i,j-1)·(CD(i,j-1)-CD(i,j-2))
        ! В отличие от 2D-схемы, здесь P+/P- включают маску adx для учёта дна.
        do j = 1, js
            do i = 1, is
                ki = idx(i, j)              ! Маска X-грани
                if (ki .eq. 0) cycle
                j1 = j + 1
                j2 = max(1, j - 1)

                do k = 1, ki
                    a1 = adx(i, j, k)*(cd(i, j, k) - cd(i, j2, k))
                    b1 = adx(i, j2, k)*(cd(i, j2, k) - cd(i, max(1, j - 2), k))
                    a = apx(i, j, k)
                    b = sign(1.0, a)
                    apx(i, j, k) = b*max(0.0, min(abs(a), b*a1, b*b1))
                end do
            end do
        end do

        ! Обновление CD после коррекции по X: CD -= ∇·APX
        do j = 1, js
            j1 = j + 1
            do i = 1, is
                ki = kt1(i, j)
                if (ki .eq. 0) cycle
                do k = 1, ki
                    cd(i, j, k) = cd(i, j, k) - (apx(i, j1, k) - apx(i, j, k))
                end do
            end do
        end do

        ! ================================================================
        ! КОРРЕКЦИЯ ПОТОКОВ FCT ПО Y (лимитер Залесака)
        ! ================================================================
        do j = 1, js
            do i = 1, is
                i1 = i + 1
                i2 = max(1, i - 1)
                ki = idy(i, j)              ! Маска Y-грани
                if (ki .eq. 0) cycle

                do k = 1, ki
                    a1 = ady(i, j, k)*(cd(i, j, k) - cd(i2, j, k))
                    b1 = ady(i2, j, k)*(cd(i2, j, k) - cd(max(1, i - 2), j, k))
                    a = apy(i, j, k)
                    b = sign(1.0, a)
                    apy(i, j, k) = b*max(0.0, min(abs(a), b*a1, b*b1))
                end do
            end do
        end do

        ! Обновление CD после коррекции по Y
        do j = 1, js
            do i = 1, is
                i1 = i + 1
                ki = kt1(i, j)
                if (ki .eq. 0) cycle
                do k = 1, ki
                    cd(i, j, k) = cd(i, j, k) - (apy(i, j, k) - apy(i1, j, k))
                end do
            end do
        end do

        ! ================================================================
        ! КОРРЕКЦИЯ ПОТОКОВ FCT ПО Z (лимитер Залесака)
        ! ================================================================
        ! Для Z лимитер использует нормализованные разности:
        !   P+ = (CD(k)-CD(k-1))·dz1(k)/dt
        !   P- = (CD(k-1)-CD(k-2))·dz1(k-1)/dt
        ! Нормализация на dz1/dt обеспечивает согласованность размерностей
        ! с потоками APZ, которые имеют размерность [°C·см/с].
        do j = 1, js
            do i = 1, is
                ki = kt1(i, j)
                if (ki .eq. 0) cycle

                if (ki .ge. 3) then
                    ! Внутренние слои (k=2..ki-1): двухсторонний лимитер
                    a1 = (cd(i, j, 2) - cd(i, j, 1))*dz1(2)/dt    ! P+ для k=2
                    a = apz(i, j, 2)
                    b = sign(1.0, a)
                    apz(i, j, 2) = b*max(0.0, min(abs(a), b*a1))

                    do k = 3, ki - 1
                        a1 = (cd(i, j, k) - cd(i, j, k - 1))*dz1(k)/dt    ! P+
                        b1 = (cd(i, j, k - 1) - cd(i, j, k - 2))*dz1(k - 1)/dt  ! P-
                        a = apz(i, j, k)
                        b = sign(1.0, a)
                        apz(i, j, k) = b*max(0.0, min(abs(a), b*a1, b*b1))
                    end do
                end if

                if (ki .ge. 2) then
                    ! Нижний слой (k=ki): двухсторонний лимитер
                    a1 = (cd(i, j, ki) - cd(i, j, ki - 1))*dz1(ki)/dt
                    b1 = (cd(i, j, ki - 1) - cd(i, j, max(1, ki - 2)))*dz1(ki - 1)/dt
                    a = apz(i, j, ki)
                    b = sign(1.0, a)
                    apz(i, j, ki) = b*max(0.0, min(abs(a), b*a1, b*b1))
                end if
            end do
        end do

        ! Обновление CD после коррекции по Z
        ! CD_new = CD - (APZ(k+1) - APZ(k))·dt/dz1(k)
        ! Множитель dt/dz1 конвертирует поток [°C·см/с] в приращение [°C]
        do j = 1, js
            do i = 1, is
                ki = kt1(i, j)
                if (ki .eq. 0) cycle
                do k = 2, ki - 1
                    cd(i, j, k) = cd(i, j, k) - (apz(i, j, k + 1) - apz(i, j, k))*dt/dz1(k)
                end do
            end do
        end do

        ! Финальное обновление: T2 = CD [°C]
        t2(:, :, :) = cd(:, :, :)

    end subroutine advt

end module advection_3d_t
