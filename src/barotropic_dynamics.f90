! ==============================================================================
! Модуль: barotropic_dynamics (advsh)
! Назначение: Адвекция баротропных интегральных потоков UP2/VP2.
!             Двумерный перенос импульса мелкой воды (интегральных потоков).
! Физика: Решает уравнение конвекции для интегральных потоков:
!           ∂U/∂t + ∂(UU/H)/∂x + ∂(VU/H)/∂y = 0
!           ∂V/∂t + ∂(UV/H)/∂x + ∂(VV/H)/∂y = 0
!         где U [см²/с] — интегральный поток (U = ∫u·dz), H [см] — глубина,
!         U/H [см/с] — средняя скорость. Это транспортная форма уравнения
!         для баротропного импульса в схеме расщепления (splitting method):
!         сначала рассчитывается баротропный цикл (shallow_water), затем
!         выполняется адвекция интегральных потоков этой схемой.
!
!         Алгоритм: Схема Лейса-Рихтмайера (Lax-Wendroff предиктор) +
!         коррекция потоков FCT (Flux-Corrected Transport) Бориса-Бука
!         с лимитером Залесака для монотонности.
!
!         Порядок по X (компоненты UP2):
!           1. Предиктор: CD2 = U - 0.5·(dt/dx)·(CDX + CDY)
!              где CDX = u_avg·(U_j+1 + U_j-1) + |u_avg|·(U_j+1 - U_j-1)  [ sincerely Lax-Wendroff ]
!           2. Антидиффузионные потоки APX2/APY2 (обнулены — см. комментарий).
!           3. FCT-лимитер Залесака: APX = sign(APX)·max(0, min(|APX|, P+, P-))
!           4. Коррекция: UP2 = CD2 - (APX(j+1) - APX(j)) - (APY(i+1) - APY(i))
!         Порядок по Y (компоненты VP2) — аналогичен, но с полным учётом
!         поперечного потока CDY (в отличие от X-блока, где CDY*0).
!
!         ВАЖНО: Антидиффузионные потоки FCT в оригинальном коде Nesterov
!         обнулены (неинициализированные переменные → нули). Это эквивалентно
!         отключению FCT. Восстановление этих потоков приводило к численной
!         неустойчивости при ненулевом форсинге.
!
! Единицы (CGS для гидродинамики):
!   UP2, VP2 — интегральные потоки [см²/с] (= ∫u·dz, где u [см/с], dz [см])
!   HU, HV   — глубины на U/V-гранях ячейки [см]
!   dt1      — баротропный шаг по времени [с] (= 120 с)
!   dx       — пространственный шаг сетки [см] (= 1 389 000 см ≈ 13.89 км)
!   c10      — число Куранта для баротропного шага [с/см] = dt1/dx
!   a        — скорость потока на U-грани [см/с] = UP2/HU
!   v11,v12  — суммы VP2 по 4 соседним ячейкам для косвенного потока [см²/с]
!   cdx/cdy  — конвективные flux-divergence [см³/с²]
!
! Сетка: B-сетка Аракавы (Arakawa B-grid).
!   X-компонента (UP2) определена на U-гранях (j-направление).
!   Y-компонента (VP2) определена на V-гранях (i-направление).
!   Оси: X ↔ j, Y ↔ i (ось Y инвертирована: j=1 — север).
!
! Ответственность: Обновление UP2/VP2 внутри баротропного цикла shal().
! ==============================================================================

module barotropic_dynamics
    use param
    implicit none

    ! Пространственный шаг сетки из спецификации модели (~13.89 км).
    ! dx = 1 389 000 см (система единиц CGS).
    ! Используется только для вычисления числа Куранта c10 = dt1/dx.
    real, parameter, private :: dx = 1389000.0

contains

    subroutine advsh(dt1)
        real, intent(in) :: dt1    ! Шаг по времени баротропной моды [с] (= 120 с)

        ! Локальные переменные
        integer :: i, j, i1, j1, i2, j2
        real :: hht, uij, uu1, uu2, uu3, uu4, v11, v12, a, u11, u12
        real :: cdx, cdy, a1, b1, a2, b2, b
        real :: vij, vv1, vv2, vv3, vv4

        ! Восстановленные переменные для схемы Лейса-Рихтмайера.
        ! В оригинальном коде these переменные не инициализируются в X-блоке,
        ! поэтому антидиффузионные потоки APX2/APY2 = 0 (FCT выключен).
        real :: c10, ujp, uu, uj1, flxp, flyp, vip, ui1, uip
        real :: vjp, vj1, vi2, vv

        ! --- ИНИЦИАЛИЗАЦИЯ РАБОЧИХ МАССИВОВ ---
        ! CD2 — предиктор (первый шаг Лейса-Рихтмайера) для U или V.
        !       Хранит промежуточное значение интегрального потока [см²/с].
        ! APX2, APY2 — антидиффузионные потоки FCT по осям X и Y [см³/с²].
        !              Обнулены (FCT выключен в оригинале).
        cd2(:, :) = 0.0
        apx2(:, :) = 0.0
        apy2(:, :) = 0.0

        ! --- ЧИСЛО КУРАНТА ДЛЯ БАРОТРОПНОГО ШАГА ---
        ! c10 = dt1/dx [с/см] — отношение временного шага к пространственному.
        ! Используется в формуле предиктора: CD2 = U - c10*0.5*(CDX+CDY).
        c10 = dt1/dx

        ! ================================================================
        ! X-COORDINATE: РАСЧЕТ ИНТЕГРАЛЬНОГО ПОТОКА UP2
        ! ================================================================
        ! Цикл по U-точкам (j = 3..JS2, i = 2..IS2).
        ! Интегральный поток UP2 определён на U-грани (j+1/2).
        ! Ячейки с hht = 8888.0 — суша (маска); kush(i,j) = 0 — берег.

        do j = 3, js2
            do i = 2, is2
                hht = hu(i, j)                       ! Глубина на U-грани [см]
                if (abs(hht - 8888.0) .lt. 1e-8) cycle   ! Пропуск суши
                ! Вне маски U предиктор и скорость a не определены; FCT-поток нулевой.
                if (kush(i, j) .eq. 0) cycle

                i1 = i + 1
                i2 = i - 1
                j1 = j + 1
                j2 = j - 1

                ! Соседние интегральные потоки UP2 [см²/с]
                uij = up2(i, j)     ! Текущая U-ячейка
                uu1 = up2(i, j1)    ! Сосед по +Y (j+1/2)
                uu2 = up2(i, j2)    ! Сосед по -Y (j-1/2)
                uu3 = up2(i2, j)    ! Сосед по -X (i-1/2)
                uu4 = up2(i1, j)    ! Сосед по +X (i+1/2)

                ! --- КОСВЕННЫЙ КОНВЕКТИВНЫЙ ПОТОК (V-компоненты на U-грани) ---
                ! Суммы VP2 по 4 соседним V-ячейкам для вычисления V-скорости
                ! на U-грани (усреднение по 4 углам ячейки) [см²/с].
                v11 = vp2(i, j)/hv(i, j) + vp2(i, j2)/hv(i, j2)
                v12 = vp2(i1, j)/hv(i1, j) + vp2(i1, j2)/hv(i1, j2)

                ! Средняя скорость потока U на U-грани [см/с]
                a = uij/hht

                ! Адведированные U-скорости на соседних гранях [см/с]
                u11 = uu1/hu(i, j1) + a     ! U на (j+1/2)+1/2
                u12 = a + uu2/hu(i, j2)     ! U на (j+1/2)-1/2

                ! --- КОНВЕКТИВНЫЕ ПОТОКИ (Lax-Wendroff Flux) ---
                ! cdx — расходимость конвективного потока по X [см³/с²]:
                !   CDX = u_avg·(U_j+1 + U_j-1) + |u_avg|·(U_j+1 - U_j-1)
                !   Это комбинация центральных разностей и upwind-коррекции.
                ! cdy — косвенный (поперечный) конвективный поток [см³/с²]:
                !   CDY = v_avg·(U_i+1 + U_i-1) + |v_avg|·(U_i+1 - U_i-1)
                cdx = u11*(uij + uu1) + abs(u11)*(uij - uu1) - &
                      u12*(uij + uu2) - abs(u12)*(uu2 - uij)
                cdy = v11*(uij + uu3) + abs(v11)*(uij - uu3) - &
                      v12*(uij + uu4) - abs(v12)*(uu4 - uij)

                ! --- ПРЕДИКТОР ЛЕЙСА-РИХТМАЙЕРА ---
                ! CD2 = U - 0.5·(dt/dx)·(CDX + CDY*0)
                ! ВАЖНО: Поперечный поток CDY домножается на 0.0 — в оригинальном
                ! коде Advsh.f90 X-блок игнорирует поперечную конвекцию.
                ! Это не влияет на консервативность, т.к. полный CDY учитывается
                ! в Y-блоке (для VP2).
                cd2(i, j) = uij - c10*0.5*(cdx + 0.0*cdy)

                ! --- АНТИДИФФУЗИОННЫЕ ПОТОКИ FCT (ОБНУЛЕНЫ) ---
                ! В оригинальном Advsh.f90 промежуточные переменные (UJP, UU, UJ1,
                ! UI1, UIP, VIP) в X-блоке НЕ инициализируются, поэтому равны нулю
                ! и антидиффузионные потоки APX2/APY2 здесь нулевые (эквивалент флагу
                ! off). Восстановление этих переменных интерполяциями включало
                ! антидиффузию FCT, которой в оригинале не было, и приводило к
                ! численной неустойчивости (взрыву) при ненулевом форсинге.
                ujp = 0.0
                uu = 0.0
                uj1 = 0.0
                ui1 = 0.0
                uip = 0.0
                vip = 0.0

                ! Вычисление APX2 (антидиффузионный поток по X на j+1/2)
                if (j .ne. js) then
                    if (ujp .ge. 0.0) then
                        flxp = ujp*uu             ! Upwind flux (определяется направлением)
                    else
                        flxp = ujp*uj1
                    end if
                    apx2(i, j1) = (ujp*ujp - flxp)*a
                end if

                ! Вычисление APY2 (антидиффузионный поток по Y на i+1/2)
                if (i .ne. is) then
                    if (vip .ge. 0.0) then
                        flyp = vip*ui1
                    else
                        flyp = vip*uu
                    end if
                    apy2(i1, j) = (uip*vip - flyp)*a
                end if
            end do
        end do

        ! --- FCT-ЛИМИТЕР ЗАЛЕСАКА ПО X ---
        ! Ограничивает антидиффузионные потоки APX2, чтобы не нарушать
        ! монотонность (не создавать новых экстремумов).
        ! Формула: APX = sign(APX) · max(0, min(|APX|, P+, P-))
        ! где P+ = cd2(i,j+1) - cd2(i,j), P- = cd2(i,j-1) - cd2(i,j-2)
        ! (градиенты поля-предиктора вдоль направления потока).
        do j = 3, js
            do i = 2, is2
                j2 = j - 1
                a2 = hu(i, j)
                b2 = hu(i, j2)
                if (abs(a2 - 8888.0) .lt. 1e-8 .or. abs(b2 - 8888.0) .lt. 1e-8) then
                    apx2(i, j) = 0.0    ! На берегу — поток нулевой
                else
                    a1 = cd2(i, j + 1) - cd2(i, j)      ! P+ (впереди по потоку)
                    b1 = cd2(i, j2) - cd2(i, max(1, j - 2))  ! P- (позади по потоку)
                    a = apx2(i, j)
                    b = sign(1.0, a)                      ! Знак потока
                    apx2(i, j) = b*max(0.0, min(abs(a), b*a1, b*b1))
                end if
            end do
        end do

        ! --- ОБНОВЛЕНИЕ CD2 ПОСЛЕ КОРРЕКЦИИ ПО X ---
        ! CD2_new = CD2_old - ∇·(APX) = CD2 - (APX(j+1) - APX(j))
        do j = 3, js2
            j1 = j + 1
            do i = 2, is2
                if (kush(i, j) .eq. 0) cycle
                cd2(i, j) = cd2(i, j) - (apx2(i, j1) - apx2(i, j))
            end do
        end do

        ! ================================================================
        ! Y-COORDINATE: КОРРЕКЦИЯ ПОТОКОВ FCT ПО Y (ДЛЯ UP2)
        ! ================================================================
        ! Лимитер Залесака по оси Y для компоненты UP2.
        ! Аналогично X-блоку, но используется ось i (Y-направление).

        do j = 3, js2
            do i = 3, is2
                i1 = i + 1
                i2 = i - 1
                a2 = hu(i, j)
                b2 = hu(i2, j)
                if (abs(a2 - 8888.0) .lt. 1e-8 .or. abs(b2 - 8888.0) .lt. 1e-8) then
                    apy2(i, j) = 0.0
                else
                    a1 = cd2(i, j) - cd2(i1, j)      ! P+ по Y
                    b1 = cd2(max(1, i - 2), j) - cd2(i2, j)  ! P- по Y
                    a = apy2(i, j)
                    b = sign(1.0, a)
                    apy2(i, j) = b*max(0.0, min(abs(a), b*a1, b*b1))
                end if
            end do
        end do

        ! --- ФИНАЛЬНОЕ ОБНОВЛЕНИЕ UP2 ---
        ! UP2_new = CD2 - ∇·(APY) = CD2 - (APY(i+1) - APY(i))
        do j = 3, js2
            do i = 2, is2
                i1 = i + 1
                if (kush(i, j) .eq. 0) cycle
                up2(i, j) = cd2(i, j) - (apy2(i, j) - apy2(i1, j))
            end do
        end do

        ! ================================================================
        ! РАСЧЕТ ДЛЯ КОМПОНЕНТЫ V (VP2)
        ! ================================================================
        ! Аналогичная процедура для Y-компонента интегральных потоков VP2.
        ! Отличие: в Y-блоке поперечный поток CDX учитывается ПОЛНОСТЬЮ
        ! (в отличие от X-блока, где CDY*0). Это соответствует оригиналу.

        ! Сброс массивов
        cd2(:, :) = 0.0
        apx2(:, :) = 0.0
        apy2(:, :) = 0.0

        do j = 2, js2
            do i = 3, is2
                hht = hv(i, j)                       ! Глубина на V-грани [см]
                if (abs(hht - 8888.0) .lt. 1e-8) cycle
                ! Аналогично U: исключаем неактивную V-грань из FCT-стенсила.
                if (kvsh(i, j) .eq. 0) cycle

                i1 = i + 1
                i2 = i - 1
                j1 = j + 1
                j2 = j - 1

                vij = vp2(i, j)
                vv1 = vp2(i2, j)     ! Сосед по -X
                vv2 = vp2(i1, j)     ! Сосед по +X
                vv3 = vp2(i, j1)     ! Сосед по +Y
                vv4 = vp2(i, j2)     ! Сосед по -Y

                ! Косвенный конвективный поток (U-компоненты на V-грани)
                u11 = up2(i2, j1)/hu(i2, j1) + up2(i, j1)/hu(i, j1)
                u12 = up2(i, j)/hu(i, j) + up2(i2, j)/hu(i2, j)

                ! Средняя скорость VP2 на V-грани [см/с]
                a = vij/hht

                v11 = vv1/hv(i2, j) + a
                v12 = a + vv2/hv(i1, j)

                ! Конвективные потоки по X и Y
                cdx = u11*(vij + vv3) + abs(u11)*(vij - vv3) - &
                      u12*(vij + vv4) - abs(u12)*(vv4 - vij)
                cdy = v11*(vij + vv1) + abs(v11)*(vij - vv1) - &
                      v12*(vij + vv2) - abs(v12)*(vv2 - vij)

                ! Предиктор: CD2 = V - 0.5·(dt/dx)·(CDX + CDY)
                ! В Y-блоке оба потока учтены (в отличие от X-блока)
                cd2(i, j) = vij - c10*0.5*(cdx + cdy)

                ! Антидиффузионные потоки FCT — обнулены (см. комментарий выше)
                vv = 0.0
                vj1 = 0.0
                vi2 = 0.0
                vjp = 0.0
                vip = 0.0
                ujp = 0.0

                if (j .ne. js) then
                    if (ujp .ge. 0.0) then
                        flxp = ujp*vv
                    else
                        flxp = ujp*vj1
                    end if
                    apx2(i, j1) = (ujp*vjp - flxp)*a
                end if

                if (i .ne. is) then
                    if (vip .ge. 0.0) then
                        flyp = vip*vv
                    else
                        flyp = vip*vi2
                    end if
                    apy2(i1, j) = (vip*vip - flyp)*a
                end if
            end do
        end do

        ! FCT-лимитер Залесака по X для V
        do j = 3, js2
            do i = 3, is2
                j2 = j - 1
                a2 = hv(i, j)
                b2 = hv(i, j2)
                if (abs(a2 - 8888.0) .lt. 1e-8 .or. abs(b2 - 8888.0) .lt. 1e-8) then
                    apx2(i, j) = 0.0
                else
                    a1 = cd2(i, j + 1) - cd2(i, j)
                    b1 = cd2(i, j2) - cd2(i, max(1, j - 2))
                    a = apx2(i, j)
                    b = sign(1.0, a)
                    apx2(i, j) = b*max(0.0, min(abs(a), b*a1, b*b1))
                end if
            end do
        end do

        ! Обновление CD2 для V после коррекции по X
        do j = 2, js2
            j1 = j + 1
            do i = 3, is2
                if (kvsh(i, j) .eq. 0) cycle
                cd2(i, j) = cd2(i, j) - (apx2(i, j1) - apx2(i, j))
            end do
        end do

        ! FCT-лимитер Залесака по Y для V
        do j = 2, js2
            do i = 3, is
                i1 = i + 1
                i2 = i - 1
                a2 = hv(i, j)
                b2 = hv(i2, j)
                if (abs(a2 - 8888.0) .lt. 1e-8 .or. abs(b2 - 8888.0) .lt. 1e-8) then
                    apy2(i, j) = 0.0
                else
                    a1 = cd2(i, j) - cd2(min(is1, i1), j)
                    b1 = cd2(max(1, i - 2), j) - cd2(i2, j)
                    a = apy2(i, j)
                    b = sign(1.0, a)
                    apy2(i, j) = b*max(0.0, min(abs(a), b*a1, b*b1))
                end if
            end do
        end do

        ! Финальное обновление VP2
        do j = 2, js2
            do i = 3, is2
                i1 = i + 1
                if (kvsh(i, j) .eq. 0) cycle
                vp2(i, j) = cd2(i, j) - (apy2(i, j) - apy2(i1, j))
            end do
        end do

    end subroutine advsh

end module barotropic_dynamics
