! ==============================================================================
! Модуль: grid_masks (ikuv)
! Назначение: Вычисляет локальные маски IKU, IKV (число водных соседей)
!             для узлов U и V на основе полей глубин HU, HV.
! Физика: Определяет характер гидродинамических граничных условий на B-сетке Аракавы:
!         - IKU/IKV = 4: внутренняя точка (4 водных соседа) — free-slip (скольжение).
!         - IKU/IKV = 1..3: прибрежная точка — no-slip (прилипание/трение).
!         - IKU/IKV = 1 (минимум) гарантирует, что делитель не станет нулем
!           при усреднении скоростей в shallow_water.
!         Эти маски используются в shallow_water для усреднения V/U при расчете
!         баротропных скоростей (переменные UUK, VKV в модуле shallow_water).
! Геометрия B-сетки: U-точки на гранях J (X-направление), V-точки на гранях I (Y).
! Ответственность: Подготовка геометрического базиса для граничных условий.
!                  Защита алгоритма от вычислений в фиктивных ячейках суши.
! ==============================================================================

module grid_masks
    use param
    implicit none

contains

    subroutine ikuv()
        ! Локальные переменные
        integer :: i, j, isum
        real :: gu1, gu2, gu3, gu4

        ! Первичная инициализация масок: 4 = внутренняя точка (все соседи вода).
        iku(:, :) = 4
        ikv(:, :) = 4

        ! --- РАСЧЕТ МАСКИ IKU (для U-компоненты скорости) ---
        ! U-точка (i,j) находится на грани между j и j-1 по X.
        ! Имеет 4 V-соседа: HV(i,j-1), HV(i,j), HV(i+1,j), HV(i+1,j-1).
        ! Цикл по i=1..IS1-1, j=2..JS1 (все U-точки внутренней области).
        do j = 2, js1
            do i = 1, is1 - 1
                ! Пропуск ячеек суши (HU=8888 — маркер суши)
                if (abs(hu(i, j) - 8888.0) .lt. 1e-8) cycle

                ! Глубины 4 соседних V-точек
                gu1 = hv(i, j - 1)     ! V-сосед юго-запад
                gu2 = hv(i, j)         ! V-сосед северо-запад
                gu3 = hv(i + 1, j)     ! V-сосед северо-восток
                gu4 = hv(i + 1, j - 1) ! V-сосед юго-восток

                isum = 4
                if (abs(gu1 - 8888.0) .lt. 1e-8) isum = isum - 1
                if (abs(gu2 - 8888.0) .lt. 1e-8) isum = isum - 1
                if (abs(gu3 - 8888.0) .lt. 1e-8) isum = isum - 1
                if (abs(gu4 - 8888.0) .lt. 1e-8) isum = isum - 1

                ! Минимум 1 — защита от деления на ноль в shallow_water
                ! (деление на IKU/IKV при усреднении скоростей).
                if (isum .eq. 0) isum = 1
                iku(i, j) = isum
            end do
        end do

        ! --- РАСЧЕТ МАСКИ IKV (для V-компоненты скорости) ---
        ! V-точка (i,j) находится на грани между i и i-1 по Y.
        ! Имеет 4 U-соседа: HU(i-1,j), HU(i-1,j+1), HU(i,j+1), HU(i,j).
        ! Цикл по i=2..IS1, j=1..JS1-1 (все V-точки внутренней области).
        do j = 1, js1 - 1
            do i = 2, is1
                ! Пропуск ячеек суши (HV=8888)
                if (abs(hv(i, j) - 8888.0) .lt. 1e-8) cycle

                ! Глубины 4 соседних U-точек
                gu1 = hu(i - 1, j)     ! U-сосед юго-запад
                gu2 = hu(i - 1, j + 1) ! U-сосед северо-запад
                gu3 = hu(i, j + 1)     ! U-сосед северо-восток
                gu4 = hu(i, j)         ! U-сосед юго-восток

                isum = 4
                if (abs(gu1 - 8888.0) .lt. 1e-8) isum = isum - 1
                if (abs(gu2 - 8888.0) .lt. 1e-8) isum = isum - 1
                if (abs(gu3 - 8888.0) .lt. 1e-8) isum = isum - 1
                if (abs(gu4 - 8888.0) .lt. 1e-8) isum = isum - 1

                if (isum .eq. 0) isum = 1
                ikv(i, j) = isum
            end do
        end do

        ! Диагностический вывод (закомментирован, так как в FPM файловый вывод
        ! лучше настраивать централизованно, а unit 2 пока не открыт)
        ! write(2, '(105I1)') ((iku(i, j), j=1, js1), i=1, is1)
        ! write(2, '(105I1)') ((ikv(i, j), j=1, js1), i=1, is1)

    end subroutine ikuv

end module grid_masks
