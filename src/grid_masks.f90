! ==============================================================================
! Модуль: grid_masks (ikuv)
! Назначение: Вычисляет локальные маски IKU, IKV (число водных соседей)
!             для узлов U и V на основе полей глубин HU, HV.
! Физика: Определяет характер гидродинамических граничных условий:
!         - IKU/IKV = 4: внутренняя точка (4 водных соседа) — free-slip.
!         - IKU/IKV = 1..3: прибрежная точка — no-slip (прилипание).
!         - IKU/IKV = 1 (минимум) гарантирует, что делитель не станет нулем.
!         Эти маски используются в shallow_water для усреднения V/U при расчете
!         баротропных скоростей (переменные UUK, VKV).
! Геометрия B-сетки: U-точки на гранях J (X-направление), V-точки на гранях I (Y).
! Ответственность: Подготовка геометрического базиса. Защита алгоритма от
!                  вычислений в фиктивных ячейках суши.
! ==============================================================================

module grid_masks
    use param
    implicit none

contains

    subroutine ikuv()
        ! Локальные переменные
        integer :: i, j, isum
        real :: gu1, gu2, gu3, gu4

        ! Первичная инициализация масок: 4 = внутренняя точка (все соседи вода).
        iku(:, :) = 4
        ikv(:, :) = 4

        ! --- Расчет маски IKU (для U-компоненты скорости) ---
        ! U-точка (i,j) имеет 4 V-соседа: HV(i,j-1), HV(i,j), HV(i+1,j), HV(i+1,j-1).
        ! Цикл по i=1..IS1-1, j=2..JS1 (U-точки).
        do j = 2, js1
            do i = 1, is1 - 1
                ! Пропуск ячеек суши (HU=8888)
                if (abs(hu(i, j) - 8888.0) .lt. 1e-8) cycle

                gu1 = hv(i, j - 1)
                gu2 = hv(i, j)
                gu3 = hv(i + 1, j)
                gu4 = hv(i + 1, j - 1)

                isum = 4
                if (abs(gu1 - 8888.0) .lt. 1e-8) isum = isum - 1
                if (abs(gu2 - 8888.0) .lt. 1e-8) isum = isum - 1
                if (abs(gu3 - 8888.0) .lt. 1e-8) isum = isum - 1
                if (abs(gu4 - 8888.0) .lt. 1e-8) isum = isum - 1

                ! Минимум 1 — защита от деления на ноль в shallow_water.
                if (isum .eq. 0) isum = 1
                iku(i, j) = isum
            end do
        end do

        ! --- Расчет маски IKV (для V-компоненты скорости) ---
        ! V-точка (i,j) имеет 4 U-соседа: HU(i-1,j), HU(i-1,j+1), HU(i,j+1), HU(i,j).
        ! Цикл по i=2..IS1, j=1..JS1-1 (V-точки).
        do j = 1, js1 - 1
            do i = 2, is1
                ! Пропуск ячеек суши (HV=8888)
                if (abs(hv(i, j) - 8888.0) .lt. 1e-8) cycle

                gu1 = hu(i - 1, j)
                gu2 = hu(i - 1, j + 1)
                gu3 = hu(i, j + 1)
                gu4 = hu(i, j)

                isum = 4
                if (abs(gu1 - 8888.0) .lt. 1e-8) isum = isum - 1
                if (abs(gu2 - 8888.0) .lt. 1e-8) isum = isum - 1
                if (abs(gu3 - 8888.0) .lt. 1e-8) isum = isum - 1
                if (abs(gu4 - 8888.0) .lt. 1e-8) isum = isum - 1

                if (isum .eq. 0) isum = 1
                ikv(i, j) = isum
            end do
        end do

        ! Диагностический вывод (закомментирован, так как в FPM файловый вывод
        ! лучше настраивать централизованно, а unit 2 пока не открыт)
        ! write(2, '(105I1)') ((iku(i, j), j=1, js1), i=1, is1)
        ! write(2, '(105I1)') ((ikv(i, j), j=1, js1), i=1, is1)

    end subroutine ikuv

end module grid_masks
