! ==============================================================================
! Модуль: ice_deform
! Назначение: Вычисление тензоров деформации скоростей льда и их обновления
!             в рабочем массиве EPR для последующего расчета напряжений.
! Физика: Рассматривает лед как непремую среду. Вычисляет компоненты тензора
!         скоростей деформации (rate-of-strain tensor) по скоростям льда U, V.
!         Деформация:
!           EXX = ∂U/∂x = (U(i,j+1)+U(i+1,j+1)-U(i,j)-U(i+1,j))/dx   [1/с]
!           EYY = ∂V/∂y = (V(i,j)+V(i,j+1)-V(i+1,j)-V(i+1,j+1))/dx   [1/с]
!           EXY = 0.5*(∂U/∂y + ∂V/∂x) = 0.5*(U(i,j)+U(i,j+1)-U(i+1,j)-U(i+1,j+1)
!                                               + V(i+1,j+1)+V(i+1,j)-V(i,j)-V(i,j+1))/dx
!         Затем EPR (накопленная деформация) обновляется по upwind-схеме:
!           EPR(t+dt1) = EPR(t) - dt1*(100/dx*(a1+a2) - CD2)
!         где a1,a2 — упреждающие разности (upwind) для адвекции деформации,
!         CD2 — текущая деформация. Это транспортировка деформации течением льда.
! Единицы: U/V [м/с] → ×50 = [см/с] (dx в см); CD2 [см/с]; dt1 [с].
! Ответственность: Формирование полей деформации (EXX, EYY, EXY) и их
!                  перенос для расчета внутренних напряжений в ice_stress.
! ==============================================================================

module ice_deform
    use param
    implicit none

contains

    subroutine deform(kl, dx, dt1)
        ! Входные параметры
        integer, intent(in) :: kl       ! Компонента тензора: 1=EXX, 2=EYY, 3=EXY
        real, intent(in) :: dx, dt1     ! Шаг по пространству [см] и время [с]

        ! Локальные переменные
        integer :: i, j, i1, j1
        real :: a, b, a1, a2, b1, v11, v22, v3, v4

        ! KL = 1: EXX (деформация по X); KL = 2: EYY (по Y); KL = 3: EXY (сдвиг).
        ! CD2 - тензор деформации (промежуточный, безразмерный [1/с]).
        ! EPR - рабочий массив [is3, js3] для накопленной деформации (с halo).
        do j = 1, js
            j1 = j + 1
            do i = 1, is
                ! Пропуск суши (KT1=0)
                if (kt1(i, j) .eq. 0) cycle

                i1 = i + 1
                v11 = v(i, j)       ! V в SW углу ячейки
                v22 = v(i, j1)      ! V в NW углу
                v3 = v(i1, j)       ! V в SE углу
                v4 = v(i1, j1)      ! V в NE углу

                ! Эквивалент старого арифметического IF(KL-2) 2,3,4
                ! Вычисление компоненты деформации CD2 [см/с]
                if (kl .eq. 1) then
                    ! EXX = dU/dx: разность U на восточной и западной гранях
                    ! U в м/с → ×50 = см/с (dx в см)
                    cd2(i, j) = 50.0*(u(i, j1) + u(i1, j1) - u(i, j) - u(i1, j))/dx
                else if (kl .eq. 2) then
                    ! EYY = dV/dy: разность V на северной и южной гранях
                    cd2(i, j) = 50.0*(v11 + v22 - v3 - v4)/dx
                else
                    ! EXY = 0.5*(dU/dy + dV/dx): сдвиг
                    cd2(i, j) = 25.0*(u(i, j) + u(i, j1) - u(i1, j) - u(i1, j1) &
                                      + v22 + v4 - v11 - v3)/dx
                end if

                ! Upwind-схема для переноса накопленной деформации EPR
                ! b = средняя V в ячейке (для адвекции по Y)
                b = 0.25*(v11 + v22 + v3 + v4)
                ! b1 = средняя U в ячейке (для адвекции по X)
                b1 = 0.25*(u(i, j) + u(i, j1) + u(i1, j1) + u(i1, j))
                a = epr(i1, j1)   ! Значение EPR в NE углу (индексы +1 из-за halo)

                ! Upwind разности для X-адвекции (a1)
                if (b1 .ge. 0.0) then
                    a1 = b1*(a - epr(i1, j))        ! поток с запада на восток
                else
                    a1 = b1*(epr(i1, min(js3, j + 2)) - a)  ! поток с востока на запад
                end if

                ! Upwind разности для Y-адвекции (a2)
                if (b .ge. 0.0) then
                    a2 = b*(a - epr(i, j1))         ! поток с юга на север
                else
                    a2 = b*(epr(min(is3, i + 2), j1) - a)   ! поток с севера на юг
                end if

                ! Обновление EPR: d(EPR)/dt = -100/dx*(a1+a2) + CD2
                ! 100/dx — коэффициент масштабирования (м/с → см/с при dx в см)
                epr(i1, j1) = a - dt1*(100.0/dx*(a1 + a2) - cd2(i, j))
            end do
        end do

    end subroutine deform

end module ice_deform
