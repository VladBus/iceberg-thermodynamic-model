! ==============================================================================
! Модуль: ice_deform
! Назначение: Вычисление компонент тензора скоростей деформации (rate-of-strain
!             tensor) ледяного покрова и их транспортировка течением льда.
! Физика: Рассматривает лёд как сплошную деформируемую среду.
!         Тензор деформации — градиент скорости льда:
!
!           EXX = ∂u/∂x = [u(i,j+1) + u(i+1,j+1) - u(i,j) - u(i+1,j)] / dx
!           EYY = ∂v/∂y = [v(i,j) + v(i,j+1) - v(i+1,j) - v(i+1,j+1)] / dx
!           EXY = 0.5·(∂u/∂y + ∂v/∂x) = 0.5·[
!                   u(i,j) + u(i,j+1) - u(i+1,j) - u(i+1,j+1)
!                   + v(i,j+1) + v(i+1,j+1) - v(i,j) - v(i+1,j)
!                 ] / dx
!
!         После вычисления деформации выполняется адвекция (перенос) EPR
!         течением льда по upwind-схеме:
!           EPR(t+dt) = EPR(t) - dt·[100/dx·(a₁ + a₂) - CD2]
!         где a₁, a₂ — upwind-разности для адвекции EPR по X и Y,
!         CD2 — текущая деформация. 100/dx — коэффициент масштабирования
!         (перевод U/V из м/с в см/с при dx в см: 100/dx = 100 [м/с→см/с]/dx [см]).
!
! Единицы:
!   U, V     — скорость льда [м/с] (в main.f90) → перевод в [см/с] через ×50
!              (50 = 100/2 для усреднения двух скоростей на грани)
!   dx       — шаг сетки [см] (= 1 389 000)
!   dt1      — баротропный шаг по времени [с] (= 120)
!   CD2      — промежуточная деформация [1/с] (результат deform)
!   EPR      — рабочий массив накопленной деформации [1/с] (с halo, размер is3×js3)
!   EXX, EYY, EXY — финальные компоненты деформации [1/с]
!
! Маски:
!   KT1(i,j)  — число мокрых уровней (0 = суша)
!   IDX, IDY  — вертикальные маски для W
!
! Сетка: T-точки (центры ячеек).
!   U(i,j)   — скорость по X (на B-сетке: U(i,j) на границе (i, j+1/2))
!   V(i,j)   — скорость по Y (на B-сетке: V(i,j) на границе (i+1/2, j))
!   EPR(i+1,j+1) — EPR с учётом halo (сдвиг индексов на +1)
!
! Ответственность: Формирование EXX/EYY/EXY для ice_stress:stress().
!
! Вызов из ice_stress: deform(kl, dx, dt1) трижды:
!   kl=1 → EXX, kl=2 → EYY, kl=3 → EXY
! ==============================================================================

module ice_deform
    use param
    implicit none

contains

    subroutine deform(kl, dx, dt1)
        ! Входные параметры
        integer, intent(in) :: kl       ! Компонента тензора: 1=EXX, 2=EYY, 3=EXY
        real, intent(in) :: dx          ! Пространственный шаг сетки [см]
        real, intent(in) :: dt1         ! Баротропный шаг по времени [с]

        ! Локальные переменные
        integer :: i, j, i1, j1
        real :: a, b, a1, a2, b1, v11, v22, v3, v4

        ! ================================================================
        ! ЦИКЛ: ВЫЧИСЛЕНИЕ КОМПОНЕНТЫ ДЕФОРМАЦИИ + АДВЕКЦИЯ EPR
        ! ================================================================
        ! Для каждой ячейки (i,j):
        !   1. Вычисляем CD2 = компонента деформации [1/с]
        !   2. Адвектируем EPR течением (u_avg, v_avg) по upwind-схеме

        do j = 1, js
            j1 = j + 1
            do i = 1, is
                ! Пропуск суши (KT1=0)
                if (kt1(i, j) .eq. 0) cycle

                i1 = i + 1

                ! Значения V на 4 углах ячейки (B-grid) [м/с]
                v11 = v(i, j)       ! V в SW углу (i, j)
                v22 = v(i, j1)      ! V в NW углу (i, j+1)
                v3 = v(i1, j)       ! V в SE углу (i+1, j)
                v4 = v(i1, j1)      ! V в NE углу (i+1, j+1)

                ! --- ВЫЧИСЛЕНИЕ КОМПОНЕНТЫ ДЕФОРМАЦИИ CD2 [1/с] ---
                if (kl .eq. 1) then
                    ! EXX = ∂u/∂x: разность U на восточной и западной гранях
                    ! U [м/с] → ×50 = [см/с] (dx в см, результат в [1/с])
                    ! 50 = 100·0.5 (перевод м/с→см/с × усреднение двух значений на грани)
                    cd2(i, j) = 50.0*(u(i, j1) + u(i1, j1) - u(i, j) - u(i1, j))/dx
                else if (kl .eq. 2) then
                    ! EYY = ∂v/∂y: разность V на северной и южной гранях
                    ! Аналогично EXX, но для V-компонента
                    cd2(i, j) = 50.0*(v11 + v22 - v3 - v4)/dx
                else
                    ! EXY = 0.5·(∂u/∂y + ∂v/∂x): сдвиговая деформация
                    ! 25 = 100·0.25 (перевод м/с→см/с × 0.5 (среднее) × 0.5 (u и v))
                    cd2(i, j) = 25.0*(u(i, j) + u(i, j1) - u(i1, j) - u(i1, j1) &
                                      + v22 + v4 - v11 - v3)/dx
                end if

                ! --- АДВЕКЦИЯ НАКОПЛЕННОЙ ДЕФОРМАЦИИ EPR (upwind-схема) ---
                ! EPR транспортируется течением льда: ∂EPR/∂t + u·∂EPR/∂x + v·∂EPR/∂y = CD2
                ! Дискретизация: EPR_new = EPR - dt·(advect - source)
                !   где advect = 100/dx·(a₁ + a₂) — расходимость потока EPR
                !         source = CD2 — генерация деформации
                !   100/dx — коэффициент масштабирования (м/с → см/с при dx в см)

                ! Средние компоненты скорости льда в ячейке [м/с]
                b = 0.25*(v11 + v22 + v3 + v4)    ! Средняя V [м/с]
                b1 = 0.25*(u(i, j) + u(i, j1) + u(i1, j1) + u(i1, j))  ! Средняя U [м/с]

                ! Значение EPR в NE углу ячейки [с учётом halo: индексы +1]
                a = epr(i1, j1)

                ! --- UPWIND РАЗНОСТИ ДЛЯ X-АДВЕКЦИИ ---
                ! a₁ = u·(EPR_current - EPR_upwind) [м/с × 1/с]
                ! При u≥0: upwind = EPR(i, j) (с запада)
                ! При u<0: upwind = EPR(i, j+2) (с востока)
                if (b1 .ge. 0.0) then
                    a1 = b1*(a - epr(i1, j))                ! U≥0: с запада
                else
                    a1 = b1*(epr(i1, min(js3, j + 2)) - a) ! U<0: с востока
                end if

                ! --- UPWIND РАЗНОСТИ ДЛЯ Y-АДВЕКЦИИ ---
                ! a₂ = v·(EPR_current - EPR_upwind) [м/с × 1/с]
                ! При v≥0: upwind = EPR(i-1, j+1) (с юга)
                ! При v<0: upwind = EPR(i+2, j+1) (с севера)
                if (b .ge. 0.0) then
                    a2 = b*(a - epr(i, j1))                ! V≥0: с юга
                else
                    a2 = b*(epr(min(is3, i + 2), j1) - a) ! V<0: с севера
                end if

                ! --- ОБНОВЛЕНИЕ EPR ---
                ! EPR(i1,j1) = EPR - dt1·(100/dx·(a1+a2) - CD2)
                !   100/dx [см⁻¹] × (a1+a2) [м/с × 1/с] = [см⁻¹·м/с²] → согласование единиц
                !   dt1 [с] × [1/с] → [безразм.] — итого EPR [1/с]
                epr(i1, j1) = a - dt1*(100.0/dx*(a1 + a2) - cd2(i, j))
            end do
        end do

    end subroutine deform

end module ice_deform
