! ==============================================================================
! Модуль: ice_redis (redis)
! Назначение: Перераспределение массы и площади льда по категориям толщины
!             (Ice Thickness Distribution, ITD) согласно алгоритму Торндайка.
! Физика: Реализует эволюцию ITD — функции распределения толщины льда.
!
!         Физические процессы:
!           1. ТЕРМОДИНАМИКА: сдвигает лёд между категориями:
!              - Нарастание/таяние меняет среднюю толщину → лёд «перетекает»
!                в соседнюю категорию если h попадает в её диапазон.
!           2. ДИНАМИКА (ТОРОШЕНИЕ): при сжатии тонкий лёд деформируется
!              и превращается в торосы (толстый лёд):
!              - A_thin → A_thick (площадь уменьшается, объём сохраняется)
!              - Строгое сохранение объёма: V_new = V1 + V2
!           3. БАЛАНСИРОВКА ПЛОЩАДИ: SUM(A_k) ≤ 1.0
!              - Если сумма площадей превышает 1, избыток перераспределяется
!                из тонких категорий в более толстые.
!
!         Уравнения переноса:
!           - При слиянии категорий k и k+1:
!             A_new = A_k + A_{k+1}
!             h_new = (A_k·h_k + A_{k+1}·h_{k+1}) / A_new
!             h_s_new = (A_k·h_s_k + A_{k+1}·h_s_{k+1}) / A_new  (снег по объёму)
!           - При разделении (таяние):
!             A_new = A_{k-1} + A_k
!             h_new = (A_{k-1}·h_{k-1} + A_k·h_k) / A_new
!
! Единицы (SI для льда):
!   AN1(i,j,k+1) — площадь категории k [безразм., 0..1]
!   AN1(i,j,1)   — площадь открытой воды [безразм., 0..1]
!   WICE1(i,j,k) — объём льда в категории k [м] (= A_k · h_k)
!   HICE(i,j,k)  — средняя толщина льда в категории k [м]
!   HSNOW(i,j,k) — толщина снега в категории k [м]
!   ANS(i,j)      — агрегированная сплошность = SUM(A_k) [безразм.]
!   WICES(i,j)    — агрегированный объём льда = SUM(WICE1_k) [м]
!   HICES(i,j)    — агрегированная средняя толщина = WICES/ANS [м]
!
!   hst(k)  — характерная толщина категории [м]:
!              k=1: 0.2 м, k=2: 0.5 м, k=3: 0.95 м, k=4: 1.6 м, k=5: 2.5 м
!   hmax(k) — верхняя граница толщины для перехода в следующую категорию [м]:
!              k=1: 0.3 м, k=2: 0.7 м, k=3: 1.2 м, k=4: 2.0 м, k=5: 50.0 м
!   ngr = 5 — число категорий толщины
!   ngr2 = 4 — число границ (для цикла по категориям)
!
! Массивы:
!   anpr(1..5)  — рабочие площади категорий (локальная копия AN1)
!   wicpr(1..5) — рабочие объёмы льда (локальная копия WICE1)
!   hsnp(1..5)  — рабочие толщины снега (локальная копия HSNOW)
!   hpr(1..5)   — рабочие средние толщины = wicpr/anpr [м]
!
! Ответственность: Обновление AN1, WICE1, HICE, HSNOW после теплового
!                  воздействия (heat) и перед адвекцией (adv2d).
!
! Вызов: redis() вызывается в main.f90 дважды:
!   1. После heat() — для перераспределения термодинамических изменений
!   2. После adv2d() по категориям — для восстановления согласованности
! ==============================================================================

module ice_redis
    use param
    implicit none

contains

    subroutine redis()
        integer :: i, j, k, k1, k2
        real :: a, b, a1, a2, a3, b1, b2, b3, dd

        ! ================================================================
        ! ОСНОВНОЙ ЦИКЛ ПО ГОРИЗОНТАЛЬНОЙ СЕТКЕ
        ! ================================================================
        do j = 1, js
            do i = 1, is
                ! Пропуск суши
                if (kt1(i, j) .eq. 0) cycle

                ! --- ЭТАП 1: ПОДГОТОВКА КАТЕГОРИЙ ---
                ! Копируем в локальные рабочие массивы для изменений.
                ! wicpr(k) — объём льда [м] (= A_k × h_k)
                ! anpr(k)  — площадь категории [безразм., 0..1]
                ! hsnp(k)  — толщина снега [м]
                do k = 1, ngr
                    hice(i, j, k) = 0.0
                    wicpr(k) = wice1(i, j, k)      ! Объём льда [м]
                    anpr(k) = an1(i, j, k + 1)     ! Площадь категории [безразм.]
                    hsnp(k) = hsnow(i, j, k)       ! Толщина снега [м]

                    ! Обнуляем при нефизичных значениях
                    if (wicpr(k) .le. 0.0 .or. anpr(k) .le. 0.0) then
                        wicpr(k) = 0.0
                        anpr(k) = 0.0
                        hsnp(k) = 0.0
                    end if
                end do

                ! --- ЭТАП 2: ПЕРЕНОС ЛЬДА В БОЛЕЕ ТОЛСТЫЕ КАТЕГОРИИ (торошение) ---
                ! Если средняя толщина h = wicpr(k)/anpr(k) > hmax(k),
                ! лёд «вырастает» за пределы текущей категории → перенос в k+1.
                ! При слиянии:
                !   A_{k+1} = A_k + A_{k+1}  (площади складываются)
                !   wicpr_{k+1} = wicpr_k + wicpr_{k+1}  (объёмы складываются)
                !   hsnp_{k+1} = (A_k·hsnp_k + A_{k+1}·hsnp_{k+1}) / A_new  (снег)
                !   wicpr_k = 0, anpr_k = 0  (категория опустошается)
                do k = 1, ngr2
                    k1 = k + 1
                    if (abs(wicpr(k)) .gt. 1e-8) then
                        if (abs(anpr(k)) .lt. 1e-8) anpr(k) = wicpr(k)/hst(k)
                        if (wicpr(k)/anpr(k) .gt. hmax(k)) then
                            a = anpr(k1) + anpr(k)
                            if (a .gt. 1.0e-8) then
                                hsnp(k1) = (anpr(k1)*hsnp(k1) + anpr(k)*hsnp(k))/a
                            end if
                            anpr(k1) = a
                            wicpr(k1) = wicpr(k1) + wicpr(k)
                            wicpr(k) = 0.0
                            anpr(k) = 0.0
                            hsnp(k) = 0.0
                        end if
                    end if
                end do

                ! --- ЭТАП 3: ПЕРЕНОС ЛЬДА В БОЛЕЕ ТОНКИЕ КАТЕГОРИИ (таяние) ---
                ! Если средняя толщина h < hmax(k-1), лёд «прогревается» до
                ! уровня более тонкой категории → перенос в k-1.
                ! При слиянии: аналогично этапу 2, но в обратном направлении.
                do k = ngr, 2, -1
                    if (wicpr(k) .gt. 0.0) then
                        k2 = k - 1
                        if (wicpr(k)/anpr(k) .lt. hmax(k2)) then
                            a = anpr(k2) + anpr(k)
                            if (a .gt. 1.0e-8) then
                                hsnp(k2) = (anpr(k2)*hsnp(k2) + anpr(k)*hsnp(k))/a
                            end if
                            wicpr(k2) = wicpr(k2) + wicpr(k)
                            anpr(k2) = a
                            wicpr(k) = 0.0
                            anpr(k) = 0.0
                            hsnp(k) = 0.0
                        end if
                    end if
                end do

                ! --- ЭТАП 4: РАСЧЕТ СРЕДНИХ ТОЛЩИН ---
                ! hpr(k) = wicpr(k)/anpr(k) [м] — средняя толщина в категории k
                do k = 1, ngr
                    if (abs(anpr(k)) .gt. 1e-8) then
                        hpr(k) = wicpr(k)/anpr(k)
                    else
                        hpr(k) = 0.0
                    end if
                end do

                ! --- ЭТАП 5: КОНТРОЛЬ МАКСИМАЛЬНОЙ ПЛОЩАДИ (СПЛОШНОСТИ) ---
                ! Итеративная балансировка: SUM(anpr) ≤ 1.0
                ! Если SUM > 1.0 (невозможно физически), избыток dd = SUM-1.0
                ! перераспределяется из тонких категорий в более толстые.
                ! Алгоритм:
                !   1. Вычисляем SUM(A_k) = a1
                !   2. Если a1 ≤ 1.0 — выходим
                !   3. Иначе: ищем пару соседних категорий (k, k+1), для которых
                !      перераспределение dd не приводит к отрицательным площадям
                !   4. Решаем систему: A_k_new = b2, A_{k+1}_new = a2
                !      где b2, a2 — площади после вычета dd
                redistribution_loop: do
                    a1 = 0.0
                    do k = 1, ngr
                        a1 = a1 + anpr(k)
                    end do

                    if (a1 .le. 1.0) exit redistribution_loop

                    dd = a1 - 1.0          ! Избыток площади [безразм.]
                    a3 = wicpr(1)           ! Накопленный объём от k=1
                    b3 = 1.0                ! Накопленная площадь от k=1

                    do k = 2, ngr
                        b3 = b3 - anpr(k)
                    end do

                    inner_loop: do k = 1, ngr2
                        k1 = k + 1
                        a3 = a3 + wicpr(k1)
                        b3 = b3 + anpr(k1)

                        if (abs(anpr(k)) .lt. 1e-8) cycle inner_loop

                        if (abs(anpr(k1)) .lt. 1e-8) then
                            ! Следующая категория пуста: просто уменьшаем текущую
                            if (dd .lt. anpr(k)) then
                                a = anpr(k)
                                anpr(k) = anpr(k) - dd
                                hsnp(k) = hsnp(k)*a/anpr(k)  ! Снег пропорционально
                                exit redistribution_loop
                            else
                                ! Перенос всей категории в следующую
                                wicpr(k1) = wicpr(k)
                                anpr(k1) = wicpr(k)/hst(k1)
                                hpr(k1) = wicpr(k1)/anpr(k1)
                                hsnp(k1) = hsnp(k)*anpr(k)/anpr(k1)
                                wicpr(k) = 0.0
                                anpr(k) = 0.0
                                hpr(k) = 0.0
                                hsnp(k) = 0.0
                            end if
                            ! Пересчёт сначала (эквивалент GOTO 319 в оригинале)
                            cycle redistribution_loop
                        end if

                        ! Решаем систему линейных уравнений для двух категорий:
                        ! a = hpr(k) - hpr(k1)  [разность средних толщин]
                        ! b2 = (a3 - hpr(k1)·b3)/a  — площадь категории k
                        ! a2 = (hpr(k)·b3 - a3)/a   — площадь категории k+1
                        a = hpr(k) - hpr(k1)
                        if (abs(a) .gt. 1e-8) then
                            b2 = (a3 - hpr(k1)*b3)/a
                            a2 = (hpr(k)*b3 - a3)/a
                        else
                            b2 = -1.0
                            a2 = -1.0
                        end if

                        if (b2 .lt. 0.0 .or. a2 .lt. 0.0) then
                            anpr(k) = 0.0
                        else
                            anpr(k) = b2
                            anpr(k1) = a2
                            wicpr(k) = hpr(k)*b2
                            wicpr(k1) = hpr(k1)*a2
                            exit redistribution_loop
                        end if
                    end do inner_loop

                    ! Если цикл дошёл до конца: вся площадь в последней категории
                    anpr(ngr) = 1.0
                    wicpr(ngr) = a3
                    exit redistribution_loop
                end do redistribution_loop

                ! --- ЭТАП 6: ФИНАЛЬНОЕ ОБНОВЛЕНИЕ ГЛОБАЛЬНЫХ МАССИВОВ ---
                ! Записываем локальные изменения обратно в глобальные массивы.
                ! Вычисляем агрегированные поля: ANS, WICES, HICES.
                a1 = 0.0    ! Суммарная сплошность
                b1 = 0.0    ! Суммарный объём льда
                do k = 1, ngr
                    if (abs(anpr(k)) .lt. 1e-8) wicpr(k) = 0.0
                    a1 = a1 + anpr(k)
                    b1 = b1 + wicpr(k)
                    an1(i, j, k + 1) = anpr(k)
                    wice1(i, j, k) = wicpr(k)
                    hsnow(i, j, k) = hsnp(k)
                    if (abs(anpr(k)) .gt. 1e-8) hice(i, j, k) = wicpr(k)/anpr(k)
                end do

                ! --- ДОПОЛНИТЕЛЬНАЯ ПРОВЕРКА НА ТОЛЩИНУ ---
                ! Если средняя толщина категории k < hmax(k-1),
                ! переносим в более тонкую категорию (k-1).
                do k = ngr, 2, -1
                    k2 = k - 1
                    if (hice(i, j, k) .lt. hmax(k2)) then
                        k1 = k + 1
                        a = an1(i, j, k) + an1(i, j, k1)
                        if (a .gt. 1.0e-8) then
                            hsnow(i, j, k2) = (an1(i, j, k)*hsnow(i, j, k2) + &
                                               an1(i, j, k1)*hsnow(i, j, k))/a
                        end if
                        an1(i, j, k) = a
                        b = wice1(i, j, k2) + wice1(i, j, k)
                        wice1(i, j, k2) = b
                        if (abs(a) .gt. 1.0e-8) hice(i, j, k2) = b/a
                        an1(i, j, k1) = 0.0
                        wice1(i, j, k) = 0.0
                        hice(i, j, k) = 0.0
                        hsnow(i, j, k) = 0.0
                    end if
                end do

                ! --- АГРЕГИРОВАННЫЕ ПОЛЯ ---
                ! ANS(i,j) — общая сплошность льда = SUM(A_k)
                ! WICES(i,j) — общий объём льда [м] = SUM(WICE1_k)
                ! HICES(i,j) — средняя толщина льда [м] = WICES/ANS
                ! Если ANS < 0.005 — льда практически нет → обнуление.
                ans(i, j) = a1
                wices(i, j) = b1

                if (a1 .ge. 0.005) then
                    hices(i, j) = b1/a1
                else
                    ans(i, j) = 0.0
                    hices(i, j) = 0.0
                    wices(i, j) = 0.0
                end if

                ! Открытая вода: AN1(:,:,1) = 1 - SUM(A_k)
                an1(i, j, 1) = 1.0 - a1

            end do
        end do

    end subroutine redis

end module ice_redis
