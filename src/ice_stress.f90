! ==============================================================================
! Модуль: ice_stress
! Назначение: Вычисление внутренних напряжений морского льда по тензору
!             скоростей деформации и эллиптической кривой текучести.
! Физика: Рассматривает ледяной покров как нелинейную вязко-пластичную
!         (viscous-plastic, VP) макроскопическую среду (Hibler, 1979).
!         Внутренние напряжения льда возникают только при сплошности > 95%
!         и при сжатии (расходимость деформации < 0).
!
!         Ключевые уравнения:
!
!         1. Тензор скоростей деформации (rate-of-strain tensor):
!            EXX = ∂u/∂x,  EYY = ∂v/∂y,  EXY = 0.5·(∂u/∂y + ∂v/∂x)
!            Вычисляется в ice_deform:deform().
!
!         2. Главные напряжения (principal stresses):
!            a₁ = σ_max, a₂ = σ_min — собственные значения тензора напряжений.
!            a₁ = (σ_xx+σ_yy)/2 + √(((σ_xx-σ_yy)/2)² + σ_xy²)
!            a₂ = (σ_xx+σ_yy)/2 - √(((σ_xx-σ_yy)/2)² + σ_xy²)
!
!         3. Кривая текучести (yield curve) — эллипс в пространстве напряжений:
!            Сжатие: a₂ = -0.43·10⁵·h_k_crit²  [дин/см²]
!            где h_k_crit — характерная толщина доминирующей категории льда [м].
!            Расширение (divergence > 0, σ ≥ 0): напряжения = 0 (нет сопротивления).
!
!         4. Проекция на кривую текучести:
!            Если напряжение выходит за пределы эллипса — проецируется на границу.
!            Затем обратное преобразование из главных осей в компоненты тензора:
!              σ_xx = a₁·cos²(θ) + a₂·sin²(θ)
!              σ_yy = a₁·sin²(θ) + a₂·cos²(θ)
!              σ_xy = -(a₁-a₂)·cos(θ)·sin(θ)
!            где θ = 0.5·atan2(σ_xy, (σ_xx-σ_yy)/2) — угол поворота главных осей.
!
! Единицы:
!   EXX, EYY, EXY — тензор деформации [1/с]
!   SXX, SYY, SXY — напряжения [дин/см² → масштабированы ×10⁷ для вычислений]
!                   (внутри: ssxx = exx·1e7, затем обратно exx = sxx·1e-7)
!   ANS(i,j)      — агрегированная сплошность льда [безразм., 0..1]
!   hst(k)        — характерная толщина категории [м] (0.2, 0.5, 0.95, 1.6, 2.5)
!   ngr = 5       — число категорий толщины
!   dx_val = 1 389 000 [см] — шаг сетки
!   dt1_val = 120 [с] — баротропный шаг времени
!   0.43e5         — коэффициент эллипса текучести [дин/см²]
!
! Маска: Напряжения вычисляются только при ans(i,j) ≥ 0.95.
!        При ans < 0.95 (или суша) все напряжения = 0.
!        При расходимости (a > 0) и σ ≥ 0 (b ≥ 0) — лёд растягивается → σ = 0.
!
! Сетка: EXX/EYY/EXY/SXX/SYY/SXY на T-точках (центры ячеек).
!        EPR — рабочий массив [is3, js3] с halo для вычисления деформации.
!
! Ответственность: Формирование полей SXX/SYY/SXY для расчёта сил льда
!                  в main.f90 (block «динамика льда», строки 422-425).
! ==============================================================================

module ice_stress
    use param
    use ice_deform
    implicit none

contains

    subroutine stress()
        integer :: i, j, i1, j1, k, k_crit
        real :: a, b, a1, a2, b1, b2, sor, cor, ssxx, ssyy, ssxy
        real :: scrit, angl
        real, parameter :: dx_val = 1389000.0   ! Шаг сетки [см]
        real, parameter :: dt1_val = 120.0       ! Баротропный шаг [с]

        ! ================================================================
        ! БЛОК 1: ПОДГОТОВКА ПОЛЕЙ С ВЫЗОВОМ deform()
        ! ================================================================
        ! Вызываем deform() трижды для каждой компоненты тензора деформации:
        !   deform(1) → EXX (растяжение по X)
        !   deform(2) → EYY (растяжение по Y)
        !   deform(3) → EXY (сдвиговая деформация)
        ! EPR — рабочий массив [is3, js3] с расширенными границами (halo).
        ! Перед каждым вызовом копируем предыдущее поле в EPR и задаём
        ! нулевой градиент на границах halo.

        ! --- Подготовка EXX: копируем в EPR и задаём граничные условия ---
        do j = 1, js
            do i = 1, is
                i1 = i + 1
                epr(i1, j + 1) = exx(i, j)    ! Сдвиг индексов из-за halo
            end do
        end do
        ! Нулевой градиент на границах (fixed boundary)
        epr(1, :) = epr(2, :)
        epr(is3, :) = epr(is1, :)
        epr(:, 1) = epr(:, 2)
        epr(:, js3) = epr(:, js1)

        ! Вычисление EXX = ∂u/∂x
        call deform(1, dx_val, dt1_val)

        ! Копируем результат обратно из EPR в EXX
        do j = 1, js
            j1 = j + 1
            do i = 1, is
                i1 = i + 1
                exx(i, j) = epr(i1, j1)
                epr(i1, j1) = eyy(i, j)    ! Подготовка EYY в EPR
            end do
        end do
        epr(1, :) = epr(2, :)
        epr(is3, :) = epr(is1, :)
        epr(:, 1) = epr(:, 2)
        epr(:, js3) = epr(:, js1)

        ! Вычисление EYY = ∂v/∂y
        call deform(2, dx_val, dt1_val)

        ! Копируем результат и подготавливаем EXY
        do j = 1, js
            j1 = j + 1
            do i = 1, is
                i1 = i + 1
                eyy(i, j) = epr(i1, j1)
                epr(i1, j1) = exy(i, j)
            end do
        end do
        epr(1, :) = epr(2, :)
        epr(is3, :) = epr(is1, :)
        epr(:, 1) = epr(:, 2)
        epr(:, js3) = epr(:, js1)

        ! Вычисление EXY = 0.5·(∂u/∂y + ∂v/∂x)
        call deform(3, dx_val, dt1_val)

        ! Копируем EXY обратно
        do j = 1, js
            do i = 1, is
                i1 = i + 1
                exy(i, j) = epr(i1, j + 1)
            end do
        end do

        ! ================================================================
        ! БЛОК 2: ОСНОВНОЙ ЦИКЛ РАСЧЕТА НАПРЯЖЕНИЙ
        ! ================================================================
        ! Для каждой ячейки (i,j):
        !   1. Проверка маски (суша → обнуление)
        !   2. Проверка сплошности (ans < 0.95 → обнуление)
        !   3. Проверка на расходимость (a > 0 и b ≥ 0 → обнуление)
        !   4. Масштабирование в 1e7 для вычислений (избегаем потеря точности)
        !   5. Вычисление главных напряжений a₁, a₂
        !   6. Определение доминирующей категории льда (k_crit)
        !   7. Критическое значение scrit по эллипсу текучести
        !   8. Проекция на эллипс (если напряжение выходит за пределы)
        !   9. Обратное преобразование из главных осей в компоненты

        do j = 1, js
            do i = 1, is
                ! --- МАСКА СУШИ ---
                if (kt1(i, j) .eq. 0) then
                    ! Обнуляем, чтобы старые значения суши не попали в stencil соседей
                    exx(i, j) = 0.0; eyy(i, j) = 0.0; exy(i, j) = 0.0
                    sxx(i, j) = 0.0; syy(i, j) = 0.0; sxy(i, j) = 0.0
                    cycle
                end if

                ! --- ПРОВЕРКА СПЛОШНОСТИ ---
                ! Напряжения возникают только при сплошности > 95%
                if (ans(i, j) .lt. 0.95) then
                    exx(i, j) = 0.0; eyy(i, j) = 0.0; exy(i, j) = 0.0
                    sxx(i, j) = 0.0; syy(i, j) = 0.0; sxy(i, j) = 0.0
                    cycle
                end if

                a = exx(i, j) + eyy(i, j)          ! След тензора деформации (divergence)
                b = (sxx(i, j) + syy(i, j))*0.5     ! Среднее нормальное напряжение

                ! --- РАСШИРЕНИЕ (DIVERGENCE) ---
                ! Если лёд растягивается (a > 0) и среднее напряжение ≥ 0,
                ! напряжения = 0 (лёд не сопротивляется растяжению)
                if (a .gt. 0.0 .and. b .ge. 0.0) then
                    exx(i, j) = 0.0; eyy(i, j) = 0.0; exy(i, j) = 0.0
                    sxx(i, j) = 0.0; syy(i, j) = 0.0; sxy(i, j) = 0.0
                    cycle
                end if

                ! --- МАСШТАБИРОВАНИЕ В 1e7 ---
                ! Перевод деформации [1/с] в условные единицы для вычислений.
                ! Формула scrit = -0.43e5·h² [дин/см²] → требует масштабирования
                ! для совместимости с exx·1e7 (масштаб ~10⁷-10⁸).
                ssxx = exx(i, j)*1.e7    ! [1/с] × 1e7 = условные единицы
                ssyy = eyy(i, j)*1.e7
                ssxy = exy(i, j)*1.e7

                ! --- ГЛАВНЫЕ НАПРЯЖЕНИЯ ---
                ! Собственные значения тензора напряжений:
                a = (ssxx + ssyy)*0.5              ! Среднее: (σxx+σyy)/2
                b1 = (ssxx - ssyy)*0.5             ! Полуразность: (σxx-σyy)/2
                b2 = sqrt(b1*b1 + ssxy*ssxy)       ! Модуль сдвигового напряжения
                a1 = a + b2                         ! σ_max (максимальное главное напряжение)
                a2 = a - b2                         ! σ_min (минимальное главное напряжение)

                ! --- ОПРЕДЕЛЕНИЕ ДОМИНИРУЮЩЕЙ КАТЕГОРИИ ЛЬДА ---
                ! Ищем первую категорию k, где площадь > 5%.
                ! Это определяет характерную толщину для кривой текучести.
                ! ngr = 5 — число категорий толщины.
                k_crit = 1
                do k = 1, ngr
                    if (an1(i, j, k + 1) .gt. 0.05) then
                        k_crit = k
                        exit
                    end if
                end do

                ! --- КРИТИЧЕСКОЕ ЗНАЧЕНИЕ ПО ЭЛЛИПСУ ТЕКУЧЕСТИ ---
                ! scrit = -0.43·10⁵·h_crit² [условные единицы]
                ! hst(k_crit) — характерная толщина категории [м]:
                !   k=1: 0.2 м, k=2: 0.5 м, k=3: 0.95 м, k=4: 1.6 м, k=5: 2.5 м
                ! Отрицательный знак: сжимающее напряжение.
                scrit = -0.43e5*hst(k_crit)**2

                ! --- ПРОВЕРКА НАХОЖДЕНИЯ ВНУТРИ ЭЛЛИПСА ---
                ! Если σ_min > scrit (не превышает критическое сжатие)
                ! И σ_max < 0 (лёд сжимается, не растягивается):
                !   → лёд в упругой области, напряжения = деформация × η_eff
                if (a2 .gt. scrit .and. a1 .lt. 0.0) then
                    sxx(i, j) = ssxx; syy(i, j) = ssyy; sxy(i, j) = ssxy
                    cycle
                end if

                ! --- ПРОЕКЦИЯ НА ГРАНИЦУ ЭЛЛИПСА ТЕКУЧЕСТИ ---
                ! Ограничиваем главные напряжения значением scrit (сжатие)
                ! и обнуляем растягивающие (положительные) компоненты.
                if (a2 .lt. scrit) a2 = scrit    ! Не ниже критического
                if (a1 .lt. scrit) a1 = scrit
                if (a1 .gt. 0.0) a1 = 0.0       ! Убираем растяжение
                if (a2 .gt. 0.0) a2 = 0.0

                ! --- ОБРАТНОЕ ПРЕОБРАЗОВАНИЕ В КОМПОНЕНТЫ ТЕНЗОРА ---
                ! Угол поворота главных осей: θ = 0.5·atan2(σ_xy, (σ_xx-σ_yy)/2)
                angl = atan2(ssxy, b1)*0.5
                cor = cos(-angl)    ! cos(θ)
                sor = sin(-angl)    ! sin(θ)

                ! Матрица поворота:
                ! σ_xx = a₁·cos²(θ) + a₂·sin²(θ)
                ! σ_yy = a₁·sin²(θ) + a₂·cos²(θ)
                ! σ_xy = -(a₁-a₂)·cos(θ)·sin(θ)
                sxx(i, j) = a1*cor*cor + a2*sor*sor
                syy(i, j) = a1*sor*sor + a2*cor*cor
                sxy(i, j) = -(a1 - a2)*cor*sor

                ! --- ВОЗВРАТ В ЕДИНИЦЫ ДЕФОРМАЦИИ ---
                ! exx = sxx · 1e-7 [1/с]
                exx(i, j) = sxx(i, j)*1.e-7
                eyy(i, j) = syy(i, j)*1.e-7
                exy(i, j) = sxy(i, j)*1.e-7
            end do
        end do

    end subroutine stress

end module ice_stress
