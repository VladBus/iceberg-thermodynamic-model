! ==============================================================================
! Модуль: initial_conditions
! Назначение: Формирование детерминированного синтетического состояния океана.
! Физика: Задает тестовые T, S и 3D-течения до подключения начальных полей ERA5.
!         Используется для проверки корректности динамических блоков.
!         Структура: вертикальная стратификация T (термоклин) и S (галиноклин),
!         фоновое дрейфовое течение, локальное «горячее пятно» для проверки
!         адвекции тепла. Начальные условия НЕ соответствуют реальному океану.
! Единицы: T [°C] (15→2°C от поверхности к дну), S [массовая доля] (0.033→0.035),
!          U/V [см/с] (0.20/0.10 — слабый дрейф), глубина/уровень [см].
!          Соленость 0.033 = 33 промилле (PSU ≈ g/kg, массовая доля ≈ PSU/1000).
! ==============================================================================

module initial_conditions
    use param
    use initial_ocean_reader
    implicit none

contains

    subroutine init_ocean()
        integer :: i, j, k
        real :: depth_ratio  ! нормированная глубина [0..1]: 0=поверхность, 1=дно
        logical :: realistic_ok

        print *, ">>> Initializing ocean conditions..."

        ! Обнуляем и активные, и ghost-узлы: транспорт читает i+1/j+1.
        t1 = 0.0   ! температура на шаге DT (предыдущий) [°C]
        t2 = 0.0   ! температура на шаге DT1 (текущий) [°C]
        s1 = 0.0   ! соленость на шаге DT [массовая доля]
        s2 = 0.0   ! соленость на шаге DT1 [массовая доля]
        u1 = 0.0   ! U-компонента скорости [см/с]
        u2 = 0.0
        v1 = 0.0   ! V-компонента скорости [см/с]
        v2 = 0.0
        w = 0.0    ! вертикальная скорость [см/с]
        ro = 0.0   ! аномалия плотности [г/см³]
        up1 = 0.0  ! интегральный U-поток [см²/с]
        up2 = 0.0
        vp1 = 0.0  ! интегральный V-поток [см²/с]
        vp2 = 0.0
        y1 = 0.0   ! возвышение свободной поверхности [см]
        y2 = 0.0
        ym1 = 0.0  ! усреднённый уровень моря [см]
        ym2 = 0.0

        ! --- Stage 7.7: реалистичные начальные T/S из файла (EN4.2.2 2020-01) ---
        call read_initial_ts(t1, t2, s1, s2, kt1, realistic_ok)
        if (realistic_ok) then
            ! Фоновое течение [см/с]: 0.20 по X и 0.10 по Y (сохранено как в Stage 7.6C.2)
            do k = 1, ks
                do j = 1, js1
                    do i = 1, is1
                        if (kt1(i, j) .gt. 0 .and. k .le. kt1(i, j)) then
                            u2(i, j, k) = 0.20
                            v2(i, j, k) = 0.10
                            u1(i, j, k) = u2(i, j, k)
                            v1(i, j, k) = v2(i, j, k)
                        end if
                    end do
                end do
            end do
            print *, ">>> Realistic ocean T/S applied (u/v drift 0.20/0.10 cm/s kept)"
            return
        end if

        print *, ">>> Warning: realistic ocean T/S unavailable, using SYNTHETIC fields"

        ! --- ЦИКЛ ПО ВЕРТИКАЛЬНЫМ УРОВНЯМ (K = 1..KS=18) ---
        do k = 1, ks
            ! Коэффициент глубины: от 0.0 (поверхность, k=1) до 1.0 (самое дно, k=KS)
            ! depth_ratio = (k-1)/(KS-1) — линейная интерполяция по вертикали
            depth_ratio = real(k - 1)/max(1.0, real(ks - 1))

            do j = 1, js
                do i = 1, is
                    ! Проверяем, что это вода, а не суша
                    if (kt1(i, j) .gt. 0 .and. k .le. kt1(i, j)) then
                        ! 1. Температура: падает от 15°C на поверхности до 2°C на дне
                        t2(i, j, k) = 15.0 - 13.0*depth_ratio
                        t1(i, j, k) = t2(i, j, k)

                        ! 2. Соленость [доля]: 0.033 соответствует 33 PSU.
                        s2(i, j, k) = 0.033 + 0.002*depth_ratio
                        s1(i, j, k) = s2(i, j, k)

                        ! 3. Аномалия: создаем 3D "горячее пятно" в центре (с 50 по 80 ячейку)
                  if (i .gt. 50 .and. i .lt. 80 .and. j .gt. 40 .and. j .lt. 60 .and. k .le. 5) then
                            t2(i, j, k) = t2(i, j, k) + 8.0  ! Нагреваем на 8 градусов
                            t1(i, j, k) = t2(i, j, k)
                        end if

                        ! 4. Фоновое течение [см/с]: 0.20 по X и 0.10 по Y.
                        u2(i, j, k) = 0.20
                        v2(i, j, k) = 0.10
                        u1(i, j, k) = u2(i, j, k)
                        v1(i, j, k) = v2(i, j, k)
                    else
                        ! Если суша, ставим нули
                        t2(i, j, k) = 0.0
                        s2(i, j, k) = 0.0
                        u2(i, j, k) = 0.0
                        v2(i, j, k) = 0.0
                    end if
                end do
            end do
        end do

    end subroutine init_ocean

end module initial_conditions
