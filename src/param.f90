! =========================================================================================
! Модуль: param
! Назначение: Централизованное хранилище глобальных массивов, физических
!             констант и параметров пространственно-временной сетки.
! Физика: Задает базовые параметры аппроксимации Буссинеска. Определяет
!         размерность B-сетки Аракавы (IS1, JS1, KS). Хранит трехмерные поля
!         температуры, солености, плотности и компонент скорости, а также
!         спектральные категории толщины морского льда.
! Ответственность: Выделение статической памяти. Обеспечение доступа всех
!                  вычислительных модулей к единому состоянию термодинамической
!                  системы.
! Параметры сетки: Горизонтальный шаг порядка 13.89 км и 18 вертикальных
!                  Z-уровней. В нем же резервируется память под многоуровневую модель
!                  распределения льда (Thorndike ice thickness distribution),
!                  включающую открытую воду и пять категорий льда различной толщины.
! Единицы измерения: CGS для гидродинамики (dx[см], dt[с], U/V[см/с]),
!                    SI для термодинамики (T[degC], S[массовая доля], h[м]).
!                    Скорость льда в динамике [м/с], в адвекции — перевод в [см/с].
! ==========================================================================================

module param
    implicit none

    ! ========================================================================
    !   ПАРАМЕТРЫ СЕТКИ И РАЗМЕРНОСТИ
    ! ========================================================================
    ! Сетка: B-тип Аракавы, 133x105 узлов (с ghost-ячейками).
    ! Оси: X ↔ j ↔ U-точки (132 ячейки), Y ↔ i ↔ V-точки (104 ячейки).
    !      Y-ось инвертирована: j=1 — север (высокие широты).
    ! Горизонтальный шаг: dx = 13.89 км = 1.389e6 см (см. main.f90:dx).
    ! Вертикальная сетка: 18 Z-уровней от 250 м до 6000 м (data z/...).
    ! ========================================================================
    integer, parameter :: is = 132   ! Число ячеек по X (U-ячейки)
    integer, parameter :: js = 104   ! Число ячеек по Y (V-ячейки)
    integer, parameter :: ks = 18    ! Число вертикальных Z-уровней
    integer, parameter :: is1 = is + 1  ! =133, размер с правой/левой ghost-ячейкой
    integer, parameter :: js1 = js + 1  ! =105, размер с верхней/нижней ghost-ячейкой
    integer, parameter :: ks1 = ks + 1  ! =19, для W-ячеек между уровнями
    integer, parameter :: is2 = is - 1  ! =131, внутренние ячейки (без двух ghost)
    integer, parameter :: js2 = js - 1  ! =103
    integer, parameter :: ks2 = ks - 1  ! =17
    ! IS3, JS3 — расширенные размеры (+2 по каждому оси) для EPR-тензоров
    ! деформации льда, где нужны halo-ячейки за пределами обычных ghost.
    integer, parameter :: is3 = is + 2  ! =134
    integer, parameter :: js3 = js + 2  ! =106
    integer, parameter :: ngr = 5       ! Число категорий толщины льда (Thorndike)
    integer, parameter :: ngr1 = ngr + 1  ! =6, индексация: 1=открытая вода, 2..6=категории
    integer, parameter :: ngr2 = ngr - 1  ! =4
    integer, parameter :: is4 = is + 3  ! =135, для маппинга метеоузлов
    integer, parameter :: js4 = js + 3  ! =107
    integer, parameter :: li = 4        ! Число приливных гармоник (M2, S2, K1, O1)
    integer, parameter :: lj = 35       ! Максимальное число метеоузлов на модельную ячейку

    ! ========================================================================
    !   МАССИВЫ ОКЕАНСКОГО БЛОКА (гидродинамика + термодинамика)
    ! ========================================================================
    ! Единицы измерения:
    !   CGS для гидродинамики: длина [см], время [с], скорость [см/с],
    !                          плотность [г/см³], давление [дин/см²]
    !   SI  для термодинамики: температура [°C], соленость [массовая доля],
    !                          толщина льда [м]
    ! ========================================================================
    real :: map1(is1, js1)  ! [см] Усреднённая глубина в T-точках (по 4 U/V-ячейки).
    ! Используется как HHT в блоках 200/210/280.
    ! Значение 8888.0 = суша (land mask).
    real :: z(ks)           ! [см] Глубины центров 18 Z-уровней (от поверхности).
    ! z(1)=25000 см (250 м), z(18)=600000 см (6000 м).
    real :: dz(ks)          ! [см] Толщина полного слоя между уровнями k и k+1.
    ! dz(1)=50000 см (500 м), для нижнего: dz(18) = ?
    real :: dz1(ks)         ! [см] Толщина полуслоя (от уровня до границы).
    ! dz1(k) = 0.5*(dz(k-1) + dz(k)), краевые: dz1(1)=dz(1)/2.
    ! Используется в convective_adjustment и block 210.
    real :: u1(is1, js1, ks)  ! [см/с] U-компонента скорости на текущем бароклинном шаге
    real :: u2(is1, js1, ks)  ! [см/с] U-компонента на предыдущем/следующем шаге
    real :: v1(is1, js1, ks)  ! [см/с] V-компонента на текущем шаге
    real :: v2(is1, js1, ks)  ! [см/с] V-компонента на предыдущем/следующем шаге
    ! В начале суток: u1=u2, v1=v2 (main.f90:370-373).
    ! U1/V1 — предыдущий бароклинный шаг, U2/V2 — текущий результат.
    real :: fku(is1, js1)   ! [1/с] Параметр Кориолиса f = 2Ω·sin(φ) в U-точках.
    ! Используется в block 200: asa1 = fku*0.5*dt.
    real :: drx(is1, js1)   ! [см/с²] Бароклинный градиент давления по X (отключён).
    real :: dry(is1, js1)   ! [см/с²] Бароклинный градиент давления по Y (отключён).
    real :: skz(is1, js1)   ! [см²/с] Вертикальный турбулентный обмен в верхнем слое.
    ! skz = rr(1) из block 210; используется в heat() для fw.

    ! Массивы для прямого/обратного хода Томаса (block 210: вертикальная вязкость).
    ! uca/vca — безразмерные коэффициенты, UNU/VNU — правая часть [см/с].
    ! Тип double precision для устойчивости алгоритма Томаса.
    double precision :: uca(ks1), unu(ks1), vca(ks1), vnu(ks1)

    ! --- МАССИВЫ ПОВЕРХНОСТНЫХ (2D) ПОЛЕЙ ---
    ! Глубины на гранях U/V для баротропного давления.
    real :: hu(is1, js1), hv(is1, js1)  ! [см] Глубины на U/V-грани (barotropic mode)
    ! Y1, Y2 — возвышение свободной поверхности [см] (мгновенное/накопленное).
    ! UP1/VP1 — интегральные потоки по U/V на текущем шаге [см²/с].
    ! UP2/VP2 — интегральные потоки на предыдущем шаге [см²/с].
    ! Используются в block 280: SUM = 0.5*(UP2(I,J)+UP2(I2,J))/HHT.
    real :: y1(is1, js1), y2(is1, js1), &
            up1(is1, js1), up2(is1, js1), vp1(is1, js1), vp2(is1, js1)
    ! FI, DL — широта и долгота [градусы] центров T-ячеек.
    ! FU, FV — Кориолис на U/V-гранях [1/с].
    real :: fi(is1, js1), dl(is1, js1), fu(is1, js1), fv(is1, js1)
    ! YM1/YM2 — накопленные и усреднённые уровни моря [см].
    ! yyy в block 210 = 0.25*ΣYM2 по 4 T-точкам (для профиля турбулентности).
    real :: ym1(is1, js1), ym2(is1, js1)
    ! ADX, ADY — вертикальные маски адвекции (1=вода, 0=дно) [безразм.].
    ! Размерность (is1,js1,ks1): для W-точек между уровнями.
    real :: adx(is1, js1, ks1), ady(is1, js1, ks1)
    ! --- Приливные массивы ---
    ! AMP, FAZ — амплитуды и фазы приливных гармоник на гидросетке.
    ! QQ — угловые частоты [°/ч], Q — те же частоты [рад на dt1].
    ! LI=4 гармоники: M2 (28.98°/ч), S2 (30.0), K1 (15.04), O1 (13.94).
    real :: amp(li, lj), faz(li, lj), qq(li), q(li)
    ! Рабочие массивы приливно-баротропного расчёта (5000 = макс. число шагов).
    real :: yyv(5000), v00(li), &
            amp1(133, 4), amp2(105, 4), amp3(133, 4), &
            uf1(5000), vf1(5000), uf2(5000), vf2(5000), uuf(5000), vvf(5000), &
            apn(5000, ngr1), wiu(5000), wiv(5000)

    ! --- ТЕРМОДИНАМИЧЕСКИЕ ПОЛЯ (T, S, ρ) ---
    ! T1/T2 — температура [°C] на шагах dt и dt1.
    !   T1 = t2 на предыдущем шаге (копируется в main.f90:370 перед heat()).
    !   T2 обновляется convective_adjustment и heat().
    ! S1/S2 — соленость [массовая доля, 0.033-0.035], НЕ промилле (PSU)!
    !   Связь: S [массовая доля] = S [PSU] / 1000.
    real :: t1(is1, js1, ks), t2(is1, js1, ks), s1(is1, js1, ks), s2(is1, js1, ks)

    ! HT — глубина в T-точках [см] (аргрегированная).
    ! RO — аномалия плотности [г/см³] = ρ - 1.02.
    !   Вычисляется eos::density_anomaly(T, S) через Eckart EOS.
    !   Физический диапазон: RO ≈ -0.03..+0.03 (около 1.02 г/см³).
    ! W — вертикальная скорость [см/с] в W-точках (between levels).
    ! TT, SS, RR — временные профили (ks1) для W-блока и block 210.
    !   rr(k) = NU = L²·|dU/dz| — коэффициент вертикальной вязкости [см²/с].
    ! SKT — вертикальный турбулентный обмен тепла на границе лёд/вода [м²/с].
    !   Используется в heat(): fw = ρ·Cp·SKT·(T_water - T_freeze) / dz.
    ! CD, APX, APY, APZ — коэффициенты имплицитной схемы (не используются в текущей версии).
    real :: ht(is1, js1), ro(is1, js1, ks), &
            w(is1, js1, ks1), tt(ks1), ss(ks1), rr(ks1), skt(is1, js1), &
            cd(is1, js1, ks), apx(is1, js1, ks), apy(is1, js1, ks), apz(is1, js1, ks1)

    ! --- МАСКИ И ГЕОМЕТРИЧЕСКИЕ ПАРАМЕТРЫ ---
    ! KK1 — индекс дна для U/V-ячеек: число мокрых уровней в столбце.
    !   KK1=0 означает сушу; используется в blocks 200/210/280.
    ! KT1 — аналогичный индекс для T-ячеек (имеет смысл только для T/S/RO).
    !   KK1 и KT1 могут различаться на границе U- и T-ячеек.
    integer :: kk1(is1, js1), kt1(is1, js1)
    ! IDX, IDY — индексы вертикальных границ W-слоёв (min из двух соседних).
    !   Используются в вычислении W (уравнение неразрывности).
    integer :: idx(is1, js1), idy(is1, js1)
    ! IT — идентификатор береговой конфигурации для адвекции льда.
    integer :: it(is1, js1)
    ! KUSH, KVSH — флаг активной U/V-грани (1=внутренняя, 0=берег/суша).
    integer :: kush(is1, js1), kvsh(is1, js1)
    ! IKU, IKV — число мокрых V/U-соседей (граничные условия no-slip/free-slip).
    integer :: iku(is1, js1), ikv(is1, js1)
    ! IIP — вспомогательный массив legacy.
    integer :: iip(is1, js1)

    ! ========================================================================
    !   МАССИВЫ ЛЕДОВОГО БЛОКА (Thorndike ice thickness distribution)
    ! ========================================================================
    ! Модель распределения толщин льда: 5 категорий + открытая вода.
    ! Категории (ngr=5): индекс k=1..5 в массивах WICE1, HSNOW, HICE.
    ! В AN1: индекс 1 = открытая вода, индексы 2..6 = категории 1..5.
    ! ========================================================================
    ! U0, V0 — скорость льда [м/с] на предыдущем баротропном шаге.
    ! U, V — скорость льда [м/с] на текущем шаге (обновляется в ice_dynamics).
    !   В адвекции переводится в [см/с] (×100).
    real :: u0(is1, js1), v0(is1, js1), u(is1, js1), v(is1, js1)
    ! WICE1 — объём льда в категории [м] = A_k × h_k.
    !   A_k — площадная доля, h_k — толщина льда.
    real :: wice1(is1, js1, ngr)
    ! AN1 — площадная доля категорий [безразм., 0..1].
    !   AN1(:,:,1) = доля открытой воды (1 - ΣA_k).
    !   AN1(:,:,k+1) = доля категории k. ΣAN1 = 1.
    real :: an1(is1, js1, ngr1)
    ! HICE — толщина льда в категории [м].
    real :: hice(is1, js1, ngr)
    ! AN3 — рабочая копия AN1 для адвекции (adv2d).
    ! ANS — агрегированная сплошность [безразм.]: ΣAN1(:,:,2:6).
    !   Значение 9.0 = суша (land mask в heat()).
    real :: an3(is1, js1), wices(is1, js1), hices(is1, js1), ans(is1, js1)
    ! CD2 — тензор деформации (промежуточный) [безразм.].
    real :: cd2(is1, js1)
    ! TXIC, TYIC — касательное напряжение воды на лёд [м/с²] (ice-water drag).
    !   Вычисляется в main.f90: a = c17*|V_water - V_ice|/h_ice.
    real :: txic(is1, js1), tyic(is1, js1)
    ! APX2, APY2 — антидиффузионные потоки FCT для льда.
    real :: apx2(is1, js1), apy2(is1, js1)
    ! EXX, EYY, EXY — компоненты тензора деформации льда [1/с].
    !   Хранятся в EPR (is3×js3) для ice_deform с halo.
    real :: exx(is1, js1), eyy(is1, js1), exy(is1, js1), epr(is3, js3)
    ! SXX, SYY, SXY — внутренние напряжения льда [дин/см²].
    !   Вычисляются в ice_stress; используются в main.f90 block 457-458.
    real :: sxx(is1, js1), syy(is1, js1), sxy(is1, js1)
    ! HSNOW — толщина снега в категории [м].
    real :: hsnow(is1, js1, ngr)
    ! TPAR, SPAR — массивы (ngr1) для temperature/salinity внутри льда.
    !   TPAR(1) = температура поверхности воды [K].
    !   SPAR(k+1) = соленость внутри категории k [массовая доля].
    real :: tpar(ngr1), spar(ngr1)
    ! ANP, DANP, HSNP, HICP — рабочие копии площади, приращения, снега, толщины
    !   внутри heat(). Неявно в heat(): ANP↔AN1(k+1), HICP↔HICE(k).
    real :: anp(ngr), danp(ngr), hsnp(ngr), hicp(ngr)
    ! SICST — критическая соленость для формирования льда в категории [массовая доля].
    !   Соль выделяется при замерзании: spar(k+1) += sicst(k)·Δh·ρ_ice/Δz.
    real :: sicst(ngr)
    ! HST — характерная толщина категории [м] (0.2, 0.5, 0.95, 1.6, 2.5).
    !   Используется при инициализации wice1 = hst(k)·an1(k+1).
    real :: hst(ngr)
    ! HMAX — верхняя граница толщины категории [м] (0.3, 0.7, 1.2, 2.0, 50.0).
    !   HMAX(5)=50.0 ≈ "бесконечность" для самой толстой категории.
    real :: hmax(ngr)
    ! ALSN — альбедо снега по месяцам [безразм., 0..1].
    !   Зимой ≈ 0.85 (свежий снег), летом ≈ 0.64 (таяние).
    !   Используется в heat(): (1-alsn(lll))·SW.
    real :: alsn(12)

    ! ========================================================================
    !   МАССИВЫ МЕТЕОРОЛОГИЧЕСКИХ ДАННЫХ (атмосферный форсинг)
    ! ========================================================================
    ! Единицы:
    !   TX/TY — касательное напряжение ветра [дин/см²] (= 0.1 Па).
    !     Формула: cof = (1.1 + 0.04·V·1e-2)·V²·1.29e-6 [дин/см²], V в [см/с].
    !   DPX/DPY — градиент атмосферного давления [hPa/см] в block 200.
    !     Формула: dpx = (p1(i,j+1) - p1(i,j))·1e3 / dxx, dxx = 13.89e5 см.
    !   TATM — температура воздуха [°C] (из t2m ERA5: K - 273.15).
    !   PATM — атмосферное давление [гПа = 100 Па] (из msl ERA5: Pa·0.01).
    !   WIND — модуль скорости геострофического ветра [м/с].
    !   HUMID, CLOUD — относительная влажность и облачность [доли, 0..1].
    !   ERA5_SNOWFALL_RATE — интенсивность снегопада [м/с] из ERA5 sf.
    ! ========================================================================
    real :: tx(is1, js1), ty(is1, js1)         ! [дин/см²] ветровое напряжение (текущее)
    real :: dpx(is1, js1), dpy(is1, js1)       ! [hPa/см] градиент давления (текущее)
    real :: tx1(is1, js1), ty1(is1, js1)       ! [дин/см²] ветровое напряжение (следующий день)
    real :: dpx1(is1, js1), dpy1(is1, js1)     ! [hPa/см] градиент давления (следующий день)
    real :: tatm1(is1, js1, 12)                ! [°C] месячная климатология температуры воздуха
    real :: tatm(is1, js1)                     ! [°C] интерполированная температура воздуха
    real :: cloud1(is1, js1, 12)               ! [доли] месячная климатология облачности
    real :: cloud(is1, js1)                    ! [доли] интерполированная облачность
    real :: humid(is1, js1)                    ! [доли] относительная влажность
    real :: patm(is1, js1)                     ! [гПа] атмосферное давление (≈1013 гПа)
    real :: wind(is1, js1)                     ! [м/с] модуль ветра (вычисляется из windx/windy)
    real :: wmonth(12)                         ! Веса для 12-мес. интерполяции метеоданных
    real :: sfal(12)                           ! [м/с] месячный снегопад (диагностика, не форсинг)
    real :: era5_snowfall_rate(is1, js1)        ! [м/с] полярная интенсивность снегопада ERA5
    real :: windx1(is1, js1), windy1(is1, js1) ! [см/с] компоненты ветра (следующий день)
    real :: windx(is1, js1), windy(is1, js1)   ! [см/с] компоненты ветра (текущие)
    ! P, PP — поле давления на метеосетке (1420×100) и интерполированное на гидросетку.
    ! X01, Y01 — координаты метеоузлов [градусы].
    real :: p(1420, 100), pp(1420), x01(1330), y01(1330)
    ! TC1/2/3/4, SC1/2/3/4 — климатологические профили T/S на разрезах.
    real :: tc1(is1, ks), sc1(is1, ks), &
            tc2(js1, ks), sc2(js1, ks), &
            tc3(15, ks), sc3(15, ks), &
            tc4(3, ks), sc4(3, ks)

    ! NP, NP1 - маппинг метео-узлов на гидро-узлы. NAT - начальная дата [год,мес,день,час].
    integer :: np(is4, js4), np1(1330, 4), nat(li)
    character(len=20) :: vix1, vix2, nam

    ! Прочие переменные из блоков (сведены вместе для удобства)
    real :: mapp, anpr(5), wicpr(5), hpr(5)
    real :: ccc(4), bbb(4), om(4), faz1(is1, li), faz2(js1, li), faz3(is1, li)
