! =========================================================================================
! Модуль: param
! Назначение: Централизованное хранилище глобальных массивов, физических
!             констант и параметров пространственно-временной сетки.
! Физика: Задает базовые параметры аппроксимации Буссинеска. Определяет
!         размерность B-сетки Аракавы (IS1, JS1, KS). Хранит трехмерные поля
!         температуры, солености, плотности и компонент скорости, а также
!         спектральные категории толщины морского льда.
! Ответственность: Выделение статической памяти. Обеспечение доступа всех
!                  вычислительных модулей к единому состоянию термодинамической
!                  системы.
! Параметры сетки: Горизонтальный шаг порядка 13.89 км и 18 вертикальных
!                  Z-уровней. В нем же резервируется память под многоуровневую модель
!                  распределения льда (Thorndike ice thickness distribution),
!                  включающую открытую воду и пять категорий льда различной толщины.
! Единицы измерения: CGS для гидродинамики (dx[см], dt[с], U/V[см/с]),
!                    SI для термодинамики (T[degC], S[массовая доля], h[м]).
!                    Скорость льда в динамике [м/с], в адвекции — перевод в [см/с].
! ==========================================================================================

module param
    implicit none

    ! Параметры сетки
    ! IS, JS - число ячеек по X(Y); KS - число Z-уровней.
    ! IS1=IS+1, JS1=JS+1, KS1=KS+1 — размеры с ghost-узлами для границ.
    integer, parameter :: is = 132, js = 104, ks = 18, is1 = 133, js1 = 105, ks1 = 19
    integer, parameter :: is2 = 131, js2 = 103, ks2 = 17
    ! IS3, JS3 — расширенные размеры для тензоров деформации (EPR).
    integer, parameter :: is3 = 134, js3 = 106, ngr = 5, ngr1 = 6, ngr2 = 4
    integer, parameter :: is4 = 135, js4 = 107
    integer, parameter :: li = 4, lj = 35

    ! Массивы океанского блока
    ! MAP1 - усредненная глубина ячейки [см].
    ! Z, DZ, DZ1 - вертикальные координаты: Z[см] глубина центра уровня,
    !              DZ[см] толщина полного слоя, DZ1[см] толщина полуслоя.
    ! U1, U2, V1, V2 - компоненты скорости тока [см/с] на текущем/предыдущем шаге.
    !                  U1/V1 — шаг DT, U2/V2 — шаг DT1 (баротропный).
    ! FKU - параметр Кориолиса [1/с] в U-точках.
    ! DRX, DRY - бароклинные градиенты давления [см/с²] (отключены в shallow_water).
    ! SKZ - вертикальный турбулентный обмен тепла/соли [см²/с].
    real :: map1(is1, js1), z(ks), dz(ks1), dz1(ks), &
            u1(is1, js1, ks), u2(is1, js1, ks), v1(is1, js1, ks), v2(is1, js1, ks), &
            fku(is1, js1), drx(is1, js1), dry(is1, js1), skz(is1, js1)

    double precision :: uca(ks1), unu(ks1), vca(ks1), vnu(ks1)

    ! HU, HV - глубины на гранях U и V [см].
    ! Y1, Y2 - возвышение свободной поверхности [см] (мгновенное/накопленное).
    ! UP1, UP2, VP1, VP2 - интегральные потоки U и V [см²/с].
    ! FI, DL - широта и долгота [градусы].
    ! FU, FV - Кориолис на U- и V-гранях [1/с].
    ! YM1, YM2 - накопленные и усредненные уровни моря [см].
    ! ADX, ADY - вертикальные маски адвекции (1=вода, 0=дно).
    ! AMP, FAZ, QQ, Q - амплитуды/фазы приливов и их угловые частоты [рад/с].
    ! YYV, V00, AMP1/2/3, UF1/2, VF1/2, UUF, VVF - рабочие массивы приливно-баротропного расчета.
    ! APN, WIU, WIV - вспомогательные массивы fortran-legacy.
    real :: hu(is1, js1), hv(is1, js1), y1(is1, js1), y2(is1, js1), &
            up1(is1, js1), up2(is1, js1), vp1(is1, js1), vp2(is1, js1), &
            fi(is1, js1), dl(is1, js1), fu(is1, js1), fv(is1, js1), &
            ym1(is1, js1), ym2(is1, js1), adx(is1, js1, ks1), ady(is1, js1, ks1), &
            amp(li, lj), faz(li, lj), qq(li), q(li), yyv(5000), v00(li), &
            amp1(133, 4), amp2(105, 4), amp3(133, 4), &
            uf1(5000), vf1(5000), uf2(5000), vf2(5000), uuf(5000), vvf(5000), &
            apn(5000, ngr1), wiu(5000), wiv(5000)

    ! T1/T2, S1/S2 - температура [degC] и соленость [массовая доля] на шагах DT и DT1.
    real :: t1(is1, js1, ks), t2(is1, js1, ks), s1(is1, js1, ks), s2(is1, js1, ks)

    ! HT - глубина в T-точках [см]. RO - аномалия плотности [г/см³].
    ! W - вертикальная скорость [см/с]. TT, SS, RR - временные массивы W-блока.
    ! SKT - вертикальный турбулентный обмен тепла на границе лед/вода [м²/с].
    ! CD, APX, APY, APZ - коэффициенты вертикального обмена и имплицитной схемы.
    real :: ht(is1, js1), ro(is1, js1, ks), &
            w(is1, js1, ks1), tt(ks1), ss(ks1), rr(ks1), skt(is1, js1), &
            cd(is1, js1, ks), apx(is1, js1, ks), apy(is1, js1, ks), apz(is1, js1, ks1)

    ! Маски: KK1 - ячейка воды для U/V; KT1 - индекс дна (число мокрых уровней).
    ! IDX, IDY - вертикальные границы для W (минимальный из двух соседей).
    ! IT - идентификатор береговой конфигурации для адвекции льда.
    ! KUSH, KVSH - флаг активной U/V-грани (1=внутренняя, 0=берег).
    ! IKU, IKV - число мокрых V/U-соседей (граничные условия no-slip/free-slip).
    ! IIP - вспомогательный массив legacy.
    integer :: kk1(is1, js1), kt1(is1, js1), idx(is1, js1), idy(is1, js1), &
               it(is1, js1), kush(is1, js1), kvsh(is1, js1), iku(is1, js1), ikv(is1, js1), &
               iip(is1, js1)

    ! Массивы ледового блока
    ! U0, V0, U, V - скорость льда [м/с] (предыдущая/текущая) и рабочие копии.
    ! WICE1 - объем льда в категории [м] (эквивалентно A_k * h_k).
    ! AN1 - площадь категории: AN1(:,:,1) = открытая вода; AN1(:,:,k+1) = категория k.
    ! HICE - толщина льда в категории [м]. AN3, WICES, HICES, ANS - агрегированные поля.
    ! CD2 - тензор деформации (промежуточный). TXIC, TYIC - напряжение воды на лед [м/с²].
    ! APX2, APY2 - антидиффузионные потоки FCT для льда.
    ! EXX, EYY, EXY - компоненты тензора деформации [1/с] (хранятся в EPR для deform).
    ! EPR - рабочий массив [is3, js3] для тензоров деформации (с halo).
    ! SXX, SYY, SXY - внутренние напряжения льда [дина/см² или см/с² — см. ice_stress].
    ! HSNOW - толщина снега в категории [м].
    ! TPAR, SPAR - температура [K] и соленость [доля] поверхности/внутри льда.
    ! ANP, DANP, HSNP, HICP - рабочие копии площади, приращения, снега, толщины в heat().
    ! SICST - критическая соленость категории [доля]. HST - характерная толщина категории [м].
    ! HMAX - верхняя граница толщины категории [м]. ALSN - альбедо снега по месяцам.
    real :: u0(is1, js1), v0(is1, js1), u(is1, js1), v(is1, js1), &
            wice1(is1, js1, ngr), an1(is1, js1, ngr1), hice(is1, js1, ngr), &
            an3(is1, js1), wices(is1, js1), hices(is1, js1), ans(is1, js1), &
            cd2(is1, js1), txic(is1, js1), tyic(is1, js1), &
            apx2(is1, js1), apy2(is1, js1), exx(is1, js1), eyy(is1, js1), &
            exy(is1, js1), epr(is3, js3), sxx(is1, js1), syy(is1, js1), sxy(is1, js1), &
            hsnow(is1, js1, ngr), tpar(ngr1), spar(ngr1), &
            anp(ngr), danp(ngr), hsnp(ngr), hicp(ngr), &
            sicst(ngr), hst(ngr), hmax(ngr), alsn(12)

    ! Массивы метеорологических данных
    ! TX, TY - касательное напряжение ветра [дина/см²].
    ! TX1, TY1, DPX1, DPY1, WINDX1, WINDY1 - целевые поля для 12-часовой интерполяции.
    ! DPX, DPY - градиенты атмосферного давления [гПа/км] или [hPa/100км].
    ! TATM1, TATM - температура воздуха [degC] (месячная/интерполированная).
    ! CLOUD1, CLOUD - облачность [доли единицы]. HUMID - влажность [доли единицы].
    ! PATM - атмосферное давление [гПа = 100 Pa].
    ! WIND - модуль скорости геострофического ветра [м/с].
    ! WMONTH, SFAL - месячные веса и снегопад [м/с].
    ! WINDX, WINDY - компоненты ветра [см/с] для диагностики.
    ! P, PP - поле давления на метео-сетке и интерполированное [гПа].
    ! X01, Y01 - координаты метео-узлов [градусы/индексы].
    ! TC1/2/3/4, SC1/2/3/4 - климатологические профили T/S на разрезах.
    real :: tx(is1, js1), ty(is1, js1), dpx(is1, js1), dpy(is1, js1), &
            tx1(is1, js1), ty1(is1, js1), dpx1(is1, js1), dpy1(is1, js1), &
            tatm1(is1, js1, 12), tatm(is1, js1), cloud1(is1, js1, 12), &
            cloud(is1, js1), humid(is1, js1), patm(is1, js1), wind(is1, js1), &
            wmonth(12), sfal(12), era5_snowfall_rate(is1, js1), &
            windx1(is1, js1), windy1(is1, js1), windx(is1, js1), &
            windy(is1, js1), &
            p(1420, 100), pp(1420), x01(1330), y01(1330), &
            tc1(is1, ks), sc1(is1, ks), &
            tc2(js1, ks), sc2(js1, ks), &
            tc3(15, ks), sc3(15, ks), &
            tc4(3, ks), sc4(3, ks)

    ! NP, NP1 - маппинг метео-узлов на гидро-узлы. NAT - начальная дата [год,мес,день,час].
    integer :: np(is4, js4), np1(1330, 4), nat(li)
    character(len=20) :: vix1, vix2, nam

    ! Прочие переменные из блоков (сведены вместе для удобства)
    real :: mapp, anpr(5), wicpr(5), hpr(5)
    real :: ccc(4), bbb(4), om(4), faz1(is1, li), faz2(js1, li), faz3(is1, li)
    real :: fi1(is4, js4), dl1(is4, js4), tauu(is1, js1), &
            alf(is1, js1), pp1(is4, js4), zzz(is1, js1), p1(is1, js1)
    character(len=10) :: ewin, ep, evet
    real :: pp2(is4, js4)
    ! FFF - узловые поправки к амплитудам приливов (long-period nodal factors).
    real :: fff(li)
    integer :: mmm(12)

    ! Режимы внешнего форсинга.
    ! forcing_mode_legacy - старый путь: DAV4_5.98 -> p -> геострофический ветер.
    ! forcing_mode_era5  - новый путь: NetCDF (u10/v10/msl/t2m) -> интерполяция.
    integer, parameter :: forcing_mode_legacy = 0
    integer, parameter :: forcing_mode_era5 = 1
    integer :: forcing_mode = forcing_mode_legacy

    ! Режим модельной сетки координат.
    ! grid_mode_real - координаты FI/DL читаются из KOORD.DAT (REAL grid).
    ! grid_mode_test  - синтетическая сетка TEST ONLY (KOORD.DAT отсутствует).
    integer, parameter :: grid_mode_real = 0
    integer, parameter :: grid_mode_test = 1
    integer :: grid_mode = grid_mode_test

    ! --- Конфигурация прогона (Stage 6.2: изоляция выходов по run_id) ---
    ! Каждый научный прогон пишет выходы в data/runs/<run_id>/output/{nc,csv,txt,logs,figures}.
    ! run_id задаётся первым аргументом командной строки main (например
    ! '2020_Q1_test_heat_on'), по умолчанию - исторический Q1-прогон.
    ! ERA5 input по умолчанию указывает на processed-файл новой структуры
    ! data/input/processed/era5/<YYYY>/<YYYY_MM>/.
    character(len=64) :: run_id = '2020_Q1_test_heat_on'
    character(len=256) :: run_output_dir = ''
    character(len=256) :: run_nc_dir = ''
    character(len=256) :: run_csv_dir = ''
    character(len=256) :: run_txt_dir = ''
    character(len=256) :: run_log_dir = ''
    character(len=256) :: run_fig_dir = ''
    character(len=256) :: era5_input_file = 'data/input/processed/era5/2020/2020_Q1/era5_2020_0103_barents_expanded_merged.nc'

    ! Инициализация данных (блок DATA)
    ! Z - глубины центров 18 Z-уровней [см].
    data z/250., 500., 1000., 1500., 2000., 2500., 3000., 4000., &
        5000., 7500., 10000., 15000., 20000., 25000., &
        30000., 40000., 50000., 60000./
    ! HST - характерная толщина 5 категорий льда [м].
    data hst/0.2, 0.5, 0.95, 1.6, 2.5/
    ! HMAX - верхние границы толщины категорий [м]; 50.0 для последней = "бесконечность".
    data hmax/0.3, 0.7, 1.20, 2.0, 50./
    ! SICST - критическая соленость для замерзания [массовая доля].
    data sicst/10.e-3, 6.e-3, 5.e-3, 4.5e-3, 4.e-3/
    ! ALSN - альбедо снега по месяцам (янв-дек).
    data alsn/0.85, 0.85, 0.83, 0.81, 0.82, 0.78, 0.64, 0.69, 0.84, &
        0.85, 0.85, 0.85/
    ! SFAL - месячный снегопад [м/с]. Инициализируем нулями для тестов HEAT.
    ! Реалистичные значения ~1e-6..1e-5 м/с (мм/ч).
    data sfal/12*0.0/
    ! MMM - число дней в месяцах (невисокосный год).
    data mmm/31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31/

end module param
