! ==============================================================================
! Модуль: shallow_water (shal)
! Назначение: Баротропный цикл мелкой воды — обновление возвышения свободной
!             поверхности η (уровень моря) и интегральных потоков UP2/VP2.
! Физика: Решает уравнения мелкой воды (shallow water equations):
!           Уравнение неразрывности (continuity):
!             ∂η/∂t + ∇·(H·U) = 0
!           Уравнения движения (momentum):
!             ∂U/∂t + g·H·∂η/∂x = -f·V + τ_wind/(ρ·H) - r·U + A_h·∇²U
!             ∂V/∂t + g·H·∂η/∂y = +f·U + τ_wind/(ρ·H) - r·V + A_h·∇²V
!         где:
!           η [см]  — возвышение свободной поверхности (y2)
!           U,V [см²/с] — интегральные потоки (∫u·dz, ∫v·dz)
!           H = map1+η [см] — полная глубина
!           g = 981 [см/с²] — ускорение свободного падения
!           f = FU/FV [1/с] — параметр Кориолиса
!           τ_wind [дин/см²] — касательное напряжение ветра на поверхности
!           r = 0.0026·dt1/(H²) — коэффициент трения о дно [с⁻¹]
!           A_h = 7.5×10⁶ [см²/с] — горизонтальная турбулентная вязкость
!
!         Схема расщепления (splitting method):
!           1. Мелкая вода (shal) — 30 баротропных микрошагов (dt1=120 с)
!              за один бароклинный шаг (dt=3600 с). Обновляет η и UP2/VP2.
!           2. Адвекция импульса (advsh) — транспорт UP2/VP2 на каждом
!              микрошаге по схеме Лейса-Рихтмайера.
!
!         Граничные условия:
!           - На гранях модели задаются приливные компоненты (M2,S2,K1,O1)
!             через амплитуды amp1/amp2/amp3 и фазы faz1/faz2/faz3.
!           - Внутри модели — свободный поток (free-slip).
!
!         Трение о дно (bottom drag):
!           u₂ = u₁/(1 + C_d·|u₁|/H), где C_d = 0.0026·dt1 [см]
!           C_d = r_base·dt1, r_base = 0.0026 [1/с] — линейный коэффициент трения.
!           Минимальная глубина clamp: H_min = 50 см (защита от деления на 0).
!
! Единицы (CGS для гидродинамики):
!   UP1, UP2 — интегральные потоки U [см²/с]
!   VP1, VP2 — интегральные потоки V [см²/с]
!   Y2       — возвышение свободной поверхности [см]
!   YM2      — накопленный/усреднённый уровень моря [см] (для block 280)
!   HT, HU, HV — глубины в T/U/V-точках [см]
!   DPX, DPY — градиент атмосферного давления [hPa/см] (= Па/(100·см))
!   TX, TY   — касательное напряжение ветра [дин/см²]
!   FU, FV   — параметр Кориолиса [1/с]
!   c1 = g = 981 [см/с²]
!   c3 = A_h/dx² [1/с] — нормализованный коэффициент вязкости
!   c9 = 0.5/dx [1/см] — множитель градиента
!   c10 = dt1/dx [с/см] — число Куранта
!   aa1 = g/dx [см/с³] — множитель градиента давления (для η-терма)
!   aa2 = 0.0026·dt1 [см] — множитель донного трения
!   aa3 = 0.0055·dt1 [см] — множитель трения лёд-вода (не используется в shal)
!   dt1 = 120 [с] — баротропный шаг по времени
!   dx = 1 389 000 [см] — пространственный шаг сетки
!   mm3 = 30 — число баротропных микрошагов за бароклинный
!
! Сетка: B-сетка Аракавы. UP2 на U-гранях (j), VP2 на V-гранях (i).
!        η на T-точках (центры ячеек).
!        Оси: X ↔ j, Y ↔ i (ось Y инвертирована: j=1 — север).
!
! Массивы:
!   om(4)   — угловые частоты приливных гармоник [рад/с на баротропный шаг]
!   q(4)    — те же частоты, переведённые в радианы (из qq [°/час])
!   jjq     — общий счётчик баротропных шагов (для приливного времени)
!   euu     — кинетическая энергия U² (диагностика)
!   ym2     — накопленный уровень моря (суммируется, затем усредняется)
!
! Ответственность: Вычисление η и интегральных потоков для баротропного цикла.
! ==============================================================================

module shallow_water
    use param
    use barotropic_dynamics, only: advsh
    implicit none

    ! Глобальные переменные, сохраняющие состояние между вызовами shal().
    ! jjq — общий счётчик баротропных шагов для приливных частот (om = q*jjq).
    ! euu — кинетическая энергия для диагностики: euu += UP2² + VP2².
    integer, save, public :: jjq = 0
    real, save, public :: euu = 0.0

contains

    subroutine shal()
        ! Локальные переменные
        integer :: i, j, k, i1, i2, j1, j2, ki, jjj, ij, uuk
        real :: hht, a, b, a1, a2, b2, vs, us, uij, vij, uu1, uu2, vv1, vv2
        real :: yy1, yy2, hh1, h1, h2, uup

        ! Константы (перенесены из старого глобального файла для локальности)
        real :: dt1, dx, c1, c3, c9, c10, aa1, aa2, aa3
        integer :: mm3

        ! === ОПРЕДЕЛЕНИЕ КОНСТАНТ ===
        ! dt1 = 120 [с] — баротропный шаг по времени (micro-step).
        !   Число Куранта Cr = g·H·dt1²/dx² ≈ 981·5000·120²/1.389e6² ≈ 0.03 (стабильно).
        dt1 = 120.0
        ! dx = 1 389 000 [см] — горизонтальный шаг сетки (~13.89 км)
        dx = 1389000.0
        ! mm3 = 30 — число баротропных микрошагов за бароклинный шаг dt=3600 с
        !   (30 × 120 = 3600 с)
        mm3 = 30
        ! c1 = g/rho0 = 981/1 = 981 [см/с² / (г/см³)] = [см⁴·г⁻¹·с⁻²]
        !   Используется как g при расчёте уровня: Y2 -= c10·div(H·U)
        c1 = 981.0/1.0
        ! c3 = A_h/dx² = 7.5e6/(1.389e6)² ≈ 3.89e-6 [1/с]
        !   Горизонтальная турбулентная вязкость, нормализованная на dx².
        c3 = 7.5e6/(dx*dx)
        ! c9 = 0.5/dx ≈ 3.60e-7 [1/см]
        !   Множитель для вычисления градиентов уровня в бароклинных блоках.
        c9 = 0.5/dx
        ! c10 = dt1/dx ≈ 8.64e-5 [с/см]
        !   Число Куранта для уравнения непрерывности: Y2 -= c10·div(UP)
        c10 = dt1/dx
        ! aa1 = g/dx = 981/1.389e6 ≈ 7.06e-4 [см/с³]
        !   Множитель градиента уровня в уравнении импульса: -(YY1-YY2)·aa1·H
        aa1 = 981.0/dx
        ! aa2 = r_base·dt1 = 0.0026·120 = 0.312 [см]
        !   Множитель донного трения: denominator = 1 + aa2·|u|/H²
        !   r_base = 0.0026 [1/с] — линейный коэффициент трения о дно
        aa2 = 0.0026*dt1
        ! aa3 = 0.0055·120 = 0.66 [см]
        !   Коэффициент трения лёд-вода (не используется в shal, нужен в block 210)
        aa3 = 0.0055*dt1

        ym2(:, :) = 0.0

        ! --- ОТКЛЮЧЁННЫЙ БЛОК: РАСЧЕТ ГРАДИЕНТОВ DRX/DRY ---
        ! В оригинальном коде этот блок был аппаратно отключен
        ! через безусловный переход GOTO 900 (прыжок к основному циклу).
        ! DRX/DRY — бароклинные градиенты давления [см/с²].
        ! Оставляем его выключенным (if (.false.)) для обратной совместимости.
        if (.false.) then
            ! --- Градиент DRX по оси X (j-направление) ---
            ! DRX = g·∫₀ᴴ (ρ(x,j) - ρ(x,j-1))·z·dz / dx
            ! Вычисляется через суммирование по вертикальным слоям с шагом c9 = 0.5/dx
            do j = 2, js2
                do i = 2, is2
                    hht = hu(i, j)
                    if (abs(hht - 8888.0) .lt. 1e-8) cycle
                    j2 = j - 1
                    a = 0.0
                    b = 0.0
                    a1 = 0.0
                    a2 = 0.0
                    ki = min(kt1(i, j), kt1(i, j2))
                    do k = 1, ki
                        if (k .eq. ki) then
                            b2 = hht - a2           ! Толщина нижнего (неполного) слоя [см]
                        else
                            b2 = dz1(k)             ! Толщина полуслоя [см]
                            a2 = a2 + b2
                        end if
                        b = b + (ro(i, j, k) - ro(i, j2, k))*b2*c9
                        a1 = a1 + (a + b)*b2*0.5
                        a = b
                    end do
                    drx(i, j) = c1*a1              ! [см/с²]
                end do
            end do

            ! --- Градиент DRY по оси Y (i-направление) ---
            do j = 2, js2
                do i = 2, is2
                    hht = hv(i, j)
                    if (abs(hht - 8888.0) .lt. 1e-8) cycle
                    i2 = i - 1
                    a = 0.0
                    b = 0.0
                    a1 = 0.0
                    a2 = 0.0
                    ki = min(kt1(i, j), kt1(i2, j))
                    do k = 1, ki
                        if (k .eq. ki) then
                            b2 = hht - a2
                        else
                            b2 = dz1(k)
                            a2 = a2 + b2
                        end if
                        b = b + (ro(i2, j, k) - ro(i, j, k))*b2*c9
                        a1 = a1 + (a + b)*b2*0.5
                        a = b
                    end do
                    dry(i, j) = c1*a1              ! [см/с²]
                end do
            end do
        end if

        ! ================================================================
        ! ОСНОВНОЙ БАРОТРОПНЫЙ ЦИКЛ (MM3 = 30 шагов по dt1 = 120 с)
        ! ================================================================
        ! За один бароклинный шаг dt = 3600 с выполняется 30 микрошагов.
        ! На каждом микрошаге:
        !   1. Сохраняем UP1=UP2, VP1=VP2 (предыдущее состояние)
        !   2. Обновляем η (уровень моря) по уравнению непрерывности
        !   3. Задаём приливные граничные условия на η
        !   4. Обновляем U-компоненту (UP2) по уравнению движения
        !   5. Задаём граничные условия для UP2
        !   6. Обновляем V-компоненту (VP2) по уравнению движения
        !   7. Задаём граничные условия для VP2
        !   8. Адвектируем UP2/VP2 через advsh(dt1) (схема Лейса-Рихтмайера)

        do jjj = 1, mm3
            jjq = jjq + 1                     ! Общий счётчик баротропных шагов
            ! Приливные угловые частоты: om = q · jjq [рад]
            ! q(1..4) = qq(1..4) · dt1 / 3600 / 57.2958 [рад/шаг]
            om(1:4) = q(1:4)*real(jjq)

            ! Сохранение предыдущего состояния потоков
            up1(:, :) = up2(:, :)
            vp1(:, :) = vp2(:, :)

            ! --- УРОВЕНЬ МОРЯ (уравнение непрерывности) ---
            ! Y2_new = Y2_old - (dt1/dx)·(UP(i,j+1) - UP(i,j) + VP(i,j) - VP(i+1,j))
            ! Это дискретизация ∂η/∂t = -∇·(H·U/H) = -∇·U  [см/с]
            ! (divergence интегральных потоков)
            do j = 2, js
                do i = 2, is
                    if (abs(ht(i, j) - 8888.0) .lt. 1e-8) cycle
                   y2(i, j) = y2(i, j) - c10*(up1(i, j + 1) - up1(i, j) + vp1(i, j) - vp1(i + 1, j))
                end do
            end do

            ! --- ПРИЛИВНЫЕ ГРАНИЧНЫЕ УСЛОВИЯ НА η ---
            ! η = Σₙ Aₙ·cos(ωₙ·t + (V₀ₙ - φₙ)/57.3)
            ! 4 гармоники: M2 (луна, 12.42 ч), S2 (солнце, 12 ч),
            !              K1 (луна+солнце, 23.93 ч), O1 (луна, 25.82 ч).
            ! amp1/amp2/amp3 — амплитуды на северной, западной, южной границах.
            ! faz1/faz2/faz3 — фазы (в градусах, переводятся через /57.3).
            ! fff — узловая поправка к амплитудам (long-period nodal correction).
            ! v00 — астрономическая фаза начальной даты.
            ! 57.3 ≈ 180/π — перевод градусов в радианы.
            do i = 1, 133
                y2(i, 1) = fff(1)*amp1(i, 1)*cos(om(1) + (v00(1) - faz1(i, 1))/57.3) + &
                           fff(2)*amp1(i, 2)*cos(om(2) + (v00(2) - faz1(i, 2))/57.3) + &
                           fff(3)*amp1(i, 3)*cos(om(3) + (v00(3) - faz1(i, 3))/57.3) + &
                           fff(4)*amp1(i, 4)*cos(om(4) + (v00(4) - faz1(i, 4))/57.3)
            end do

            ! Западная граница (j=1, i=1..105)
            do i = 1, 105
                y2(1, i) = fff(1)*amp2(i, 1)*cos(om(1) + (v00(1) - faz2(i, 1))/57.3) + &
                           fff(2)*amp2(i, 2)*cos(om(2) + (v00(2) - faz2(i, 2))/57.3) + &
                           fff(3)*amp2(i, 3)*cos(om(3) + (v00(3) - faz2(i, 3))/57.3) + &
                           fff(4)*amp2(i, 4)*cos(om(4) + (v00(4) - faz2(i, 4))/57.3)
            end do

            ! Южная граница (j=JS=104, i=1..133)
            do i = 1, 133
                y2(i, js) = fff(1)*amp3(i, 1)*cos(om(1) + (v00(1) - faz3(i, 1))/57.3) + &
                            fff(2)*amp3(i, 2)*cos(om(2) + (v00(2) - faz3(i, 2))/57.3) + &
                            fff(3)*amp3(i, 3)*cos(om(3) + (v00(3) - faz3(i, 3))/57.3) + &
                            fff(4)*amp3(i, 4)*cos(om(4) + (v00(4) - faz3(i, 4))/57.3)
            end do

            ! Накопление η для усреднения: YM2 += Y2 (потом YM2/mm3)
            ym2(:, :) = ym2(:, :) + y2(:, :)

            ! ================================================================
            ! U-КОМПОНЕНТА: РАСЧЕТ ИНТЕГРАЛЬНОГО ПОТОКА UP2
            ! ================================================================
            ! Уравнение движения для U-компонента интегрального потока:
            !   UP2 = UP1 + dt1·[
            !     -(η(i,j) - η(i,j-1))·g·H/dx           ← градиент уровня
            !     - H·(DPX(i) + DPX(i+1))/2              ← градиент атмос. давления
            !     + 0.125·f·(HV_sum)                      ← сила Кориолиса
            !     + (1-A₁)·(TX_wind + TX_ice)/2           ← ветровое напряжение
            !     + A_h/dx²·∇²(UP)                        ← горизонтальная диффузия
            !   ] / (1 + C_d·|u|/H)                       ← донное трение (implicit)
            !
            ! HV_sum — сумма VP1/ HV по 4 соседним V-ячейкам (косвенный поток).
            ! A₁ = 0.5·(ANS(i,j)+ANS(i,j-1)) — средняя сплошность льда на U-грани.
            ! H_eff = HT + (Y2(i,j) + Y2(i,j-1))/2 — эффективная глубина [см].
            ! H_min = 50 см — защита от вырождения (мелководье).

            do j = 2, js
                j1 = j + 1
                j2 = j - 1
                do i = 2, is
                    hht = hu(i, j)                       ! Глубина на U-грани [см]
                    if (abs(hht - 8888.0) .lt. 1e-8) cycle

                    uuk = iku(i, j)    ! Число мокрых V-соседей (для усреднения)
                    i1 = i + 1
                    i2 = i - 1

                    ! Суммирование VP1/HV по 4 соседним V-ячейкам (для Кориолиса)
                    bbb(1) = hv(i, j2)    ! Глубина V-ячейки (i, j-1)
                    bbb(2) = hv(i, j)     ! Глубина V-ячейки (i, j)
                    bbb(3) = hv(i1, j2)   ! Глубина V-ячейки (i+1, j-1)
                    bbb(4) = hv(i1, j)    ! Глубина V-ячейки (i+1, j)
                    ccc(1) = vp1(i, j2)   ! Поток V в (i, j-1)
                    ccc(2) = vp1(i, j)    ! Поток V в (i, j)
                    ccc(3) = vp1(i1, j2)  ! Поток V в (i+1, j-1)
                    ccc(4) = vp1(i1, j)   ! Поток V в (i+1, j)

                    ! Суммарный V-поток на U-грани [см²/с]
                    vs = 0.0
                    do ij = 1, 4
                        if (abs(bbb(ij) - 8888.0) .lt. 1e-8) cycle
                        a = ccc(ij)/bbb(ij)      ! Средняя V-скорость [см/с]
                        vs = vs + (bbb(ij) + hht)*a
                    end do

                    uij = up1(i, j)               ! Текущий U-поток [см²/с]

                    ! Граничные условия: на краю модели UP2(i边界) = UP2(i内)
                    if (i .eq. is .or. abs(hu(i1, j) - 8888.0) .lt. 1e-8) then
                        uu1 = uij
                    else
                        uu1 = up1(i1, j)
                    end if

                    if (i .eq. 1 .or. abs(hu(i2, j) - 8888.0) .lt. 1e-8) then
                        uu2 = uij
                    else
                        uu2 = up1(i2, j)
                    end if

                    ! Средняя V-скорость на U-грани [см/с] (для Кориолиса)
                    a = (ccc(1) + ccc(2) + ccc(3) + ccc(4))/real(uuk)

                    ! Средняя сплошность льда на U-грани [безразм.]
                    ! A₁ = 0.5·(ANS(i,j) + ANS(i,j-1))
                    a1 = 0.5*(ans(i, j) + ans(i, j2))

                    ! Градиент уровня по X [см]
                    yy1 = y2(i, j)
                    yy2 = y2(i, j2)

                    ! Эффективная глубина на U-грани [см]
                    hh1 = hht + (yy1 + yy2)*0.5
                    if (hh1 .le. 50.0) hh1 = 50.0   ! Защита от мелководья

                    ! Множители для градиента и трения
                    h1 = aa1*hh1        ! g·H/dx [см/с³] · [см] = [см²/с³]
                    h2 = aa2/(hh1*hh1)  ! C_d/H² [см⁻¹]

                    ! --- УРАВНЕНИЕ ДВИЖЕНИЯ U ---
                    ! UP2 = [UP1 + dt1·(F_cor + F_wind + F_diff + F_grad)] / (1 + F_drag)
                    ! где:
                    !   F_cor = 0.125·f·vs              ← Кориолис (cos f ≈ отсутствует, sin f)
                    !   F_wind = (1-A₁)·TX_avg          ← ветровое напряжение (только на открытую воду)
                    !   F_diff = c3·∇²(UP1)             ← горизонтальная диффузия (Лапласиан)
                    !   F_grad = -(YY1-YY2)·g·H/dx      ← градиент уровня свободной поверхности
                    !   F_grad2 = -H·DPX_avg            ← градиент атмосферного давления
                    !   F_drag = C_d·|u|/H              ← донное трение (в знаменателе)
                    uup = (uij + dt1*(-(yy1 - yy2)*h1 &
                                      - hh1*0.5*(dpx(i, j) + dpx(i1, j)) &
                                      + 0.125*fu(i, j)*vs &
                                      + (1.0 - a1)*0.5*(tx(i, j) + tx(i1, j)) &
                                      + c3*(uu1 + uu2 + up1(i, j1) + up1(i, j2) - 4.0*uij))) &
                          /(1.0 + h2*sqrt(uij*uij + a*a))

                    euu = euu + uup*uup             ! Кинетическая энергия (диагностика)
                    up2(i, j) = uup
                end do
            end do

            ! --- ГРАНИЧНЫЕ УСЛОВИЯ ДЛЯ U ---
            ! На северной границе (j=1): UP2 = UP2(j=2) (свободный поток).
            ! Первичное значение UP2(i,1) = -η(i,1)·√(g·H) — волновой импеданс,
            ! но перезаписывается UP2(i,2) (оригинальный код Нестерова).
            do i = 1, is
                hht = hu(i, 2)
                if (abs(hht - 8888.0) .lt. 1e-8) cycle
                up2(i, 1) = -y2(i, 1)*sqrt(981.0*hht)   ! Волновой импеданс
                up2(i, 1) = up2(i, 2)                     ! Перезапись (legacy)
            end do

            ! Особая область (юго-запад, i=1..15, j=95): аналогично
            do i = 1, 15
                hht = ht(i, 94)
                up2(i, 95) = y2(i, 94)*sqrt(981.0*hht)
                up2(i, 95) = up2(i, 94)
            end do

            ! ================================================================
            ! V-КОМПОНЕНТА: РАСЧЕТ ИНТЕГРАЛЬНОГО ПОТОКА VP2
            ! ================================================================
            ! Аналогично U-компоненте, но для Y-направления.
            ! Уравнение движения для V:
            !   VP2 = VP1 + dt1·[
            !     +(η(i+1,j) - η(i,j))·g·H/dy    ← градиент уровня (знак + для V)
            !     - H·(DPY(j) + DPY(j+1))/2       ← градиент атмос. давления
            !     - 0.125·f·(HU_sum)               ← сила Кориолиса (противоположный знак)
            !     + (1-A₁)·(TY_wind + TY_ice)/2    ← ветровое напряжение
            !     + A_h/dx²·∇²(VP1)                ← горизонтальная диффузия
            !   ] / (1 + C_d·|v|/H)
            ! HU_sum — сумма UP2/HU по 4 соседним U-ячейкам.

            do j = 2, js
                j1 = j + 1
                j2 = j - 1
                do i = 2, is
                    hht = hv(i, j)
                    if (abs(hht - 8888.0) .lt. 1e-8) cycle

                    uuk = ikv(i, j)
                    i1 = i + 1
                    i2 = i - 1

                    ! Суммирование UP2/HU по 4 соседним U-ячейкам (для Кориолиса)
                    bbb(1) = hu(i, j)
                    bbb(2) = hu(i2, j)
                    bbb(3) = hu(i2, j1)
                    bbb(4) = hu(i, j1)
                    ccc(1) = up2(i, j)     ! U-поток (уже обновлённый)
                    ccc(2) = up2(i2, j)
                    ccc(3) = up2(i2, j1)
                    ccc(4) = up2(i, j1)

                    ! Суммарный U-поток на V-грани [см²/с]
                    us = 0.0
                    do ij = 1, 4
                        if (abs(bbb(ij) - 8888.0) .lt. 1e-8) cycle
                        a = ccc(ij)/bbb(ij)
                        us = us + (bbb(ij) + hht)*a
                    end do

                    vij = vp1(i, j)

                    ! Граничные условия для V
                    if (j .eq. js .or. abs(hv(i, j1) - 8888.0) .lt. 1e-8) then
                        vv1 = vij
                    else
                        vv1 = vp1(i, j1)
                    end if

                    if (j .eq. 1 .or. abs(hv(i, j2) - 8888.0) .lt. 1e-8) then
                        vv2 = vij
                    else
                        vv2 = vp1(i, j2)
                    end if

                    ! Средняя U-скорость на V-грани [см/с]
                    a = (ccc(1) + ccc(2) + ccc(3) + ccc(4))/real(uuk)

                    ! Средняя сплошность льда на V-грани
                    a1 = 0.5*(ans(i, j) + ans(i2, j))

                    ! Градиент уровня по Y [см]
                    yy1 = y2(i2, j)
                    yy2 = y2(i, j)

                    ! Эффективная глубина [см]
                    hh1 = hht + (yy1 + yy2)*0.5
                    if (hh1 .le. 50.0) hh1 = 50.0

                    h1 = aa1*hh1
                    h2 = aa2/(hh1*hh1)

                    ! --- УРАВНЕНИЕ ДВИЖЕНИЯ V ---
                    ! Аналогично U, но знак Кориолиса противоположный (-f·U),
                    ! а градиент уровня по Y имеет знак + (j↑ → η↑).
                    uup = (vij + dt1*((yy2 - yy1)*h1 &
                                      - hh1*0.5*(dpy(i, j) + dpy(i, j1)) &
                                      - 0.125*fv(i, j)*us &
                                      + (1.0 - a1)*0.5*(ty(i, j) + ty(i, j1)) &
                                      + c3*(vv1 + vv2 + vp1(i1, j) + vp1(i2, j) - 4.0*vij))) &
                          /(1.0 + h2*sqrt(vij*vij + a*a))

                    euu = euu + uup*uup
                    vp2(i, j) = uup
                end do
            end do

            ! --- ГРАНИЧНЫЕ УСЛОВИЯ ДЛЯ V ---
            ! На западной границе (i=1): VP2 = VP2(i=2) (свободный поток).
            do j = 1, js
                hht = hv(2, j)
                if (abs(hht - 8888.0) .lt. 1e-8) cycle
                vp2(1, j) = y2(1, j)*sqrt(981.0*hht)     ! Волновой импеданс
                vp2(1, j) = vp2(2, j)                      ! Перезапись (legacy)
            end do

            ! Особая область (j=91..93, i=73)
            do j = 91, 93
                vp2(73, j) = y2(73, j)*sqrt(981.0*ht(73, j))
                vp2(73, j) = vp2(74, j)
            end do

            ! ================================================================
            ! АДВЕКЦИЯ ИНТЕГРАЛЬНЫХ ПОТОКОВ (схема Лейса-Рихтмайера + FCT)
            ! ================================================================
            ! Перенос UP2/VP2 потоками (для поддержания схемы расщепления).
            ! См. модуль barotropic_dynamics:advsh() для подробного описания.
            call advsh(dt1)

        end do

        ! Усреднение η по баротропным шагам: YM2 = Σ(Y2) / mm3 [см]
        ! YM2 используется в block 280 для выравнивания бароклинной и баротропной мод.
        ym2(:, :) = ym2(:, :)/real(mm3)

    end subroutine shal

end module shallow_water
