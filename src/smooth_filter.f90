! ==============================================================================
! Модуль: smooth_filter
! Назначение: Сглаживание полей данных (атмосферного давления) явным методом
!             конечных разностей с оператором Лапласа.
! Физика: Реализует пространственное сглаживание атмосферного давления с помощью
!         оператора Лапласа (пятиточечный шаблон: 4 соседа + центр).
!         Данный фильтр подавляет пилообразные осцилляции на масштабе шага сетки,
!         играя роль искусственной вязкости для атмосферных полей.
!         Явная схема: P(t+Δt) = P(t) + factor * ∇²P
!         где ∇²P ≈ (P[i-1,j] + P[i+1,j] + P[i,j+1] + P[i,j-1] - 4*P[i,j])
!         factor = a_coeff * dt / dx²
!           a_coeff = 7e7 [см²/с] — коэффициент диффузии сглаживания.
!           dt = 3600 с — шаг по времени (бароклинный, DT).
!           dx = 1389000 см — шаг сетки.
!         factor ≈ 7e7 * 3600 / (1.389e6)² ≈ 0.131 < 0.25
!         (условие устойчивости явной схемы для 2D теплового уравнения).
!         48 итераций за один вызов → эффективно сглаживает на масштабе ~7*dx.
!         Границы: js3=106, is3=134 включают halo-уровень.
! Единицы: P [гПа]; dx [см]; dt [с]; factor [безразмерный].
! Ответственность: Обработка и улучшение качества численных полей давления
!                  перед расчетом градиентов в wind1.
! ==============================================================================

module smooth_filter
    use param
    implicit none

contains

    subroutine gladw()
        ! Локальные переменные
        integer :: i, j, jj
        real :: dt, a_coeff, dx, factor

        ! Инициализация констант (из оригинального кода)
        dt = 3600.0          ! Бароклинный временной шаг [с] (=1 час)
        a_coeff = 7.e7       ! Коэффициент диффузии сглаживания [см²/с]
        ! физический смысл: искусственная вязкость для подавления
        ! пилообразных осцилляций на масштабе шага сетки
        dx = 1389000.0       ! Горизонтальный шаг сетки [см] (13.89 км)

        ! Коэффициент сглаживания: factor = a_coeff * dt / dx²
        factor = a_coeff*dt/(dx*dx)

        ! Первичное копирование массива PP1 -> PP2
        pp2(:, :) = pp1(:, :)

        ! Основной цикл сглаживания (48 итераций)
        do jj = 1, 48

            ! Применение оператора Лапласа ко внутренним точкам сетки
            ! Границы циклов is3 и js3 соответствуют 134 и 106 (с halo)
            do j = 2, js3
                do i = 2, is3
                    ! Явная схема: P_new = P_old + factor * (Laplacian)
                    ! Лапласиан: P[i-1,j] + P[i+1,j] + P[i,j+1] + P[i,j-1] - 4*P[i,j]
                    pp1(i, j) = pp2(i, j) + factor* &
                     (pp2(i - 1, j) + pp2(i + 1, j) + pp2(i, j + 1) + pp2(i, j - 1) - 4.0*pp2(i, j))
                end do
            end do

            ! Обновление внутренней области рабочего массива PP2
            pp2(2:is3, 2:js3) = pp1(2:is3, 2:js3)

        end do

        ! Возврат сглаженного поля в исходный массив PP1
        pp1(:, :) = pp2(:, :)

    end subroutine gladw

end module smooth_filter
