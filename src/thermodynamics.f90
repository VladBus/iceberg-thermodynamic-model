! ==============================================================================
! Модуль: thermodynamics (heat)
! Назначение: Расчёт теплового баланса на границах раздела и фазовых переходов.
!
! Физика: Тепловой баланс системы "атмосфера — лёд — вода" включает:
!   Q_sw  = SW · (1 - α)          — поглощённая коротковолновая радиация [Вт/м²]
!   Q_lw  = ε · σ · T⁴            — длинноволновое излучение поверхности [Вт/м²]
!   Q_atm = 5.5e-8 · T_a⁴ · (1 + 0.275·C) · (1 - 0.261·e^(-7.77e-4·(273-T_a)²))
!                                        — излучение атмосферы [Вт/м²]
!   Q_sh  = ρ_a · c_p · C_H · V · (T_a - T_s)  — явное тепло [Вт/м²]
!   Q_lh  = ρ_a · L_v · C_E · V · (q_a - q_s)  — скрытое тепло [Вт/м²]
!   T_f   = -54 · S                — точка замерзания по Зубову [°C]
!   fw    = ρ_w · Cp_w · SKT · (T_w - T_f) / dz  — турбулентный поток
!                                                     лёд/вода [Вт/м²]
!
!   Термодинамические постулаты:
!     Зубов: скорость нарастания = Q / (ρ_i · L_f)
!     Стефан: толщина льда Δh = dt/(ρ_i·L_f) · (Q_bottom - Q_top)
!     Скрытая теплота: L_f = 3.34e5 Дж/кг, ρ_i·L_f = 302e6 Дж/м³ (лёд)
!                                    ρ_s·L_f = 110e6 Дж/м³ (снег)
!
!   Температура поверхности льда (T_ts) находится итерационным методом
!   Ньютона-Рафсона из уравнения теплового баланса:
!     4·ε·σ·T³·ΔT = Q_sum - ε·σ·T⁴ + λ·(T_f - T)/h
!   где λ = 2.04/h для чистого льда, λ_eff = 0.6324/(λ_ice·h + λ_snow·hs)
!   для льда со снегом.
!
!   Адвекция снегопада: ERA5 sf [м/с] × dt → приращение толщины снега.
!   Ограничение: hsnow ≤ 0.1 · hice.
!
! Единицы: T [°C] (внутри) и [K] (вradiation-формулах), S [массовая доля],
!          dt [с], h [м], A [доли, 0..1], Q [Вт/м²], fw [Вт/м²].
! Ответственность: Энергетический баланс системы, изменение толщины и сплошности
!                  ледяного покрова за счёт тепловых процессов.
! ==============================================================================

module thermodynamics
    use param
    implicit none

contains

    subroutine heat(dt, nday, lll)
        real, intent(in) :: dt          ! [с] Временной шаг термодинамики (= 3600 с = 1 час)
        integer, intent(in) :: nday     ! Номер дня в месяце (1..31)
        integer, intent(in) :: lll      ! Номер месяца (1..12) — для альбедо снега alsn(lll)

        ! --- Локальные переменные ---
        integer :: i, j, k, k1, n_iter
        real :: dzz, dtz, ttac, tta, ppatm, ratm, twac, twa, hhum, ww, cclo
        real :: a, a1, a2, a3, b, b1, b2, b3, b4, cz, e_vap, sw, wl
        real :: hfirst, ann1, ann2, sh1, el1, aaa, qn, dhsn, dhic1, dhic
        real :: tts, el, hhic1, err, err1, sh, dtts, tti, tfr, fw, tfr_new
        real :: a_tmp, b_tmp, a3_tmp, b3_tmp, a_tmp2, ansum, hour, rad_b1, rad_b2

        ! ====================================================================
        !   ПРЕДВАРИТЕЛЬНЫЕ РАСЧЁТЫ (вынесены из циклов для скорости)
        ! ====================================================================
        ! dzz — толщина верхнего полуслоя [м] (dz1(1) [см] → [м]).
        !   dz1(1) = 25000 см = 250 м, поэтому dzz = 250 м.
        dzz = dz1(1)/100.0
        ! dtz — коэффициент теплового баланса [°C·м²/Дж].
        !   dtz = dt / (dzz · ρ_w · Cp_w)
        !   ρ_w = 1028 кг/м³ — плотность морской воды.
        !   Cp_w = 4186.8 Дж/(кг·К) — удельная теплоёмкость воды.
        !   ρ_w·Cp_w = 4.304e6 Дж/(м³·К) ≈ 4.19e6 Дж/(м³·К).
        !   dtz = 3600 / (250 · 4.19e6) ≈ 3.44e-6 °C·м²/Дж.
        dtz = dt/(dzz*4.19e6)
        hour = 12.0  ! Полдень (UT) для расчёта солнечной радиации [час]

        ! --- ЦИКЛ ПО ГОРИЗОНТАЛЬНОЙ СЕТКЕ (I, J) ---
        do j = 1, js
            do i = 1, is
                ! Пропуск суши и замаскированных ячеек (ans=9.0 = суша)
                if (kt1(i, j) .eq. 0 .or. abs(ans(i, j) - 9.0) .lt. 1e-8) cycle

                ! --- ПОДГОТОВКА МЕТЕОРОЛОГИИ И ОКЕАНА ---
                ttac = tatm(i, j)           ! [°C] Температура воздуха (из ERA5 t2m)
                tta = ttac + 273.15         ! [K]  Температура воздуха (для Stefan-Boltzmann)
                ppatm = patm(i, j)*100.0    ! [Па] Атмосферное давление (из гПа: ×100)
                ratm = ppatm/(287.0*tta)    ! [кг/м³] Плотность воздуха по уравнению состояния
                !   идеального газа: ρ = p/(R·T), R = 287.0 Дж/(кг·К)
                twac = t1(i, j, 1)          ! [°C] Температура поверхности воды (уровень 1)
                twa = twac + 273.15         ! [K]  Температура воды (для radiation-формул)
                hhum = humid(i, j)          ! [доли, 0..1] Относительная влажность (из ERA5)
                ww = wind(i, j)             ! [м/с] Скорость ветра (вычисляется из windx/windy)
                cclo = cloud(i, j)          ! [доли, 0..1] Облачность (из ERA5 tcc)
                a = s1(i, j, 1)             ! [массовая доля] Соленость поверхностного слоя

                ! --- ПОДГОТОВКА МАССИВОВ ЛЬДА ---
                ! Копируем данные из глобальных массивов в рабочие локальные.
                ! anp(hicp/hsnp) = an1/hice/hsnow и изменяются внутри heat().
                do k = 1, ngr
                    anp(k) = an1(i, j, k + 1)      ! [доли] Площадь категории k
                    if (abs(anp(k)) .gt. 1e-8) then
                        ! Толщина льда = объём/площадь [м] (wice1 = A·h)
                        hicp(k) = wice1(i, j, k)/anp(k)
                        hsnp(k) = hsnow(i, j, k)   ! [м] Толщина снега категории k
                    else
                        hicp(k) = 0.0
                        hsnp(k) = 0.0
                    end if
                    spar(k) = a                      ! [массовая доля] Солёность внутри льда
                    tpar(k) = twa                     ! [K] Температура льда ≈ температура воды
                end do

                ! --- ОСНОВНЫЕ РАСЧЁТЫ ДЛЯ СТОЛБЦА ---
                ansum = ans(i, j)              ! [доли] Агрегированная сплошность льда ΣA_k
                tfr = -54.0*spar(1)            ! [°C] Точка замерзания по Зубову: T_f = -54·S
                !   S ≈ 0.034 → T_f ≈ -1.84 °C
                ! fw [Вт/м²] — турбулентный поток тепла между водой и льдом:
                !   fw = ρ_w · Cp_w · SKT · (T_water - T_freeze) / dz
                !   ρ_w = 1028 кг/м³ — плотность морской воды.
                !   Cp_w = 4186.8 Дж/(кг·К) — теплоёмкость.
                !   skt [м²/с] — турбулентный коэффициент обмена (из block 210).
                !   dz(1)*1e-2 [м] — толщина первого слоя (500 м).
                fw = 1028.0*4.1868e3*skt(i, j)*(t1(i, j, 1) - tfr)/(dz(1)*1.0e-2)
                if (fw .le. 0.0) fw = 0.0    ! fw ≥ 0: только нагревание льда снизу
                tfr = tfr + 273.15             ! [K] Точка замерзания в Кельвинах

                ! --- СОЛНЕЧНАЯ РАДИАЦИЯ ---
                ! Шаг 1: Вычисление солнечной высоты и азимута.
                !   fi(i,j) — широта ячейки [градусы], преобразуется в радианы (/57.3).
                !   nday — номер дня в месяце (для склонения Солнца).
                a1 = fi(i, j)/57.3           ! [рад] Широта
                a2 = sin(a1)                 ! sin(φ)
                b2 = cos(a1)                 ! cos(φ)
                ! Склонение Солнца δ [рад]: δ ≈ 23.44°·cos[(172 - nday)/57.3] / 57.3
                !   23.44° — наклон оси Земли, 172 — примерно начало июня (макс. δ).
                !   Деление на 57.3 переводит градусы в радианы.
                b = 23.44*cos((172.0 - nday)/57.3)/57.3
                a3 = sin(b)                  ! sin(δ)
                b3 = cos(b)                  ! cos(δ)

                ! Шаг 2: Косинус зенитного угла μ = cos(θ_z):
                !   μ = sin(φ)·sin(δ) + cos(φ)·cos(δ)·cos(h)
                !   где h = (12 - hour)·π/12 — часовой угол [рад].
                !   0.2617994 = π/12 ≈ 0.2618 [рад/час].
                !   μ ≥ 0 (ночью = 0, нет солнечной радиации).
                cz = max(0.0, a2*a3 + b2*b3*cos((12.0 - hour)*0.2617994))

                ! Шаг 3: Коротковолновая радиация [Вт/м²]:
                !   a1 = S₀·μ²·(1 - 0.6·C³), где S₀ = 1353 Вт/м² (солнечная
                !   постоянная), C — облачность [0..1]. С empirical облачным
                !   коэффициентом 0.6 ( stabilize半夜值).
                a1 = 1353.0*cz*cz*(1.0 - 0.6*cclo**3)
                ! Коэффициенты атмосферного поглощения:
                rad_b1 = (cz + 2.7)*1.0e-5   ! Прозрачность (зависит от μ)
                rad_b2 = 1.085*cz + 0.1       ! Фоновое ослабление
                ! Парциальное давление водяного пара e [Па]:
                !   Формула Тетенса: e = e₀ · 10^(8.61503·T/(T+273.15))
                !   где e₀ = 610.78 Па — давление насыщенного пара при 0°C.
                !   Tta — температура воздуха [K].
                e_vap = hhum*610.78*10.0**(8.61503*(tta - 273.15)/tta)
                ! Итоговая коротковолновая радиация на поверхности [Вт/м²]:
                sw = a1/(rad_b1*e_vap + rad_b2)

                ! Коэффициенты турбулентного обмена (для sensible/latent heat):
                !   b3 = ρ_a · C_H · V — для явного тепла (sensible heat).
                !     C_H ≈ 1.7068e-3 (коэффициент турбулентного обмена тепла).
                !   a3 = ρ_a/p · C_E · V — для скрытого тепла (latent heat).
                !     C_E ≈ 0.665e-3 (коэффициент турбулентного обмена влаги).
                b3 = ratm*1.7068*ww           ! [кг/(м²·с)] С Utf для sensible heat
                a3 = 0.6650735*ratm/ppatm*ww  ! [1/(м·с)] Для latent heat (через q)

                ! Длинноволновая радиация (излучение атмосферы) [Вт/м²]:
                !   wl = ε_a·σ·T_a⁴·(1 + 0.275·C)·(1 - 0.261·exp[-7.77e-4·(273-T_a)²])
                !   ε_a·σ ≈ 5.5e-8 Вт/(м²·К⁴) —effective emissivity × Stefan-Boltzmann.
                !   0.275·C — облачный коэффициент (облака усиливают обратную радиацию).
                !   1 - 0.261·exp[...] — коррекция на влажность (водяной пар — парниковый газ).
            wl = 5.4999e-8*tta**4*(1.0 - 0.261*exp(-7.77e-4*((273.15 - tta)**2)))*(1.0 + 0.275*cclo)

                ! ====================================================================
                !   ПОТОКИ И ОБРАЗОВАНИЕ ЛЬДА (ЧИСТАЯ ВОДА, КАТЕГОРИЯ 0)
                ! ====================================================================
                ! Тепловой баланс открытой воды (land fraction = AN1(:,:,1) = ann1):
                !   Q_net = Q_sh + Q_lw_atm + Q_lw_surface + Q_sw + Q_latent
                ! Положительный Q_net → нагревание воды; отрицательный → замерзание.
                hfirst = 0.0  ! Приращение нового льда [м] (0 = нет образования)
                ann1 = an1(i, j, 1)  ! [доли] Площадь открытой воды

                if (abs(ann1) .gt. 1e-8) then
                    ! --- ЯВНОЕ ТЕПЛО (sensible heat) [Вт/м²] ---
                    !   Q_sh = ρ_a · C_H · V · (T_a - T_w)
                    sh1 = b3*(tta - twa)
                    ! --- СКРЫТОЕ ТЕПЛО (latent heat) [Вт/м²] ---
                    !   Q_lh = (ρ_a/p) · C_E · V · L_v · (q_a - q_w)
                    !   L_v = 2.5e6 Дж/кг — теплота парообразования.
                    !   q = hhum · 10^[8.615·T/(T+273.15)] — удельная влажность
                    !   (формула Тетенса через относительную влажность).
           el1 = a3*2.5e6*(hhum*10.0**(7.63*ttac/(241.9 + ttac)) - 10.0**(7.63*twac/(241.9 + twac)))
                    ! --- ИЗЛУЧЕНИЕ ВОДЫ (surface longwave) [Вт/м²] ---
                    !   Q_lw = -ε_w · σ · T_w⁴, ε_w = 0.97 (эмиссивность воды).
                    aaa = -0.97*5.67e-8*(twa**4)
                    ! --- ЧИСТЫЙ ТЕПЛОВОЙ БАЛАНС ОТКРЫТОЙ ВОДЫ [Вт/м²] ---
                    !   Q_net = Q_sh + Q_lh + ε_a·σ·T_a⁴·(BackColor) + 0.9·SW - ε_w·σ·T_w⁴
                    !   0.9 — альбедо воды для коротковолновой радиации (~0.06-0.10).
                    qn = sh1 + el1 + 0.97*wl + 0.9*sw + aaa

                    if (qn .gt. 0.0) then
                        ! Нагревание воды: ΔT = dtz · A_open · Q_net [°C]
                        !   dtz = dt/(dzz·ρ·Cp) — коэффициент теплового баланса.
                        !   ann1 — доля открытой воды (только она нагревается).
                        tpar(1) = tpar(1) + dtz*ann1*qn
                    else
                        ! Охлаждение воды (без привязки к area — вся вода)
                        tpar(1) = tpar(1) + dtz*qn
                    end if

                    ! Проверка: если T_water упала ниже T_freeze → замерзание
                    if (tpar(1) .ge. tfr) then
                        ! Вода ещё не замерзла: но не может быть теплее воздуха
                        ! при положительном тепловом балансе (ограничение).
                        if (tpar(1) .gt. tta .and. qn .gt. 0.0) tpar(1) = tta
                    else
                        ! Замерзание: фиксируем T = T_freeze, образуем лёд
                        tpar(1) = tfr  ! [K]
                        hfirst = 0.01  ! [м] Начальная толщина нового льда (1 см)
                    end if
                end if

                ! ====================================================================
                !   ТЕРМОДИНАМИКА ЛЬДА (ЦИКЛ ПО КАТЕГОРИЯМ ТОЛЩИН, k=1..NGR)
                ! ====================================================================
                ! Для каждой категории lьда решается:
                !   1. Уравнение теплового баланса на поверхности (метод Ньютона-Рафсона).
                !   2. Нарастание/таяние сверху (из баланса поверхности).
                !   3. Нарастание/таяние снизу (из турбулентного потока fw).
                !   4. Изменение солености при фазовых переходах (солевыделение).
                do k = 1, ngr
                    k1 = k + 1  ! Индекс в AN1/TPAR/SPAR (k+1 = категория k)
                    if (anp(k) .lt. 0.001) cycle  ! Пустая категория (<0.1%) — пропуск

                    dhsn = 0.0       ! [м] Приращение толщины снега за шаг dt
                    dhic1 = 0.0      ! [м] Приращение льда сверху (от radiation)
                    ! tts — начальная оценка температуры поверхности льда [K]:
                    !   Среднее арифметическое T_air и T_water.
                    tts = 0.5*(tta + twa)
                    ! Скрытое тепло для льда/снега [Вт/м²]:
                    !   L_v,ice = 2.834e6 Дж/кг (теплота парообразования со льда).
                    !   q_snow = 10^[9.5·(T-273.15)/(T-7.65)] — формула для снега.
                    !   a3 = (ρ_a/p)·C_E·V — коэффициент турбулентного обмена.
    el = a3*2.834e6*(hhum*10.0**(9.5*ttac/(265.5 + ttac)) - 10.0**(9.5*(tts - 273.15)/(tts - 7.65)))
                    hhic1 = 1.0/max(hicp(k), 1.0e-6) ! [1/м] Обратная толщина (защита от div/0)

                    if (abs(hsnp(k)) .lt. 1e-8) then
                        ! ============================================================
                        !   СЛУЧАЙ 1: ЛЁД БЕЗ СНЕГА
                        ! ============================================================
                        ! Теплопроводность льда: λ_ice = 2.04 Вт/(м·К).
                        !   b = λ_ice / h = 2.04 / h_ice [Вт/(м²·К)].
                        b = 2.04*hhic1
                        err = 100.0    ! Начальная ошибка итерации (большое значение)
                        err1 = 100.0
                        n_iter = 0
                        ! --- Итерационное решение уравнения теплового баланса ---
                        ! Метод Ньютона-Рафсона для T_s (температура поверхности льда):
                        !   Уравнение: 4·ε·σ·T_s³ + λ/h = Q_sum - ε·σ·T_s⁴ + λ·T_f/h
                        !   ΔT = [Q_sum - ε·σ·T_s⁴ + λ/h·(T_f-T_s)] / [4·ε·σ·T_s³ + λ/h]
                        !   где ε·σ ≈ 5.5e-8 для льда (0.97×5.67e-8).
                        !   Сходимость: обычно за 5-10 итераций, критерий |ΔT| < 0.25 K.
                        do while (err .ge. 0.25 .and. n_iter .lt. 100)
                            n_iter = n_iter + 1
                            sh = b3*(tta - tts)  ! [Вт/м²] Sensible heat: ρ·C_H·V·(T_a-T_s)
                            a = 5.4999e-8*tts**3  ! d(εσT⁴)/dT = 4·ε·σ·T³, где εσ = 5.5e-8
                            ! a1 — сумма потоков без длинноволновой составляющей льда:
                            a1 = sh + el + 0.466*sw + 0.97*wl
                            !   0.466 = (1-α_ice)·трансмиссия — доля SW, поглощённая льдом.
                            !   0.97·wl — обратная длинноволновая радиация атмосферы.
                            ! Формула приращения Ньютона-Рафсона:
                            dtts = (a1 - a*tts + b*(tfr - tts))/(4.0*a + b)
                            !   Числитель: Q_net(T_s) = ΣQ - 4εσT⁴ + λ/h·(T_f-T_s)
                            !   Знаменатель: dQ/dT_s = -4εσT³ - λ/h (якобиан).
                            a_tmp = tts + dtts
                            err1 = err
                            err = abs(dtts)  ! |ΔT| [K] — критерий сходимости
                            if (err .ge. err1) exit  ! Дивергентная итерация — выход
                            tts = a_tmp
                        end do
                        ! Fallback: если не сошлось — T_s = T_air
                        if (err .ge. err1 .or. n_iter .eq. 100) tts = tta

                        if (tts .le. 273.15) then
                            ! --- Нарастание снега (T_surface < 0°C) ---
                            ! ERA5 интенсивность снегопада [м/с] × dt [с] = Δh [м].
                            dhsn = dt*era5_snowfall_rate(i, j)
                            hsnp(k) = dhsn
                        else
                            ! --- Таяние льда сверху (T_surface > 0°C) ---
                            ! Фиксируем T_s = 273.15 K (temperaturesurface = 0°C).
                            tts = 273.15
                            ! dhic1 [м] = -dt/(ρ_i·L_f) · Q_net(T_s=0°C)
                            !   ρ_i·L_f = 302e6 Дж/м³ — объёмная теплота плавления льда.
                            dhic1 = -dt/302.e6*(a1 - 5.4999e-8*tts**4 + b*(tfr - tts))
                            hicp(k) = hicp(k) + dhic1
                            if (hicp(k) .lt. 0.01) hicp(k) = 0.0  ! Лёд исчез (<1 см)
                        end if

                        ! --- Нарастание/таяние СНИЗУ (водный поток fw) ---
                        !   Δh_bottom = -dt/(ρ_i·L_f) · [fw - λ/h·(T_f - T_s)]
                        !   fw ≥ 0 (вода нагревает лёд снизу), λ/h·(T_f-T_s) ≤ 0.
                        dhic = -dt/302.e6*(fw - b*(tfr - tts))
                        hicp(k) = hicp(k) + dhic
                        if (hicp(k) .lt. 0.01) then
                            hicp(k) = 0.0   ! Лёд полностью растаял
                            hsnp(k) = 0.0   ! Снег тоже исчезает
                        end if

                    else
                        ! ============================================================
                        !   СЛУЧАЙ 2: ЛЁД СО СНЕГОМ
                        ! ============================================================
                        ! Комбинированная теплопроводность: лёд + снег последовательно.
                        !   λ_ice = 2.04 Вт/(м·К) — теплопроводность льда.
                        !   λ_snow = 0.31 Вт/(м·К) — теплопроводность снега.
                        !   Термическое сопротивление: R = h_ice/λ_ice + h_snow/λ_snow.
                        !   λ_eff = 1/R = 1/(h_ice/2.04 + h_snow/0.31).
                        b1 = 0.31*hicp(k)   ! [м·Вт/(м·К)] = Вт/(К) — вклад льда в R
                        b2 = 2.04*hsnp(k)   ! [Вт/(К)] — вклад снега в R (перевёрнутые λ!)
                        b4 = b1 + b2         ! [Вт/(К)] — суммарное термическое сопротивление
                        b = 0.6324/b4        ! [Вт/(м²·К)] — эффективная теплопроводность
                        !   0.6324 = 2.04 × 0.31 — произведение λ_ice × λ_snow.
                        err = 100.0
                        err1 = 100.0
                        n_iter = 0
                        ! Итерационное решение (метод Ньютона-Рафсона) для T_s.
                        ! Отличие от случая без снега: альbedo снега alsn(lll) и
                        !   другая Stefan-Boltzmann константа для снега (5.6133e-8).
                        do while (err .ge. 0.25 .and. n_iter .lt. 100)
                            n_iter = n_iter + 1
                            sh = b3*(tta - tts)  ! Sensible heat [Вт/м²]
                            a = 5.6133e-8*tts**3  ! 4·ε_snow·σ·T³, ε_snow ≈ 0.99
                            ! a1 — суммарный тепловой баланс поверхности снега:
                            a1 = sh + el + (1.0 - alsn(lll))*sw + 0.99*wl
                            !   (1 - alsn) — доля поглощённой SW (альбедо снега).
                            !   0.99·wl — обратная LW (эмиссивность снега ≈ 0.99).
                            dtts = (a1 - a*tts + b*(tfr - tts))/(4.0*a + b)
                            a_tmp = tts + dtts
                            err1 = err
                            err = abs(dtts)
                            if (err .ge. err1) exit
                            tts = a_tmp
                        end do
                        if (err .ge. err1 .or. n_iter .eq. 100) tts = tta

                        if (tts .le. 273.15) then
                            ! --- Нарастание снега на существующем снеге ---
                            dhsn = era5_snowfall_rate(i, j)*dt  ! [м]
                            ! Температура на границе лёд/снег T_i [K]:
                            !   Взвешенное: T_i = (λ_ice·h_ice·T_s + λ_snow·h_snow·T_f) / (λ_ice·h_ice + λ_snow·h_snow)
                            !   Упрощённо: T_i = (b1·T_s + b2·T_f) / b4
                            tti = (b1*tts + b2*tfr)/b4
                        else
                            ! --- Таяние снега ---
                            tts = 273.15  ! T_surface = 0°C
                            tti = (b1*273.15 + b2*tfr)/b4  ! T на границе лёд/снег
                            ! Таяние снега сверху:
                            !   Δh_snow = -dt/(ρ_s·L_f) · [Q_net(T_s=0) + λ_snow/hsnow·(T_i-T_s)]
                            !   ρ_s·L_f = 110e6 Дж/м³ — объёмная теплота плавления снега.
                            dhsn = -dt/110.e6*(a1 - 5.6133e-8*tts**4 + 0.31/hsnp(k)*(tti - tts))
                        end if

                        ! --- Изменение толщины льда (водный поток + теплопроводность) ---
                        !   Δh_ice = dt/(ρ_i·L_f) · [2.04·(T_f-T_i)/h_ice - fw]
                        !   2.04·(T_f-T_i)/h_ice — тепловой поток от границы лёд/снег к воде.
                        !   fw — турбулентный поток от воды (нагревает лёд снизу).
                        dhic = dt/302.e6*(2.04*(tfr - tti)/hicp(k) - fw)
                        hicp(k) = hicp(k) + dhic
                        if (hicp(k) .ge. 0.01) then
                            ! Ограничение толщины снега: hsnow ≤ 0.1 · hice.
                            ! Физика: снег не может быть толще 10% от льда (для стабильности).
                            a_tmp = 0.1*hicp(k)
                            hsnp(k) = hsnp(k) + dhsn
                            if (hsnp(k) .gt. a_tmp) hsnp(k) = a_tmp
                            if (hsnp(k) .lt. 0.0) hsnp(k) = 0.0
                        else
                            hicp(k) = 0.0   ! Лёд исчез
                            hsnp(k) = 0.0   ! Снег исчезает вместе с льдом
                        end if
                    end if

                    ! ====================================================================
                    !   НОВАЯ ТЕМПЕРАТУРА И СОЛЕНОСТЬ ПОСЛЕ ФАЗОВЫХ ПЕРЕХОДОВ
                    ! ====================================================================
                    ! При таянии (dhic < 0): соль из льда выделяется в воду,
                    !   разбавляя поверхностный слой. При нарастании (dhic > 0):
                    !   соль из воды "замораживается" в лёд.
                    !   0.88 — коэффициент солевыделения (88% соли идёт в воду).
                    !   sicst(k) — критическая солёность категории [массовая доля].
                    !   spar(k+1) — солёность внутри категории k [массовая доля].
                    !   tpar(k+1) — температура внутри категории k [K].
                    !   tfr_new = -54·spar(k+1) — новая точка замерзания [°C].
                    a_tmp = 0.88*dhic      ! [м] Объём льда с солью (88% соли)
                    b_tmp = dzz - a_tmp     ! [м] Эффективная толщина водного слоя
                    if (dhic .lt. 0.0) then
                        ! --- ТАЯНИЕ: соль выделяется из льда в воду ---
                        if (dhsn .lt. 0.0) then
                            ! Таяние снега: добавляем талую воду (солоноватую)
                            a1 = 0.3*dhsn     ! [м] Вклад талой воды
                            b_tmp = b_tmp - a1
                            b1 = 273.15*a1     ! [K·м] Тепло от талой воды (0°C)
                        else
                            b1 = 0.0
                            a1 = 0.0
                        end if
                        ! Новая солёность воды: разбавление за счёт соли из льда
                        spar(k1) = (spar(k1)*(dzz + a_tmp + a1) - sicst(k)*a_tmp)/dzz
                        tfr_new = -54.0*spar(k1) + 273.15  ! [K] Новая T_freeze
                        tpar(k1) = (tfr_new*dzz - b1)/(dzz - a1)
                    else
                        ! --- НАРАСТАНИЕ: соль из воды замораживается в лёд ---
                        spar(k1) = (spar(k1)*dzz - sicst(k)*a_tmp)/b_tmp
                        tfr_new = -54.0*spar(k1) + 273.15  ! [K]
                        tpar(k1) = tfr_new  ! Вода при температуре замерзания
                    end if

                    ! Обновление глобальных массивов
                    hsnow(i, j, k) = hsnp(k)
                    hice(i, j, k) = hicp(k)
                    if (abs(hicp(k)) .lt. 1e-8) then
                        ann1 = ann1 + anp(k)
                        an1(i, j, k1) = 0.0
                        anp(k) = 0.0
                    end if
                end do ! Конец цикла по NGR

                ! ====================================================================
                !   ТАЯНИЕ В РАЗВОДЬЯХ (open-water fraction absorbs heat → melts ice)
                ! ====================================================================
                ! Если есть открытая вода (ann1 > 0 и ann1 < 1) и положительный
                ! тепловой баланс (qn > 0), избыточное тепло передаётся соседним
                ! категориям льда, вызывая их таяние (уменьшение площади).
                ! Тепло: Q = ann1 · qn · dt [Дж/м²] — энергия, доступная для таяния.
                ! Максимальное таяние каждой категории:
                !   ΔA_k = A_k · Q / (ρ_i·L_f·h_k + ρ_s·L_f·hs_k) [доли]
                !   где ρ_i·L_f = 302e6 Дж/м³, ρ_s·L_f = 110e6 Дж/м³.
                if (ann1 .gt. 0.0 .and. ann1 .lt. 1.0 .and. qn .gt. 0.0) then
                    a_tmp = ann1*qn*dt    ! [Дж/м²] Тепло для таяния
                    b_tmp = 0.0           ! Накопленная доля растаявших категорий
                    a3_tmp = 0.0          ! Накопленное A·T для осреднения
                    b3_tmp = 0.0          ! Накопленное A·S для осреднения
                    do k = 1, ngr
                        if (abs(hicp(k)) .gt. 1e-8) then
                            k1 = k + 1
                            ! danp(k) — доля категории, растаявшая за этот шаг.
                            !   Ограничена min(anp(k)) — не может стать отрицательной.
                            danp(k) = min(anp(k), anp(k)*a_tmp/(302.e6*hicp(k) + 110.e6*hsnp(k)))
                            anp(k) = anp(k) - danp(k)   ! Обновление площади
                            b_tmp = b_tmp + danp(k)       ! Суммарная растаявшая доля
                            a3_tmp = a3_tmp + anp(k)*tpar(k1)  ! A·T для осреднения
                            b3_tmp = b3_tmp + anp(k)*spar(k1)  ! A·S для осреднения
                        else
                            danp(k) = 0.0
                        end if
                    end do

                    ! Новая доля открытой воды
                    ann2 = ann1 + b_tmp  ! [доли]
                    a2 = 0.0  ! Накопленное A·T растаявших категорий
                    b2 = 0.0  ! Накопленное A·S растаявших категорий
                    do k = 1, ngr
                        k1 = k + 1
                        tfr_new = -54.0*sicst(k) + 273.15  ! [K] T_freeze
                        a_tmp2 = 0.88*hicp(k)  ! [м] Солёный объём (88% соли в льду)
                        ! a1 — доля растаявшей категории, нормированная на толщину слоя
                        a1 = danp(k)/(a_tmp2 + dzz)
                        ! Распределение тепла и соли от таяния по водному слою
                        a2 = a2 + (tpar(k1)*dzz + tfr_new*a_tmp2)*a1
                        b2 = b2 + (spar(k1)*dzz + sicst(k)*a_tmp2)*a1
                    end do

                    ! Осреднение T и S по всей открытой воде (ann2)
                    tpar(1) = (tpar(1)*ann1 + a2)/ann2
                    spar(1) = (spar(1)*ann1 + b2)/ann2
                    an1(i, j, 1) = ann2
                    t1(i, j, 1) = ann2*tpar(1) + a3_tmp - 273.15  ! [°C]
                    s1(i, j, 1) = ann2*spar(1) + b3_tmp           ! [массовая доля]
                else
                    ! --- Случай: нет таяния в разводьях ---
                    ! Осреднение T и S по всем категориям (взвешенное по площади).
                    a1 = ann1*tpar(1)  ! T·A для открытой воды
                    b1 = ann1*spar(1)  ! S·A для открытой воды
                    do k = 1, ngr
                        k1 = k + 1
                        a1 = a1 + anp(k)*tpar(k1)  ! + T·A для каждой категории
                        b1 = b1 + anp(k)*spar(k1)  ! + S·A для каждой категории
                    end do
                    ! Итоговая T и S поверхностного слоя
                    t1(i, j, 1) = a1 - 273.15  ! [°C] (из K)
                    s1(i, j, 1) = b1           ! [массовая доля]

                    if (hfirst .gt. 0.0) then
                        ! --- Формирование нового льда (hfirst = 0.01 м = 1 см) ---
                        ! Новый лёд добавляется в категорию 1 (самую тонкую).
                        a2 = an1(i, j, 2)  ! Текущая доля категории 1
                        a1 = ann1 + a2      ! Общая доля (открытая вода + категория 1)
                        if (a1 .gt. 0.0) then
                            ! Взвешенное среднее толщины: (0.01·open_water + h_existing·A_existing) / A_total
                            hicp(1) = (0.01*ann1 + hicp(1)*a2)/a1
                        end if
                        an1(i, j, 1) = 0.0    ! Открытая вода исчезла
                        anp(1) = a1            ! Вся доля перешла в категорию 1
                    end if
                end if

                ! --- Обновление глобальных массивов после thermodynamics ---
                do k = 1, ngr
                    hice(i, j, k) = hicp(k)   ! [м] Обновлённая толщина льда
                    hsnow(i, j, k) = hsnp(k)  ! [м] Обновлённая толщина снега
                    an1(i, j, k + 1) = anp(k) ! [доли] Обновлённая доля категории
                    if (abs(anp(k)) .gt. 1e-8) then
                        ! wice1 = h × A — объём льда в категории [м]
                        wice1(i, j, k) = hice(i, j, k)*anp(k)
                    else
                        wice1(i, j, k) = 0.0
                    end if
                end do

            end do
        end do

    end subroutine heat

end module thermodynamics
