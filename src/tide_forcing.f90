! ==============================================================================
! Модуль: tide_forcing (datte)
! Назначение: Расчет астрономических аргументов для генерации приливных волн.
! Физика: Вычисляет начальные фазы и амплитудные множители (f-факторы) для
!         основных гармонических составляющих прилива (M2, S2, K1, O1).
!         Основывается на теории приливов Дудсона.
!         ГЛАВНЫЕ ГАРМОНИКИ:
!           1: M2 (главная полусуточная лунная)  q1 = 28.9841042 °/ч
!           2: S2 (главная полусуточная солнечная) q2 = 30.0 °/ч
!           3: K1 (объявленная суточная)           q3 = 15.041069 °/ч
!           4: O1 (основная суточная лунная)        q4 = 13.943036 °/ч
!         ФАЗЫ (v00) рассчитываются через средние долготы:
!           h  — средняя долгота Солнца;  st — средняя долгота Луны;
!           presh — долгота восходящего узла орбиты Луны.
!         НОДАЛЬНЫЕ ПОПРАВКИ (f-факторы) — учет прецессии орбиты Луны (18.6 лет):
!           fff(1)=M2, fff(2)=S2 (нет поправки = 1.0), fff(3)=K1, fff(4)=O1.
!         Фазы приводятся к диапазону 0-360°.
!         Эпоха отсчета: 1900.0 год (dn = сутки от 1900.0).
! Единицы: углы [градусы], время [сутки], частоты q [°/ч].
! Ответственность: Генерация граничных условий на открытых участках расчетной
!                  области для корректного моделирования приливно-отливных течений.
! ==============================================================================

module tide_forcing
    use param
    implicit none

contains

    subroutine datte()
        ! Локальные переменные
        real :: god, den, hour, gk
        integer :: mes, mu, i, mi, si, nv
        real :: q1, q2, q3, q4, ras, sm, dn, h, st, presh, r
        real :: su, an, bn, cn, dov, doz, dv1, a1n, b1n, c1n, uu1, u3, u4

        ! Перенос параметров из глобального массива NAT
        god = real(nat(1))
        mes = nat(2)
        den = real(nat(3))
        hour = real(nat(4))

        ! Константы приливных гармоник [градусы/час]
        q1 = 28.9841042    ! M2 - главная полусуточная лунная (период ~12.42 ч)
        q2 = 30.0          ! S2 - главная полусуточная солнечная (период = 12 ч)
        q3 = 15.041069     ! K1 - объявленная суточная (период ~23.93 ч)
        q4 = 13.943036     ! O1 - основная суточная лунная (период ~25.82 ч)
        ras = 57.29578     ! 180/pi — перевод радиан в градусы

        ! Расчет количества високосных дней
        gk = god - 1901.0
        sm = 0.0
        mu = mes - 1

        do i = 1, mu
            sm = sm + real(mmm(i))
        end do

        if (mu .eq. 0) sm = 0.0

        mi = int(gk/4.0)
        si = mi*4

        if (abs((gk - real(si)) - 3.0) .lt. 1e-8 .and. mes .gt. 2) then
            sm = sm + 1.0
        end if

        ! Общее время в сутках от 1900.0
        ! Формула: dn = (год-1900)*365 + високосные_годы + сумма_мес + день - 0.5
        ! -0.5: эпоха отсчёта — полдень 1900-01-01 (астрономическая конвенция)
        dn = (god - 1900.0)*365.0 + real(mi) + sm + den - 0.5

        ! Средние долготы (астрономические аргументы) [°]
        ! Вычисляются как полиномы времени dn от эпохи 1900.0:
        !   h     = 279.69668 + 0.98564734*dn  — средняя долгота Солнца [°]
        !   st    = 270.43416 + 13.1763965*dn  — средняя долгота Луны [°]
        !   presh = 334.32956 + 0.1114041*dn   — долгота восходящего узла Луны [°]
        ! Коэффициенты соответствуют астрономическим таблицам Дудсона.
        h = 279.696678 + 0.9856473354*dn      ! Средняя долгота Солнца [°]
        st = 270.434164 + 13.1763965268*dn    ! Средняя долгота Луны [°]
        presh = 334.329556 + 0.1114040803*dn  ! Долгота восходящего узла Луны [°]
        r = presh/ras

        ! Расчет фаз прилива (с выделением дробной части угла)
        ! Формулы астрономических фаз v00(k) [°]:
        !   M2: v00(1) = 2*h - 2*st + q1*hour  (полусуточная лунная)
        !   S2: v00(2) = q2*hour  (полусуточная солнечная; h-аргументы отсутствуют)
        !   K1: v00(3) = h + 90 + q3*hour  (суточная)
        !   O1: v00(4) = h - 2*st + 270 + q4*hour  (суточная лунная)
        ! Приводим к [0,360): делим на 360, берём дробную часть, умножаем на 360.
        v00(1) = (2.0*h - 2.0*st + q1*hour)/360.0
        nv = int(v00(1))
        v00(1) = (v00(1) - real(nv))*360.0

        v00(2) = q2*hour

        v00(3) = (h + 90.0 + q3*hour)/360.0
        nv = int(v00(3))
        v00(3) = (v00(3) - real(nv))*360.0

        v00(4) = (h - 2.0*st + 270.0 + q4*hour)/360.0
        nv = int(v00(4))
        v00(4) = (v00(4) - real(nv))*360.0

        ! Астрономические поправки (для узловых факторов)
        ! su — аргумент широты Луны [рад]: su = (259.183275 - 0.0529539*dn) / (180/pi)
        ! Орбита Луны прецессирует с периодом ~18.6 лет; su отслеживает эту прецессию.
        su = (259.183275 - 0.0529539222*dn)/ras  ! [рад]
        an = sin(su)    ! sin(su)  — для поправок фаз
        bn = sin(2.0*su) ! sin(2*su)
        cn = sin(3.0*su) ! sin(3*su)

        ! Узловые поправки к фазам [°]
        dov = 12.94*an - 1.34*bn + 0.19*cn      ! поправка для M2
        doz = (11.87*an - 1.34*bn + 0.19*cn)*2.0 ! поправка для K1, O1
        dv1 = 8.86*an - 0.68*bn + 0.07*cn       ! поправка для K1

        a1n = cos(su)   ! cos(su)
        b1n = cos(2.0*su) ! cos(2*su)
        c1n = cos(3.0*su) ! cos(3*su)

        uu1 = doz - 2.0*dov   ! узловая поправка M2
        u3 = -dv1              ! узловая поправка K1
        u4 = doz - dov         ! узловая поправка O1

        ! Амплитудные множители (nodal factors f-факторы) [безразмерные]
        ! Корректируют амплитуду каждой гармоники с учётом прецессии орбиты Луны.
        ! f(1)=M2, f(2)=S2 (нет поправки = 1.0), f(3)=K1, f(4)=O1.
        ! Полиномы в cos(su) из теории Дудсона.
        fff(1) = 1.00035 - 0.03733*a1n + 0.00017*b1n + 0.00001*c1n  ! M2
        fff(2) = 1.0       ! S2 (нет поправки, солнечная)
        fff(3) = 1.006 + 0.116*a1n - 0.0088*b1n + 0.0006*c1n       ! K1
        fff(4) = 1.0089 + 0.1871*a1n - 0.0147*b1n + 0.0014*c1n     ! O1

        ! Приведение фаз к диапазону 0-360 и добавление поправок
        if (v00(1) .le. 0.0) v00(1) = v00(1) + 360.0
        if (v00(3) .le. 0.0) v00(3) = v00(3) + 360.0
        if (v00(4) .le. 0.0) v00(4) = v00(4) + 360.0

        v00(1) = v00(1) + uu1
        v00(3) = v00(3) + u3
        v00(4) = v00(4) + u4

    end subroutine datte

end module tide_forcing
